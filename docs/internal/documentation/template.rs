use crate::{Engine, Error, Matrix, Result, matrix};

/// A public semantic value demonstrating OA Rust conventions.
///
/// Clones retain the same Matrix storage. The wrapper preserves its own
/// semantics instead of becoming an alias for Matrix.
#[derive(Clone)]
pub struct ValueTemplate {
	data: Matrix,
	enabled: bool,
}

impl ValueTemplate {
	/// Attach these semantics to an existing Matrix.
	///
	/// # Errors
	///
	/// Returns an error when the Matrix is empty or violates the value's stable
	/// shape, dtype, layout, ownership, or capability contract.
	pub fn new(data: Matrix) -> Result<Self> {
		if data.num_elements() == 0 {
			return Err(Error::invalid_argument(
				"ValueTemplate requires at least one element",
			));
		}

		Ok(Self {
			data,
			enabled: true,
		})
	}

	/// Return the zero-copy Matrix view.
	#[must_use]
	pub const fn as_matrix(&self) -> &Matrix {
		&self.data
	}

	/// Return whether processing is enabled.
	#[must_use]
	pub const fn is_enabled(&self) -> bool {
		self.enabled
	}

	/// Enable or disable processing for subsequent calls.
	pub const fn set_enabled(&mut self, enabled: bool) {
		self.enabled = enabled;
	}

	/// Process this value through the module's canonical operation.
	///
	/// This convenience method delegates to [`process`] and does not introduce a
	/// second validation, graph, synchronization, or lowering path.
	///
	/// # Errors
	///
	/// Returns an error when processing is disabled or the operation cannot be
	/// recorded or executed.
	pub fn process(&self, scale: f32) -> Result<Self> {
		process(self, scale)
	}
}

/// The value and selected index returned by [`process_with_index`].
pub struct ValueTemplateResult {
	/// Processed value.
	pub value: ValueTemplate,

	/// Selected result index.
	pub index: usize,
}

/// Upload host values and attach the module's value semantics.
///
/// This is an explicit host-to-device boundary. The returned value retains the
/// originating Engine's internal lifetime without owning another Engine.
///
/// # Errors
///
/// Returns an error for invalid shape or value counts, checked-size overflow,
/// unsupported capabilities, or device allocation and upload failure.
pub fn from_f32(
	engine: &Engine,
	shape: impl Into<Vec<usize>>,
	values: &[f32],
) -> Result<ValueTemplate> {
	ValueTemplate::new(Matrix::from_f32(engine, shape, values)?)
}

/// Scale one value and preserve its semantic wrapper.
///
/// The operation is stateless. It records through the Engine already associated
/// with `input` and returns without an implicit host wait.
///
/// # Errors
///
/// Returns an error when processing is disabled or Matrix validation,
/// recording, allocation, lowering, or submission fails.
pub fn process(input: &ValueTemplate, scale: f32) -> Result<ValueTemplate> {
	if !input.enabled {
		return Err(Error::failed_precondition(
			"ValueTemplate processing is disabled",
		));
	}

	ValueTemplate::new(matrix::scale(&input.data, scale)?)
}

/// Process one value and return its value-plus-index result.
///
/// # Errors
///
/// Returns the same failures as [`process`].
pub fn process_with_index(input: &ValueTemplate, scale: f32) -> Result<ValueTemplateResult> {
	Ok(ValueTemplateResult {
		value: process(input, scale)?,
		index: 0,
	})
}

