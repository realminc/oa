import os
import importlib.util
import tempfile
import unittest
from pathlib import Path
GENERATOR_PATH = Path(__file__).resolve().parents[5] / "tool/gen/fn/generate.py"
SPEC = importlib.util.spec_from_file_location("oa_fn_publication", GENERATOR_PATH)
GENERATOR = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(GENERATOR)


class PublicationTests(unittest.TestCase):
	def test_repeated_publication_preserves_exact_bytes_and_timestamp(self):
		with tempfile.TemporaryDirectory() as directory:
			root = Path(directory)
			path = root / "src/rs/audio/signal.gen.rs"
			outputs = {path: "// @generated by tool/gen/fn/generate.py; DO NOT EDIT.\n"}
			GENERATOR.publish(outputs, root)
			os.utime(path, ns=(1_000_000_000, 1_000_000_000))
			GENERATOR.publish(outputs, root)
			self.assertEqual(path.stat().st_mtime_ns, 1_000_000_000)
			self.assertEqual(path.read_bytes(), outputs[path].encode())
			self.assertEqual(GENERATOR.check(outputs, root), [])

	def test_orphan_cleanup_covers_rust_tests_and_unsuffixed_slang_only_by_owner(self):
		with tempfile.TemporaryDirectory() as directory:
			root = Path(directory)
			owned = []
			for relative, banner in (
				("src/rs/ml/autograd/obsolete.gen.rs", "// @generated by tool/gen/fn/generate.py; DO NOT EDIT."),
				("test/rs/matrix/obsolete.gen.rs", "// @generated by tool/gen/fn/generate.py; DO NOT EDIT."),
				("src/slang/cryptography/pqc/obsolete.slang", "// Generated by tool/gen/fn/generate.py; do not edit."),
			):
				path = root / relative
				path.parent.mkdir(parents=True, exist_ok=True)
				path.write_text(banner + "\n", encoding="utf-8")
				owned.append(path)
			manual = root / "src/rs/manual.gen.rs"
			manual.write_text("// Manual teaching example\n", encoding="utf-8")
			other = root / "src/rs/other.gen.rs"
			other.write_text("// @generated by tool/gen/shader/generate.py; DO NOT EDIT.\n", encoding="utf-8")
			self.assertEqual(len(GENERATOR.check({}, root)), 3)
			GENERATOR.publish({}, root)
			self.assertTrue(all(not path.exists() for path in owned))
			self.assertTrue(manual.exists())
			self.assertTrue(other.exists())

	def test_missing_and_modified_outputs_are_checked_without_writing(self):
		with tempfile.TemporaryDirectory() as directory:
			root = Path(directory)
			path = root / "test/rs/example.gen.rs"
			self.assertIn("missing", GENERATOR.check({path: "expected\n"}, root)[0])
			path.parent.mkdir(parents=True)
			path.write_bytes(b"expected\r\n")
			self.assertIn("stale", GENERATOR.check({path: "expected\n"}, root)[0])
			self.assertEqual(path.read_bytes(), b"expected\r\n")

	def test_escape_and_symlink_destinations_fail_before_publication(self):
		with tempfile.TemporaryDirectory() as directory:
			root = Path(directory) / "repo"
			root.mkdir()
			valid = root / "src/rs/valid.gen.rs"
			for invalid in (root / "docs/invalid.rs", root / "../escaped.rs", root / "src/rs/../../docs/escaped.rs"):
				with self.assertRaises(ValueError):
					GENERATOR.publish({valid: "valid", invalid: "bad"}, root)
				self.assertFalse(valid.exists())
			(root / "src").mkdir()
			(root / "src/rs").symlink_to(Path(directory), target_is_directory=True)
			with self.assertRaises(ValueError):
				GENERATOR.publish({valid: "bad"}, root)
			self.assertFalse((Path(directory) / "valid.gen.rs").exists())

	def test_ownership_scan_does_not_follow_symlinks(self):
		with tempfile.TemporaryDirectory() as directory:
			root = Path(directory) / "repo"
			outside = Path(directory) / "outside"
			outside.mkdir()
			source = outside / "owned.rs"
			source.write_text("// @generated by tool/gen/fn/generate.py; DO NOT EDIT.\n", encoding="utf-8")
			(root / "src/rs").mkdir(parents=True)
			(root / "src/rs/link").symlink_to(outside, target_is_directory=True)
			(root / "src/rs/file.rs").symlink_to(source)
			GENERATOR.publish({}, root)
			self.assertTrue(source.exists())

	def test_ownership_scan_does_not_follow_top_level_source_symlink(self):
		with tempfile.TemporaryDirectory() as directory:
			root = Path(directory) / "repo"
			outside = Path(directory) / "outside"
			outside.mkdir()
			source = outside / "owned.rs"
			source.write_text("// @generated by tool/gen/fn/generate.py; DO NOT EDIT.\n", encoding="utf-8")
			(root / "src").mkdir(parents=True)
			(root / "src/rs").symlink_to(outside, target_is_directory=True)
			GENERATOR.publish({}, root)
			self.assertTrue(source.exists())
