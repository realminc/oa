class SchemaError(ValueError):
	"""Invalid metadata or unsafe publication destination."""


def require(condition: bool, message: str) -> None:
	if not condition:
		raise SchemaError(message)


def render(template: str, values: dict[str, str]) -> str:
	require(set(TOKEN.findall(template)) == set(values), "template metadata does not match tokens")
	result = TOKEN.sub(lambda match: values[match[1]], template)
	require(not TOKEN.search(result), "unresolved template token")
	return result


def validate(schema: dict) -> None:
	require(isinstance(schema, dict) and set(schema) == {"version", "family", "imports", "helper", "layers"}, "unknown or missing NN schema fields")
	require(type(schema["version"]) is int and schema["version"] == 1, "unsupported NN schema version")
	family = schema["family"]
	require(isinstance(family, str) and family in FAMILIES, "unsupported NN family")
	imports = schema["imports"]
	require(
		isinstance(imports, list) and imports and all(
			isinstance(item, str) and (
				re.fullmatch(r"use [a-zA-Z0-9_: {},]+;", item)
				or (family == "upsample" and item == "pub use super::super::matrix::UpsampleMode;")
			)
			for item in imports
		),
		"invalid imports",
	)
	require(schema["helper"] == ("flatten_dimensions" if family == "utility" else ""), "unexpected helper template")
	layers = schema["layers"]
	require(isinstance(layers, list) and layers, "NN family requires layers")
	require(family != "swiglu" or len(layers) == 1, "Swiglu family owns one shared projection helper set")
	require(family != "attention" or len(layers) == 1, "Attention family owns one policy and mask helper set")
	require(family != "transformer" or len(layers) == 1, "Transformer family owns one shared recipe and child tree")
	require(family != "moe" or len(layers) == 1, "MoE family owns one routing and parameter tree")
	require(family not in {"rnn", "gru"} or len(layers) == 1, "Recurrent family owns one cell and layer helper set")
	require(family != "vq" or len(layers) == 1, "VQ family owns one config and residual helper set")
	require(family != "mamba3" or len(layers) == 1, "Mamba3 family owns one config and explicit state cache")
	require(family != "flow" or len(layers) == 1, "Flow family owns one coherent time, backbone and denoiser set")
	require(family != "empyrealm" or len(layers) == 1, "Empyrealm family owns one embedding and mixer tree")
	names = set()
	for layer in layers:
		require(isinstance(layer, dict) and set(layer) == {"name", "doc", "template", "values", "donor", "adaptation"}, "unknown or missing layer fields")
		name = layer["name"]
		require(isinstance(name, str) and re.fullmatch(r"[A-Z][A-Za-z0-9]*", name) and name not in names, "invalid or duplicate layer name")
		names.add(name)
		for key in ("doc", "donor", "adaptation"):
			require(isinstance(layer[key], str) and layer[key].strip() and "\n" not in layer[key] and "\r" not in layer[key], f"invalid layer {key}")
		donor = Path(layer["donor"])
		require(not donor.is_absolute() and ".." not in donor.parts and donor.as_posix().startswith("source/cpp/lib/oa/ml/nn/"), "invalid donor path")
		kind = layer["template"]
		require(isinstance(kind, str) and kind in FAMILIES[family], "template does not belong to NN family")
		values = layer["values"]
		require(isinstance(values, dict) and set(values) == set(CONTRACTS[kind]), "invalid template values")
		for key, value in values.items():
			value_type = CONTRACTS[kind][key]
			if value_type == "operation":
				allowed = {PROVIDER_ROLES[kind][key]} if kind in PROVIDER_ROLES else OPERATIONS[kind]
				require(isinstance(value, str) and value in allowed, "unsupported operation provider")
			elif value_type == "support_type":
				require(isinstance(value, str) and re.fullmatch(r"[A-Z][A-Za-z0-9]*", value), "invalid supporting type name")
			elif value_type == "upsample_mode":
				require(isinstance(value, str) and value in {"UpsampleMode::Nearest", "UpsampleMode::Bilinear"}, "unsupported interpolation default")
			elif value_type == "parameter_name":
				require(isinstance(value, str) and re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", value), "invalid parameter name")
			elif value_type == "registration_name":
				require(isinstance(value, str) and re.fullmatch(r"[a-z][a-z0-9_]*", value), "invalid registration name")
			else:
				bits = {"i32": 32, "isize": 32, "u64": 64}[value_type]
				low, high = (0, 2**bits - 1) if value_type == "u64" else (-(2**(bits - 1)), 2**(bits - 1) - 1)
				require(type(value) is int and low <= value <= high, f"invalid {value_type} default")
		support_names = [value for key, value in values.items() if CONTRACTS[kind][key] == "support_type"]
		require(len(support_names) == len(set(support_names)) and name not in support_names, "duplicate public NN type within layer")
		require(kind != "attention" or "AttentionMask" not in [name, *support_names], "public NN type collides with private attention support")
		require(kind != "transformer" or not ({name, *support_names} & {"FeedForward", "FeedForwardConfig"}), "public NN type collides with private Transformer support")
		require(kind not in {"rnn", "gru"} or not ({name, *support_names} & {"RnnBias", "RnnLayer", "GruBias", "GruLayer"}), "public NN type collides with private recurrent support")
		require(family != "vq" or not ({name, *support_names} & {"Rc", "DType", "Engine", "Error", "Matrix", "Result", "Module", "ModuleRegistry", "NamedBuffer", "NamedStateU32"}), "public VQ type collides with imported support")
		require(family != "mamba3" or not ({name, *support_names} & {"DType", "Engine", "Error", "Matrix", "Result", "Module", "ModuleRegistry", "Parameter"}), "public Mamba3 type collides with imported support")
		require(family != "flow" or not ({name, *support_names} & {"Cell", "Rc", "DType", "Engine", "Error", "Matrix", "Result", "Module", "ModuleRegistry", "Parameter", "AttentionMode", "LayerNorm", "Linear", "TransformerBlock"}), "public Flow type collides with imported support")
		require(family != "empyrealm" or name not in {"Rc", "DType", "Engine", "Error", "Matrix", "Result", "Module", "ModuleRegistry", "Embedding", "Mamba3", "Mamba3Config", "Mamba3State"}, "Empyrealm type collides with imported support")
		require(family != "byte" or name not in {"Embedding", "Linear"}, "byte layer name collides with imported provider")
		registration_names = [value for key, value in values.items() if key.endswith("_name")]
		require(len(registration_names) == len(set(registration_names)), "duplicate registration name")


def expected_outputs(root: Path, destination: Path) -> dict[Path, str]:
	outputs = {}
	names = set()
	for path in sorted((root / "tool/gen/nn/schema/ml").glob("*.json")):
		schema = json.loads(path.read_text())
		validate(schema)
		family = schema["family"]
		target = destination / f"src/rs/ml/nn/{family}.gen.rs"
		require(target not in outputs, "duplicate NN output family")
		digest = hashlib.sha256(json.dumps(schema, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
		parts = [BANNER, f"// Source: {path.relative_to(root).as_posix()}", f"// generator_version={VERSION}; schema_sha256={digest}", "", "\n\n".join(schema["imports"]), ""]
		for layer in schema["layers"]:
			public_names = [layer["name"], *[value for key, value in layer["values"].items() if CONTRACTS[layer["template"]][key] == "support_type"]]
			for name in public_names:
				require(name not in names, "duplicate public NN type across schemas")
				names.add(name)
			template = (root / f"tool/gen/nn/template/{layer['template']}.rs.in").read_text()
			values = {"name": layer["name"], "doc": layer["doc"], **{key: str(value) for key, value in layer["values"].items()}}
			parts.extend([f"// OA donor: oacpp/{layer['donor']}", f"// Adaptation: {layer['adaptation']}", render(template, values), ""])
		if schema["helper"]:
			parts.append((root / f"tool/gen/nn/template/{schema['helper']}.rs.in").read_text())
		text = "\n".join(parts).rstrip() + "\n"
		result = subprocess.run(["rustfmt", "--edition", "2024", "--config-path", str(root / "rustfmt.toml")], input=text, text=True, capture_output=True, check=False)
		require(result.returncode == 0, f"rustfmt failed: {result.stderr}")
		outputs[target] = result.stdout
	require(outputs, "no NN schemas found")
	return outputs


def owned_outputs(root: Path) -> set[Path]:
	owned = set()
	for parent, directories, files in os.walk(root / "src/rs/ml/nn", followlinks=False):
		directories[:] = [name for name in sorted(directories) if not (Path(parent) / name).is_symlink()]
		for name in sorted(files):
			path = Path(parent) / name
			if path.is_symlink() or path.suffix != ".rs":
				continue
			with path.open() as stream:
				if stream.readline().rstrip() == BANNER:
					owned.add(path)
	return owned


def validate_paths(outputs: dict[Path, str], root: Path) -> None:
	for path in outputs:
		relative = path.absolute().relative_to(root.absolute())
		require(".." not in relative.parts and relative.parts[:4] == ("src", "rs", "ml", "nn"), "output outside NN source tree")
		cursor = root
		for part in relative.parts:
			cursor /= part
			require(not cursor.is_symlink(), "NN output traverses symlink")
		require(path.resolve().is_relative_to(root.resolve()), "NN output escapes destination")


def check(outputs: dict[Path, str], root: Path) -> list[str]:
	validate_paths(outputs, root)
	errors = [f"missing or stale NN output: {path}" for path, content in outputs.items() if not path.is_file() or path.read_text() != content]
	errors.extend(f"orphaned NN output: {path}" for path in sorted(owned_outputs(root) - set(outputs)))
	return errors


def publish(outputs: dict[Path, str], root: Path) -> None:
	validate_paths(outputs, root)
	stale = owned_outputs(root) - set(outputs)
	for path, content in sorted(outputs.items()):
		data = content.encode()
		if path.is_file() and path.read_bytes() == data:
			continue
		# Never overwrite a handwritten or another generator's artifact.
		require(not path.exists() or path in owned_outputs(root), f"NN destination is not owned: {path}")
	for path, content in sorted(outputs.items()):
		data = content.encode()
		if path.is_file() and path.read_bytes() == data:
			continue
		path.parent.mkdir(parents=True, exist_ok=True)
		temporary_path = None
		try:
			with tempfile.NamedTemporaryFile("wb", dir=path.parent, delete=False) as temporary:
				temporary_path = Path(temporary.name)
				temporary.write(data)
			os.replace(temporary_path, path)
		finally:
			if temporary_path is not None:
				temporary_path.unlink(missing_ok=True)
	for path in sorted(stale):
		path.unlink()


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3])
	mode = parser.add_mutually_exclusive_group()
	mode.add_argument("--check", action="store_true")
	mode.add_argument("--live", action="store_true")
	mode.add_argument("--output-dir", type=Path)
	args = parser.parse_args()
	try:
		root = args.root.resolve()
		destination = args.output_dir.absolute() if args.output_dir else root
		outputs = expected_outputs(root, destination)
		if args.check:
			errors = check(outputs, destination)
			for error in errors:
				print(error, file=sys.stderr)
			return int(bool(errors))
		publish(outputs, destination)
		return 0
	except (SchemaError, OSError, ValueError) as error:
		print(f"nn generation: {error}", file=sys.stderr)
		return 1


if __name__ == "__main__":
	raise SystemExit(main())
