#!/usr/bin/env python3
"""
OA neural-network module generation from schema-owned layer contracts.

This is intentionally small: NN layers are public API classes, so the first
slice only generates simple oa::FnMatrix-backed modules where the boilerplate is
mechanical and runtime policy stays inside oa::ExecutionSession and oa::Fn*.
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

REPO_ROOT_PATH = Path(__file__).resolve().parents[3]
if str(REPO_ROOT_PATH) not in sys.path:
	sys.path.insert(0, str(REPO_ROOT_PATH))

from tools.gen.io import writeGeneratedText


REPO_ROOT = Path(__file__).resolve().parents[3]
SCHEMA_DIR = Path(__file__).resolve().parent / "schema"
DEFAULT_OUTPUT = REPO_ROOT / "build" / "gen" / "nn"
LIVE_SOURCE_ROOT = REPO_ROOT / "source" / "cpp"


GEN_HEADER = """// AUTO-GENERATED by tools/gen/nn/generate.py - DO NOT EDIT.
// source of truth: tools/gen/nn/schema/{schema_name}.
// Regenerate via: python3 tools/gen/nn/generate.py --live
"""
GEN_SOURCE_MARKER = "// AUTO-GENERATED by tools/gen/nn/generate.py - DO NOT EDIT."
GEN_CMAKE_MARKER = "# AUTO-GENERATED by tools/gen/nn/generate.py - DO NOT EDIT."


def fail(message: str) -> None:
	print(f"nnGen: ERROR: {message}", file=sys.stderr)
	raise SystemExit(1)


def schemaLabel(schemaPath: Path) -> str:
	try:
		return schemaPath.relative_to(SCHEMA_DIR).as_posix()
	except ValueError:
		return schemaPath.name


def validateLayer(schemaPath: Path, layer: dict) -> None:
	name = layer.get("name")
	if not isinstance(name, str) or not name:
		fail(f"{schemaPath}: layer missing non-empty name")
	if not name[0].isupper() or any(ch == "_" for ch in name):
		fail(f"{schemaPath}:{name}: layer name must be PascalCase")
	if name != "Silu" and any(part in name for part in ("ReLU", "GELU", "SiLU")):
		fail(f"{schemaPath}:{name}: use PascalCase names such as Relu/Gelu/Silu")
	fn = layer.get("fn")
	forwardBody = layer.get("forward_body")
	if (not isinstance(fn, str) or not fn) and (not isinstance(forwardBody, str) or not forwardBody.strip()):
		fail(f"{schemaPath}:{name}: layer missing fn expression or forward_body")
	if "fn" in layer and (not isinstance(fn, str) or not fn):
		fail(f"{schemaPath}:{name}: fn must be a non-empty string")
	if "forward_body" in layer and (not isinstance(forwardBody, str) or not forwardBody.strip()):
		fail(f"{schemaPath}:{name}: forward_body must be a non-empty string")
	if "constructor_args" in layer and not isinstance(layer["constructor_args"], str):
		fail(f"{schemaPath}:{name}: constructor_args must be a string")
	if "constructor_body" in layer and not isinstance(layer["constructor_body"], list):
		fail(f"{schemaPath}:{name}: constructor_body must be a list of strings")
	if "extra_methods" in layer and not isinstance(layer["extra_methods"], str):
		fail(f"{schemaPath}:{name}: extra_methods must be a string containing raw C++ code")
	if "extra_includes" in layer and not isinstance(layer["extra_includes"], str):
		fail(f"{schemaPath}:{name}: extra_includes must be a string containing #include directives")
	headerIncludes = layer.get("header_includes", [])
	if not isinstance(headerIncludes, list) or any(
	 not isinstance(include, str)
	 or not re.fullmatch(r"oa/[A-Za-z0-9_/]+\.h", include)
	 for include in headerIncludes
	):
		fail(f"{schemaPath}:{name}: header_includes must be a list of oa/... .h paths")
	autogradNodeHeader = layer.get("autograd_node_header")
	if autogradNodeHeader is not None:
		if not isinstance(autogradNodeHeader, str) or not re.fullmatch(r"oa/[A-Za-z0-9_/]+\.h", autogradNodeHeader):
			fail(f"{schemaPath}:{name}: autograd_node_header must be an oa/... .h include path")
	if isinstance(forwardBody, str) and "oa::makeShared<oa::Grad" in forwardBody and autogradNodeHeader is None:
		fail(f"{schemaPath}:{name}: custom gradient-node construction requires autograd_node_header")
	path = layer.get("path", name.lower())
	if not isinstance(path, str) or not path or Path(path).is_absolute() or ".." in Path(path).parts:
		fail(f"{schemaPath}:{name}: path must be a safe relative output directory")
	if not re.fullmatch(r"[a-z0-9]+(?:/[a-z0-9]+)*", path):
		fail(f"{schemaPath}:{name}: path components must be lowercase alphanumeric names")
	if Path(path).name != name.lower():
		fail(f"{schemaPath}:{name}: path must end in the lowercase layer name")


def outPaths(layer: dict, outRoot: Path, *, live: bool) -> tuple[Path, Path]:
	layerName = layer["name"]
	# File names follow camelCase convention: first char lowercase.
	fileStem = layerName[0].lower() + layerName[1:]
	pathVal = layer.get("path", layerName.lower())
	pathObj = Path(pathVal)
	dirRelative = Path("oa") / "ml" / "nn" / pathObj
	headerBase = outRoot / "include" / dirRelative
	cppBase = outRoot / "lib" / dirRelative
	return headerBase / f"{fileStem}.h", cppBase / f"{fileStem}.cpp"


def cppParamListWithoutDefaults(params: str) -> str:
	return re.sub(r"\s*=\s*[^,]+", "", params)


def emitHeader(layer: dict, schemaName: str) -> str:
	name = layer["name"]
	# Classes live inside namespace oa with camelCase methods.
	notes = layer.get("notes", "")
	constructor = layer.get("constructor")
	constructorArgs = layer.get("constructor_args")
	constructorExplicit = layer.get("constructor_explicit", False)
	methods = layer.get("methods", [])
	members = layer.get("members", [])
	lines = [GEN_HEADER.format(schema_name=schemaName)]
	lines.append("#pragma once\n")
	lines.append("#include <oa/ml/module.h>")
	for include in layer.get("header_includes", []):
		lines.append(f"#include <{include}>")
	lines.append("")
	lines.append("#include <initializer_list>\n")
	lines.append("namespace oa {")
	lines.append("")
	lines.append(f"/// {name}: {notes}")
	lines.append(f"class {name} : public Module {{")
	lines.append("public:")
	# Emit both default constructor (if specified) and parameterized constructor
	if constructor:
		lines.append(f"\t{constructor}")
	if constructorArgs is not None:
		explicitPrefix = "explicit " if constructorExplicit else ""
		lines.append(f"\t{explicitPrefix}{name}({constructorArgs});")
	elif not constructor:
		lines.append(f"\t{name}() = default;")
	lines.append("\tMatrix forward(const Matrix& inInput) override;")
	for method in methods:
		lines.append(f"\t{method}")
	if members:
		lines.append("")
		lines.append("private:")
		for member in members:
			lines.append(f"\t{member}")
	lines.append("};")
	lines.append("")
	lines.append("} // namespace oa")
	lines.append("")
	return "\n".join(lines)


def emitCpp(layer: dict, schemaName: str) -> str:
	name = layer["name"]
	fn = layer.get("fn")
	forwardBody = layer.get("forward_body")
	notes = layer.get("notes", "")
	constructorArgs = layer.get("constructor_args")
	constructorInit = layer.get("constructor_init", "")
	constructorBody = layer.get("constructor_body", [])
	extraMethods = layer.get("extra_methods", "")
	extraIncludes = layer.get("extra_includes", "")
	constructorDef = ""
	if constructorArgs is not None:
		cppConstructorArgs = cppParamListWithoutDefaults(constructorArgs)
		init = f"\n\t: {constructorInit}" if constructorInit else ""
		bodyLines = "\n".join(f"\t{line}" for line in constructorBody)
		constructorDef = (
		 f"oa::{name}::{name}({cppConstructorArgs})"
		 f"{init} {{\n"
		 f"{bodyLines}\n"
		 "}\n\n"
		)
	if forwardBody is None:
		forwardBody = f"\treturn {fn};\n"
	elif not forwardBody.endswith("\n"):
		forwardBody += "\n"
	bodyConstructsGradNode = "oa::makeShared<oa::Grad" in forwardBody
	autogradInclude = (
	 f"#include <{layer['autograd_node_header']}>\n"
	 if bodyConstructsGradNode else ""
	)

	return (
	 GEN_HEADER.format(schema_name=schemaName)
	 + f"// oa::{name} - {notes}\n\n"
	 + "#include <oa/ml/nn.h>\n"
	 + "#include <oa/core/fnMatrix.h>\n"
	 + autogradInclude
	 + "#include <oa/core/validation.h>\n"
	 + extraIncludes
	 + "\n"
	 + constructorDef
	 + extraMethods
	 + f"oa::Matrix oa::{name}::forward(const oa::Matrix& inInput) {{\n"
	 + forwardBody
	 + "}\n"
	)


def generatedCppBase(outRoot: Path) -> Path:
	return outRoot / "lib" / "oa" / "ml" / "nn"


def generatedHeaderBase(outRoot: Path) -> Path:
	return outRoot / "include" / "oa" / "ml" / "nn"


def emitUmbrella(layers: list[tuple[Path, Path]], outRoot: Path) -> str:
	lines = [GEN_HEADER.format(schema_name="all NN schemas")]
	lines.append("#pragma once\n")
	nnBase = generatedHeaderBase(outRoot)
	for headerPath, _cppPath in layers:
	 # Include path relative to the include/oa/ml/nn root (e.g. "relu/relu.h")
		try:
			rel = headerPath.relative_to(nnBase)
		except ValueError:
			rel = Path(headerPath.name)
		lines.append(f'#include "{rel.as_posix()}"')
	lines.append("")
	return "\n".join(lines)


def emitCmakeSources(
 layers: list[tuple[Path, Path]], outRoot: Path
) -> str:
	lines = [
	 GEN_CMAKE_MARKER,
	 "# Regenerate via: python3 tools/gen/nn/generate.py --live",
	 "",
	 "set(OA_NN_GENERATED_SOURCES",
	]
	for _headerPath, cppPath in layers:
	 # Manifests are reproducible from live and scratch output roots alike.
		rel = Path("source") / "cpp" / cppPath.relative_to(outRoot)
		lines.append(f"\t{rel.as_posix()}")
	lines.append(")")
	lines.append("")
	return "\n".join(lines)


def writeManifestFiles(layers: list[tuple[Path, Path]], outRoot: Path, *, dryRun: bool) -> None:
	umbrellaPath = generatedHeaderBase(outRoot) / "layers.h"
	cmakePath = (
	 REPO_ROOT / "cmake" / "gen" / "nnSources.cmake"
	 if outRoot == LIVE_SOURCE_ROOT
	 else outRoot / "cmake" / "gen" / "nnSources.cmake"
	)
	if dryRun:
		print(f"  would write: {umbrellaPath}")
		print(f"  would write: {cmakePath}")
		return
	writeGeneratedText(umbrellaPath, emitUmbrella(layers, outRoot))
	writeGeneratedText(cmakePath, emitCmakeSources(layers, outRoot))
	legacyUmbrellas = (
	 outRoot / "include" / "oa" / "ml" / "nn.gen.h",
	 generatedHeaderBase(outRoot) / "nn.gen.h",
	 generatedCppBase(outRoot) / "nn.gen.h",
	)
	for legacyUmbrella in legacyUmbrellas:
		if legacyUmbrella != umbrellaPath and legacyUmbrella.exists():
			legacyUmbrella.unlink()
	print(f"  wrote {umbrellaPath.name}, {cmakePath.name}")


def removeStaleOutputs(
 layers: list[tuple[Path, Path]],
 outRoot: Path,
 *,
 dryRun: bool,
) -> None:
	expected = {headerPath for headerPath, _ in layers}
	expected.update(cppPath for _, cppPath in layers)
	expected.add(generatedHeaderBase(outRoot) / "layers.h")

	for base in (generatedHeaderBase(outRoot), generatedCppBase(outRoot)):
		if not base.exists():
			continue
		for candidate in base.rglob("*"):
			if not candidate.is_file() or candidate in expected:
				continue
			try:
				firstLine = candidate.open(encoding="utf-8").readline().rstrip("\r\n")
			except (OSError, UnicodeError):
				continue
			if firstLine not in (GEN_SOURCE_MARKER, GEN_CMAKE_MARKER):
				continue
			if dryRun:
				print(f"  would remove stale: {candidate}")
			else:
				candidate.unlink()
				print(f"  removed stale: {candidate}")


def processSchema(schemaPath: Path, outRoot: Path, *, live: bool, dryRun: bool) -> list[tuple[Path, Path]]:
	with schemaPath.open("rb") as f:
		data = tomllib.load(f)
	layers = data.get("layers", [])
	if not layers:
		fail(f"{schemaPath}: no [[layers]] entries")
	for layer in layers:
		validateLayer(schemaPath, layer)
	schemaName = schemaLabel(schemaPath)
	print(f"nnGen: {schemaPath.name} - {len(layers)} layers")
	result: list[tuple[Path, Path]] = []
	for layer in layers:
		headerPath, cppPath = outPaths(layer, outRoot, live=live)
		result.append((headerPath, cppPath))
		if dryRun:
			print(f"  would write: {headerPath}")
			print(f"  would write: {cppPath}")
			continue
		writeGeneratedText(headerPath, emitHeader(layer, schemaName))
		writeGeneratedText(cppPath, emitCpp(layer, schemaName))
		relativeHeader = headerPath.relative_to(
		 outRoot / "include" / "oa")
		legacyPrivateHeader = outRoot / "lib" / "oa" / relativeHeader
		if legacyPrivateHeader.exists():
			legacyPrivateHeader.unlink()
		print(f"  wrote {headerPath.name}, {cppPath.name}")
	return result


def main() -> int:
	parser = argparse.ArgumentParser(description="Generate oa::Module NN layer wrappers from schema.")
	parser.add_argument("--schema-dir", dest="schemaDir", type=Path, default=SCHEMA_DIR)
	parser.add_argument("--schema", type=Path, default=None)
	parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
	parser.add_argument("--live", action="store_true")
	parser.add_argument("--dry-run", dest="dryRun", action="store_true")
	args = parser.parse_args()
	if args.live and args.schema and not args.dryRun:
		fail("--schema cannot be combined with --live because Layers.h and NnSources.gen.cmake require every schema")

	outRoot = LIVE_SOURCE_ROOT if args.live else args.out
	if args.live:
		print("nnGen: LIVE MODE - updating generated source artifacts")
	schemas = [args.schema] if args.schema else sorted(args.schemaDir.rglob("*.toml"))
	if not schemas:
		fail(f"no schemas found in {args.schemaDir}")
	layers: list[tuple[Path, Path]] = []
	for schemaPath in schemas:
		layers.extend(processSchema(schemaPath, outRoot, live=args.live, dryRun=args.dryRun))
	print(f"nnGen: generated NN manifest - {len(layers)} layers")
	writeManifestFiles(layers, outRoot, dryRun=args.dryRun)
	if args.schema is None:
		removeStaleOutputs(layers, outRoot, dryRun=args.dryRun)
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
