def emitCoopCmake(families: list[CoopFamily], schemaRel: str) -> str:
	lines = ["# AUTO-GENERATED by tools/gen/tile/generate.py -- DO NOT EDIT.",
	 f"# Source of truth: {schemaRel}", ""]
	for family in families:
		var = "OA_GEMM_BF16_VARIANTS" if family.template == "GemmCmSgBf16" else "OA_GEMM_WG_BF16_VARIANTS"
		lines.append(f"set({var}")
		for variant in family.variants:
			lines.append(f'\t"{variant.name}" "{variant.act}"')
		lines.append(")")
	return "\n".join(lines) + "\n"


def emitCoopRows(families: list[CoopFamily], schemaRel: str) -> str:
	lines = generatedHeader(schemaRel)
	for family in families:
		for variant in family.variants:
			ep, bias, activation, dual = COOP_EPILOGUES[variant.kind]
			lines.extend([
			 f'\t{{oa::matmulVariantIdFromName("{variant.name}"), "{variant.name}",',
			 f"\t oa::GemmKernel::{family.kernel}, oa::GemmPath::Standard, oa::GemmEpilogue::{ep},",
			 "\t oa::StoragePrecision::Bf16, oa::StoragePrecision::Bf16,",
			 "\t oa::StoragePrecision::Fp32, oa::StoragePrecision::Fp32,",
			 f"\t {family.tileM}, {family.tileN}, {family.tileK}, {family.workgroup},",
			 f"\t false, true, {str(bias).lower()}, {str(activation).lower()}, {str(dual).lower()}, 0,",
			 f"\t {family.caps}}},", ""])
	if lines and lines[-1] == "":
		lines.pop()
	return "\n".join(lines) + "\n"


