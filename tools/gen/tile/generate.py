@dataclass(frozen=True)
class Epilogue:
	kind: str
	name: str
	localId: int


@dataclass(frozen=True)
class Variant:
	name: str
	localId: int
	tileM: int
	tileN: int
	tileK: int
	threadM: int
	threadN: int
	workgroup: int
	groupM: int
	strided: bool
	epilogues: tuple[Epilogue, ...]

	@property
	def sharedBytes(self) -> int:
		return (self.tileM + self.tileN) * (self.tileK + 1) * 4


@dataclass(frozen=True)
class CompiledVariant:
	name: str
	localId: int
	geometry: Variant
	epilogue: str


@dataclass(frozen=True)
class SmallMVariant:
	name: str
	localId: int
	outputsPerGroup: int
	reductionWidth: int
	workgroup: int
	maxM: int
	epilogues: tuple[Epilogue, ...]

	@property
	def sharedBytes(self) -> int:
		return self.workgroup * 4


@dataclass(frozen=True)
class CompiledSmallMVariant:
	name: str
	localId: int
	geometry: SmallMVariant
	epilogue: str


@dataclass(frozen=True)
class BaseVariant:
	name: str
	source: str
	compileGroup: str
	localId: int
	publicId: bool
	kernel: str
	path: str
	precisions: tuple[str, str, str, str]
	tileM: int
	tileN: int
	tileK: int
	workgroup: int
	requiresAligned: bool
	requiresTransposedB: bool
	supportsBias: bool
	supportsActivation: bool
	dualOutput: bool
	sharedBytes: int
	caps: str
	supportsArbitraryLayout: bool
	supportsBatch: bool


@dataclass(frozen=True)
class CoopVariant:
	name: str
	kind: str
	act: int


@dataclass(frozen=True)
class CoopFamily:
	template: str
	kernel: str
	tileM: int
	tileN: int
	tileK: int
	workgroup: int
	caps: str
	variants: tuple[CoopVariant, ...]


EPILOGUES = {
 "none": ("None", False, False),
 "bias": ("Bias", True, False),
 "bias_relu": ("BiasRelu", True, True),
 "bias_gelu": ("BiasGelu", True, True),
 "bias_silu": ("BiasSilu", True, True),
}

COOP_EPILOGUES = {
 "none": ("None", False, False, False),
 "bias": ("Bias", True, False, False),
 "bias_relu": ("BiasRelu", True, True, False),
 "bias_gelu": ("BiasGelu", True, True, False),
 "silu_dual": ("SiluDual", False, True, True),
 "bias_silu": ("BiasSilu", True, True, False),
}

BASE_COMPILE_GROUPS = {"standard", "coopvec"}
BASE_KERNELS = {"Naive", "StridedFp32", "CoopVec"}
BASE_PATHS = {"Standard", "CoopVec"}
BASE_PRECISIONS = {"Fp32", "Bf16"}


def loadBaseSchema(path: Path) -> tuple[int, int, list[BaseVariant], int]:
	rawBytes = path.read_bytes()
	data = tomllib.loads(rawBytes.decode("utf-8"))
	version = int(data.get("schema_version", 0))
	abi = int(data.get("generator_abi", 0))
	if version != 1 or abi <= 0:
		fail("unsupported base matmul schema contract")
	variants: list[BaseVariant] = []
	for index, item in enumerate(data.get("variant", [])):
		ctx = f"variant[{index}]"
		name = str(item.get("name", ""))
		source = str(item.get("source", ""))
		compileGroup = str(item.get("compile_group", ""))
		precisions = tuple(map(str, item.get("precisions", [])))
		tile = tuple(map(int, item.get("tile", [])))
		if not name or not name.replace("_", "").isalnum() or not name[0].isalpha():
			fail(f"{ctx}: invalid name {name!r}")
		if compileGroup not in BASE_COMPILE_GROUPS:
			fail(f"{ctx}: invalid compile_group {compileGroup!r}")
		expectedPrefix = "gemm/" if compileGroup == "standard" else "util/"
		expectedBasename = name[0].lower() + name[1:]
		if (not source.startswith(expectedPrefix)
		  or source.split("/")[-1] != expectedBasename):
			fail(f"{ctx}: source must be {expectedPrefix}{expectedBasename}")
		if len(precisions) != 4 or any(p not in BASE_PRECISIONS for p in precisions):
			fail(f"{ctx}: precisions must contain four supported storage types")
		if len(tile) != 3 or min(tile) <= 0:
			fail(f"{ctx}: tile must contain three positive values")
		variant = BaseVariant(
		 name=name,
		 source=source,
		 compileGroup=compileGroup,
		 localId=int(item.get("local_id", 0)),
		 publicId=bool(item.get("public_id", False)),
		 kernel=str(item.get("kernel", "")),
		 path=str(item.get("path", "")),
		 precisions=precisions,  # type: ignore[arg-type]
		 tileM=tile[0], tileN=tile[1], tileK=tile[2],
		 workgroup=int(item.get("workgroup", 0)),
		 requiresAligned=bool(item.get("requires_aligned", False)),
		 requiresTransposedB=bool(item.get("requires_transposed_b", False)),
		 supportsBias=bool(item.get("supports_bias", False)),
		 supportsActivation=bool(item.get("supports_activation", False)),
		 dualOutput=bool(item.get("dual_output", False)),
		 sharedBytes=int(item.get("shared_bytes", 0)),
		 caps=str(item.get("caps", "")),
		 supportsArbitraryLayout=bool(item.get("supports_arbitrary_layout", False)),
		 supportsBatch=bool(item.get("supports_batch", False)),
		)
		if variant.localId <= 0 or variant.workgroup <= 0 or variant.sharedBytes < 0:
			fail(f"{ctx}: ID/workgroup must be positive and shared_bytes non-negative")
		if variant.kernel not in BASE_KERNELS or variant.path not in BASE_PATHS or not variant.caps:
			fail(f"{ctx}: invalid kernel, path or capability contract")
		variants.append(variant)
	if not variants:
		fail("base matmul schema contains no variants")
	if len({v.name for v in variants}) != len(variants):
		fail("duplicate base variant name")
	if len({v.localId for v in variants}) != len(variants):
		fail("duplicate base local_id")
	schemaHash = int.from_bytes(hashlib.sha256(rawBytes).digest()[:8], "little")
	return version, abi, variants, schemaHash


def loadCoopSchema(path: Path) -> tuple[int, int, list[CoopFamily], int]:
	rawBytes = path.read_bytes()
	data = tomllib.loads(rawBytes.decode("utf-8"))
	version = int(data.get("schema_version", 0))
	abi = int(data.get("generator_abi", 0))
	if version != 1 or abi <= 0:
		fail("unsupported BF16 cooperative-matrix schema contract")
	families: list[CoopFamily] = []
	allNames: set[str] = set()
	for index, item in enumerate(data.get("family", [])):
		tile = item.get("tile", [])
		if len(tile) != 3 or min(map(int, tile)) <= 0:
			fail(f"family[{index}]: tile must contain three positive values")
		variants: list[CoopVariant] = []
		for raw in item.get("variants", []):
			kind, name, act = str(raw.get("kind", "")), str(raw.get("name", "")), int(raw.get("act", -1))
			if kind not in COOP_EPILOGUES or not name or act < 0:
				fail(f"family[{index}]: invalid BF16 variant")
			if name in allNames:
				fail(f"duplicate BF16 variant name {name}")
			allNames.add(name)
			variants.append(CoopVariant(name, kind, act))
		family = CoopFamily(
		 template=str(item.get("template", "")), kernel=str(item.get("kernel", "")),
		 tileM=int(tile[0]), tileN=int(tile[1]), tileK=int(tile[2]),
		 workgroup=int(item.get("workgroup", 0)), caps=str(item.get("caps", "")),
		 variants=tuple(variants))
		if not family.template or not family.kernel or not family.caps or family.workgroup <= 0 or not variants:
			fail(f"family[{index}]: incomplete BF16 family")
		families.append(family)
	if not families:
		fail("BF16 schema contains no families")
	schemaHash = int.from_bytes(hashlib.sha256(rawBytes).digest()[:8], "little")
	return version, abi, families, schemaHash


def compiledVariants(variants: list[Variant]) -> list[CompiledVariant]:
	result: list[CompiledVariant] = []
	for variant in variants:
		result.append(CompiledVariant(
		 name=variant.name, localId=variant.localId,
		 geometry=variant, epilogue="none"))
		result.extend(CompiledVariant(
		 name=epilogue.name, localId=epilogue.localId,
		 geometry=variant, epilogue=epilogue.kind)
		 for epilogue in variant.epilogues)
	return result


def compiledSmallMVariants(
 variants: list[SmallMVariant],
) -> list[CompiledSmallMVariant]:
	result: list[CompiledSmallMVariant] = []
	for variant in variants:
		result.append(CompiledSmallMVariant(
		 name=variant.name, localId=variant.localId,
		 geometry=variant, epilogue="none"))
		result.extend(CompiledSmallMVariant(
		 name=epilogue.name, localId=epilogue.localId,
		 geometry=variant, epilogue=epilogue.kind)
		 for epilogue in variant.epilogues)
	return result


def fail(message: str) -> None:
	raise ValueError(message)


def loadSchema(path: Path) -> tuple[int, int, list[Variant], int]:
	rawBytes = path.read_bytes()
	data = tomllib.loads(rawBytes.decode("utf-8"))
	schemaVersion = int(data.get("schema_version", 0))
	generatorAbi = int(data.get("generator_abi", 0))
	if schemaVersion != 1:
		fail(f"unsupported schema_version={schemaVersion}")
	if generatorAbi <= 0:
		fail("generator_abi must be positive")

	variants: list[Variant] = []
	for index, item in enumerate(data.get("variant", [])):
		ctx = f"variant[{index}]"
		baseName = str(item.get("name", ""))
		if not baseName or not baseName.replace("_", "").isalnum() or not baseName[0].isalpha():
			fail(f"{ctx}: invalid C++/shader name {baseName!r}")
		tile = item.get("tile", [])
		threadTile = item.get("thread_tile", [])
		if len(tile) != 3 or len(threadTile) != 2:
			fail(f"{ctx}: tile must have 3 values and thread_tile 2")
		epilogues: list[Epilogue] = []
		for epilogueIndex, epilogueItem in enumerate(item.get("epilogues", [])):
			ectx = f"{ctx}.epilogues[{epilogueIndex}]"
			kind = str(epilogueItem.get("kind", ""))
			epilogueName = str(epilogueItem.get("name", ""))
			localId = int(epilogueItem.get("local_id", 0))
			if kind == "none" or kind not in EPILOGUES:
				fail(f"{ectx}: unsupported epilogue kind {kind!r}")
			if not epilogueName or not epilogueName.replace("_", "").isalnum() or not epilogueName[0].isalpha():
				fail(f"{ectx}: invalid C++/shader name {epilogueName!r}")
			if localId <= 0:
				fail(f"{ectx}: local_id must be positive")
			epilogues.append(Epilogue(kind=kind, name=epilogueName, localId=localId))
		v = Variant(
		 name=baseName,
		 localId=int(item.get("local_id", 0)),
		 tileM=int(tile[0]), tileN=int(tile[1]), tileK=int(tile[2]),
		 threadM=int(threadTile[0]), threadN=int(threadTile[1]),
		 workgroup=int(item.get("workgroup", 0)),
		 groupM=int(item.get("group_m", 0)),
		 strided=bool(item.get("strided", False)),
		 epilogues=tuple(epilogues),
		)
		if min(v.localId, v.tileM, v.tileN, v.tileK,
		       v.threadM, v.threadN, v.workgroup) <= 0 or v.groupM < 0:
			fail(f"{ctx}: dimensions/IDs must be positive and group_m non-negative")
		if v.tileM % v.threadM or v.tileN % v.threadN:
			fail(f"{ctx}: tile must divide evenly into thread_tile")
		threads = (v.tileM // v.threadM) * (v.tileN // v.threadN)
		if threads != v.workgroup:
			fail(f"{ctx}: thread grid requires {threads}, schema says {v.workgroup}")
		for label, elements in (("A", v.tileM * v.tileK), ("B", v.tileN * v.tileK)):
			if elements % (v.workgroup * 4):
				fail(f"{ctx}: {label} tile cannot be distributed as float4 loads")
		if v.tileK % 4:
			fail(f"{ctx}: tile_k must be a multiple of four")
		if v.strided and v.epilogues:
			fail(f"{ctx}: strided variants do not yet admit fused epilogues")
		variants.append(v)

	if not variants:
		fail("schema contains no variants")
	compiled = compiledVariants(variants)
	if len({v.name for v in compiled}) != len(compiled):
		fail("duplicate variant name")
	if len({v.localId for v in compiled}) != len(compiled):
		fail("duplicate local_id")
	schemaHash = int.from_bytes(hashlib.sha256(rawBytes).digest()[:8], "little")
	return schemaVersion, generatorAbi, variants, schemaHash


def loadSmallMSchema(
 path: Path,
) -> tuple[int, int, list[SmallMVariant], int]:
	rawBytes = path.read_bytes()
	data = tomllib.loads(rawBytes.decode("utf-8"))
	version = int(data.get("schema_version", 0))
	abi = int(data.get("generator_abi", 0))
	if version != 1 or abi <= 0:
		fail("unsupported small-M matmul schema contract")

	variants: list[SmallMVariant] = []
	for index, item in enumerate(data.get("variant", [])):
		ctx = f"variant[{index}]"
		name = str(item.get("name", ""))
		if not name or not name.replace("_", "").isalnum() or not name[0].isalpha():
			fail(f"{ctx}: invalid small-M variant name {name!r}")
		epilogues: list[Epilogue] = []
		for epilogueIndex, epilogueItem in enumerate(item.get("epilogues", [])):
			ectx = f"{ctx}.epilogues[{epilogueIndex}]"
			kind = str(epilogueItem.get("kind", ""))
			epilogueName = str(epilogueItem.get("name", ""))
			localId = int(epilogueItem.get("local_id", 0))
			if kind == "none" or kind not in EPILOGUES:
				fail(f"{ectx}: unsupported epilogue kind {kind!r}")
			if (not epilogueName
			 or not epilogueName.replace("_", "").isalnum()
			 or not epilogueName[0].isalpha()
			 or localId <= 0):
				fail(f"{ectx}: invalid name or local_id")
			epilogues.append(Epilogue(kind, epilogueName, localId))
		variant = SmallMVariant(
		 name=name,
		 localId=int(item.get("local_id", 0)),
		 outputsPerGroup=int(item.get("outputs_per_group", 0)),
		 reductionWidth=int(item.get("reduction_width", 0)),
		 workgroup=int(item.get("workgroup", 0)),
		 maxM=int(item.get("max_m", 0)),
		 epilogues=tuple(epilogues),
		)
		if min(variant.localId, variant.outputsPerGroup,
		       variant.reductionWidth, variant.workgroup, variant.maxM) <= 0:
			fail(f"{ctx}: dimensions and IDs must be positive")
		if variant.reductionWidth & (variant.reductionWidth - 1):
			fail(f"{ctx}: reduction_width must be a power of two")
		if variant.workgroup != (
		 variant.outputsPerGroup * variant.reductionWidth
		):
			fail(f"{ctx}: workgroup must equal outputs_per_group * reduction_width")
		if variant.workgroup > 1024:
			fail(f"{ctx}: workgroup exceeds the Vulkan maximum")
		variants.append(variant)
	if not variants:
		fail("small-M matmul schema contains no variants")
	compiled = compiledSmallMVariants(variants)
	if len({v.name for v in compiled}) != len(compiled):
		fail("duplicate small-M variant name")
	if len({v.localId for v in compiled}) != len(compiled):
		fail("duplicate small-M local_id")
	schemaHash = int.from_bytes(hashlib.sha256(rawBytes).digest()[:8], "little")
	return version, abi, variants, schemaHash


def generatedHeader(schemaRel: str) -> list[str]:
	return [MARKER, f"// Source of truth: {schemaRel}", ""]


def generatedHeaderMany(schemaRels: tuple[str, ...]) -> list[str]:
	return [MARKER, "// Sources of truth:", *(f"// - {path}" for path in schemaRels), ""]


def emitBaseCmake(variants: list[BaseVariant], schemaRel: str) -> str:
	lines = [
	 "# AUTO-GENERATED by tools/gen/tile/generate.py -- DO NOT EDIT.",
	 f"# Source of truth: {schemaRel}",
	 "",
	]
	for group, variable in (
	 ("standard", "OA_BLAS_GEMM_KERNEL"),
	 ("coopvec", "OA_BLAS_UTIL_KERNEL"),
	):
		groupVariants = [v for v in variants if v.compileGroup == group]
		lines.append(f"set({variable}_NAMES")
		lines.extend(f"\t{v.name}" for v in groupVariants)
		lines.append(")")
		lines.append(f"set({variable}_SOURCES")
		lines.extend(f"\t{v.source}" for v in groupVariants)
		lines.append(")")
	return "\n".join(lines) + "\n"


def emitCmake(variants: list[Variant], schemaRel: str) -> str:
	lines = [
	 "# AUTO-GENERATED by tools/gen/tile/generate.py -- DO NOT EDIT.",
	 f"# Source of truth: {schemaRel}",
	 "",
	]
	compiled = compiledVariants(variants)
	fields = {
	 "NAMES": [v.name for v in compiled],
	 "IDS": [str(v.localId) for v in compiled],
	 "TILE_M": [str(v.geometry.tileM) for v in compiled],
	 "TILE_N": [str(v.geometry.tileN) for v in compiled],
	 "TILE_K": [str(v.geometry.tileK) for v in compiled],
	 "THREAD_M": [str(v.geometry.threadM) for v in compiled],
	 "THREAD_N": [str(v.geometry.threadN) for v in compiled],
	 "WORKGROUP": [str(v.geometry.workgroup) for v in compiled],
	 "GROUP_M": [str(v.geometry.groupM) for v in compiled],
	 "STRIDED": ["1" if v.geometry.strided else "0" for v in compiled],
	 "EPILOGUE": [str(list(EPILOGUES).index(v.epilogue)) for v in compiled],
	}
	for suffix, values in fields.items():
		lines.append(f"set(OA_TILE_FP32_{suffix}")
		lines.extend(f"\t{value}" for value in values)
		lines.append(")")
	return "\n".join(lines) + "\n"


