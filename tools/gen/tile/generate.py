def emitKernelRows(
 variants: list[Variant], smallMVariants: list[SmallMVariant],
 baseVariants: list[BaseVariant], schemaRels: tuple[str, str, str],
) -> str:
	lines = generatedHeaderMany(schemaRels)
	for v in baseVariants:
		lines.append(
		 f'\t{{ "{v.name}", OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::Ml, '
		 f'{v.localId}), oa::ComputeKernelCategory::Ml, "oa" }},')
	for v in compiledVariants(variants):
		lines.append(
		 f'\t{{ "{v.name}", OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::Ml, '
		 f'{v.localId}), oa::ComputeKernelCategory::Ml, "oa" }},')
	for v in compiledSmallMVariants(smallMVariants):
		lines.append(
		 f'\t{{ "{v.name}", OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::Ml, '
		 f'{v.localId}), oa::ComputeKernelCategory::Ml, "oa" }},')
	return "\n".join(lines) + "\n"


def emitComputeIds(
 variants: list[Variant], smallMVariants: list[SmallMVariant],
 baseVariants: list[BaseVariant], schemaRels: tuple[str, str, str],
) -> str:
	lines = generatedHeaderMany(schemaRels)
	for v in baseVariants:
		if v.publicId:
			lines.append(
			 f"static constexpr oa::U64 {v.name} = "
			 f"OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::Ml, {v.localId});")
	for v in compiledVariants(variants):
		lines.append(
		 f"static constexpr oa::U64 {v.name} = "
		 f"OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::Ml, {v.localId});")
	for v in compiledSmallMVariants(smallMVariants):
		lines.append(
		 f"static constexpr oa::U64 {v.name} = "
		 f"OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::Ml, {v.localId});")
	return "\n".join(lines) + "\n"


def validateCombinedKernelIdentities(
 baseVariants: list[BaseVariant], variants: list[Variant],
 smallMVariants: list[SmallMVariant],
) -> None:
	records = [
	 *((v.name, v.localId) for v in baseVariants),
	 *((v.name, v.localId) for v in compiledVariants(variants)),
	 *((v.name, v.localId) for v in compiledSmallMVariants(smallMVariants)),
	]
	for fieldIndex, label in ((0, "name"), (1, "local_id")):
		values = [record[fieldIndex] for record in records]
		if len(set(values)) != len(values):
			fail(f"duplicate OaTile {label} across generated manifests")


def emitBaseRows(variants: list[BaseVariant], schemaRel: str) -> str:
	lines = generatedHeader(schemaRel)
	for v in variants:
		a, b, output, accumulator = v.precisions
		lines.extend([
		 f'\t{{oa::matmulVariantIdFromName("{v.name}"), "{v.name}",',
		 f"\t oa::GemmKernel::{v.kernel}, oa::GemmPath::{v.path}, oa::GemmEpilogue::None,",
		 f"\t oa::StoragePrecision::{a}, oa::StoragePrecision::{b},",
		 f"\t oa::StoragePrecision::{output}, oa::StoragePrecision::{accumulator},",
		 f"\t {v.tileM}, {v.tileN}, {v.tileK}, {v.workgroup},",
		 f"\t {str(v.requiresAligned).lower()}, {str(v.requiresTransposedB).lower()}, "
		 f"{str(v.supportsBias).lower()}, {str(v.supportsActivation).lower()}, "
		 f"{str(v.dualOutput).lower()}, {v.sharedBytes},",
		 f"\t {v.caps}, {str(v.supportsArbitraryLayout).lower()}, "
		 f"{str(v.supportsBatch).lower()}}},",
		 "",
		])
	if lines and lines[-1] == "":
		lines.pop()
	return "\n".join(lines) + "\n"


def emitMatmulRows(variants: list[Variant], schemaRel: str) -> str:
	lines = generatedHeader(schemaRel)
	for v in compiledVariants(variants):
		epName, supportsBias, supportsActivation = EPILOGUES[v.epilogue]
		geometry = v.geometry
		kernel = "StridedTiledFp32" if geometry.strided else "TiledFp32"
		lines.extend([
		 f'\t{{oa::matmulVariantIdFromName("{v.name}"), "{v.name}",',
		 f"\t oa::GemmKernel::{kernel}, oa::GemmPath::Standard, oa::GemmEpilogue::{epName},",
		 "\t oa::StoragePrecision::Fp32, oa::StoragePrecision::Fp32,",
		 "\t oa::StoragePrecision::Fp32, oa::StoragePrecision::Fp32,",
		 f"\t {geometry.tileM}, {geometry.tileN}, {geometry.tileK}, {geometry.workgroup},",
		 f"\t false, {str(not geometry.strided).lower()}, {str(supportsBias).lower()}, "
		 f"{str(supportsActivation).lower()}, false, {geometry.sharedBytes},",
		 f"\t kCapTiledFp32, {str(geometry.strided).lower()}, "
		 f"{str(geometry.strided).lower()}}},",
		 "",
		])
	if lines and lines[-1] == "":
		lines.pop()
	return "\n".join(lines) + "\n"


