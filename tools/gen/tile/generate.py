def write(path: Path, content: str, dryRun: bool) -> None:
	if dryRun:
		print(path)
		return
	writeGeneratedText(path, content)
	print(f"wrote {path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path}")


def main() -> int:
	parser = argparse.ArgumentParser(description="Generate OaTile matmul variants")
	parser.add_argument("--schema", type=Path, default=SCHEMA)
	parser.add_argument("--bf16-schema", dest="bf16Schema", type=Path, default=BF16_SCHEMA)
	parser.add_argument("--base-schema", dest="baseSchema", type=Path, default=BASE_SCHEMA)
	parser.add_argument("--small-m-schema", dest="smallMSchema", type=Path, default=SMALL_M_SCHEMA)
	parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
	parser.add_argument("--live", action="store_true", help="write generated files into the repo Source tree")
	parser.add_argument("--dry-run", dest="dryRun", action="store_true")
	args = parser.parse_args()
	out = REPO_ROOT if args.live else args.out.resolve()
	schema = args.schema.resolve()
	schemaVersion, generatorAbi, variants, schemaHash = loadSchema(schema)
	schemaRel = schema.relative_to(REPO_ROOT).as_posix()
	bf16Schema = args.bf16Schema.resolve()
	bf16Version, bf16Abi, bf16Families, bf16Hash = loadCoopSchema(bf16Schema)
	bf16Rel = bf16Schema.relative_to(REPO_ROOT).as_posix()
	baseSchema = args.baseSchema.resolve()
	baseVersion, baseAbi, baseVariants, baseHash = loadBaseSchema(baseSchema)
	baseRel = baseSchema.relative_to(REPO_ROOT).as_posix()
	smallMSchema = args.smallMSchema.resolve()
	smallMVersion, smallMAbi, smallMVariants, smallMHash = (
	 loadSmallMSchema(smallMSchema)
	)
	smallMRel = smallMSchema.relative_to(REPO_ROOT).as_posix()
	validateCombinedKernelIdentities(
	 baseVariants, variants, smallMVariants)

	outputs = {
	 Path("cmake/gen/tileBaseVariants.cmake"):
	  emitBaseCmake(baseVariants, baseRel),
	 Path("cmake/gen/tileFp32Variants.cmake"):
	  emitCmake(variants, schemaRel),
	 Path("cmake/gen/tileSmallMVariants.cmake"):
	  emitSmallMCmake(smallMVariants, smallMRel),
	 Path("source/cpp/lib/oa/runtime/gen/tileKernelRegistry.inc"):
	  emitKernelRows(variants, smallMVariants, baseVariants,
	   (baseRel, schemaRel, smallMRel)),
	 Path("source/cpp/include/oa/runtime/gen/tileComputeKernel.h"):
	  emitComputeIds(variants, smallMVariants, baseVariants,
	   (baseRel, schemaRel, smallMRel)),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileBaseVariants.inc"):
	  emitBaseRows(baseVariants, baseRel),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileFp32Variants.inc"):
	  emitMatmulRows(variants, schemaRel),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileSmallMVariants.inc"):
	  emitSmallMRows(smallMVariants, smallMRel),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileBaseMetadata.h"):
	  emitBaseMetadata(baseVersion, baseAbi, baseHash, baseRel),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileMetadata.h"):
	  emitMetadata(schemaVersion, generatorAbi, schemaHash, schemaRel),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileSmallMMetadata.h"):
	  emitSmallMMetadata(
	   smallMVersion, smallMAbi, smallMHash, smallMRel),
	 Path("cmake/gen/tileBf16Variants.cmake"):
	  emitCoopCmake(bf16Families, bf16Rel),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileBf16Variants.inc"):
	  emitCoopRows(bf16Families, bf16Rel),
	 Path("source/cpp/lib/oa/runtime/gemm/gen/tileBf16Metadata.h"):
	  emitCoopMetadata(bf16Version, bf16Abi, bf16Hash, bf16Rel),
	}
	for rel, content in outputs.items():
		write(out / rel, content, args.dryRun)
	return 0


if __name__ == "__main__":
	try:
		sys.exit(main())
	except (OSError, ValueError, tomllib.TOMLDecodeError) as exc:
		print(f"oatile: {exc}", file=sys.stderr)
		sys.exit(1)
