def collectSchemaKernels(schemaPaths: list[Path]) -> list[dict]:
	"""Collect built-in kernel identities mechanically owned by operation schemas."""
	kernels: list[dict] = []
	for schemaPath in schemaPaths:
		with schemaPath.open("rb") as file:
			data = tomllib.load(file)
		for op in data.get("ops", []):
			if "kernel" not in op:
				continue
			spec = dict(op["kernel"])
			spec["name"] = op.get("kernel_forward", "")
			spec["operation"] = op.get("name", "")
			spec["schema"] = schemaLabel(schemaPath)
			kernels.append(spec)
	return kernels


def partitionSchemaOwners(
 schemaPaths: list[Path],
) -> tuple[list[Path], list[Path]]:
	coreSchemas: list[Path] = []
	sdkSchemas: list[Path] = []
	for schemaPath in schemaPaths:
		with schemaPath.open("rb") as file:
			owner = tomllib.load(file).get("owner", "core")
		if owner == "core":
			coreSchemas.append(schemaPath)
		elif owner == "sdk":
			sdkSchemas.append(schemaPath)
		else:
			fail(f"{schemaPath}: unsupported schema owner {owner!r}")
	return coreSchemas, sdkSchemas


def validateSchemaKernelOwnership(
 kernels: list[dict], registryPath: Path
) -> None:
 # Schema-owned fragments are outputs of this generator, so collision checks
 # Compare against only the other two authorities: standalone + Tile.
	texts = [registryPath.read_text()]
	for include in re.findall(r'#include\s+<oa/runtime/([^>]+)>', texts[0]):
		includeName = Path(include).name
		if not (
		 includeName.startswith("kernelRegistryStandalone")
		 or includeName == "tileKernelRegistry.inc"
		):
			continue
		included = registryPath.parent / include
		if included.exists():
			texts.append(included.read_text())
	pattern = re.compile(
	 r'\{\s*"([^"]+)"\s*,\s*OA_COMPUTE_KERNEL_ID\('
	 r'oa::computeKernelPrefix::([A-Za-z0-9_]+),\s*([0-9]+)\)'
	)
	manualNames: set[str] = set()
	manualIds: set[tuple[str, int]] = set()
	for text in texts:
		for name, prefix, local in pattern.findall(text):
			manualNames.add(name)
			manualIds.add((prefix, int(local)))

	seenNames: set[str] = set()
	seenIds: set[tuple[str, int]] = set()
	seenSources: set[str] = set()
	for kernel in kernels:
		ctx = f"{kernel.get('schema', '<schema>')}:{kernel.get('operation', '<op>')}"
		name = kernel.get("name", "")
		prefix = kernel.get("id_prefix")
		local = kernel.get("id_local")
		source = kernel.get("source")
		if not name:
			fail(f"{ctx}: schema-owned kernel is missing kernel_forward")
		if name in manualNames:
			fail(f"{ctx}: kernel {name!r} is duplicated by another kernel authority")
		if name in seenNames:
			fail(f"{ctx}: duplicate schema-owned kernel name {name!r}")
		if isinstance(local, int) and not isinstance(local, bool):
			packed = (prefix, local)
			if packed in manualIds:
				fail(f"{ctx}: kernel id {prefix}:{local} belongs to another kernel authority")
			if packed in seenIds:
				fail(f"{ctx}: duplicate schema-owned kernel id {prefix}:{local}")
			seenIds.add(packed)
		if source in seenSources:
			fail(f"{ctx}: duplicate schema-owned kernel source {source!r}")
		seenNames.add(name)
		seenSources.add(source)


def emitSchemaKernelRegistry(kernels: list[dict], category: str) -> str:
	lines = [
	 "// AUTO-GENERATED by tools/gen/fn/generate.py — DO NOT EDIT.",
	 "// Source of truth: tools/gen/fn/schema/**.toml [ops.kernel].",
	 "// Included inside the matching oa::kernelRegistry fixed-family array.",
	]
	for kernel in sorted(
	 (k for k in kernels if k["category"] == category),
	 key=lambda item: (item["id_prefix"], item["id_local"], item["name"]),
	):
		lines.append(
		 f'\t{{ "{kernel["name"]}", '
		 f'OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::{kernel["id_prefix"]}, '
		 f'{kernel["id_local"]}), oa::ComputeKernelCategory::{kernel["category"]}, '
		 f'"{kernel["origin"]}" }},'
		)
	lines.append("")
	return "\n".join(lines)


def emitSchemaKernelIds(kernels: list[dict]) -> str:
	lines = [
	 "// AUTO-GENERATED by tools/gen/fn/generate.py — DO NOT EDIT.",
	 "// Source of truth: tools/gen/fn/schema/**.toml [ops.kernel].",
	 "// Included inside namespace oa::computeKernelId.",
	]
	for kernel in sorted(
	 kernels,
	 key=lambda item: (item["id_prefix"], item["id_local"], item["name"]),
	):
		lines.append(
		 f"static constexpr oa::U64 {kernel['name']} = "
		 f"OA_COMPUTE_KERNEL_ID(oa::computeKernelPrefix::{kernel['id_prefix']}, "
		 f"{kernel['id_local']});"
		)
	lines.append("")
	return "\n".join(lines)


def emitSchemaKernelCmake(kernels: list[dict]) -> str:
	lines = [
	 "# AUTO-GENERATED by tools/gen/fn/generate.py -- DO NOT EDIT.",
	 "# Source of truth: tools/gen/fn/schema/**.toml [ops.kernel].",
	]
	byCategory: dict[str, list[dict]] = defaultdict(list)
	for kernel in kernels:
		byCategory[kernel["category"]].append(kernel)
	for category, entries in sorted(byCategory.items()):
		variable = re.sub(r"(?<!^)(?=[A-Z])", "_", category).upper()
		entries.sort(key=lambda item: (item["id_prefix"], item["id_local"], item["name"]))
		lines += [f"set(OA_OPERATION_{variable}_KERNEL_NAMES"]
		lines += [f"\t{entry['name']}" for entry in entries]
		lines += [")", f"set(OA_OPERATION_{variable}_KERNEL_SOURCES"]
		lines += [f"\t{entry['source']}" for entry in entries]
		lines += [")"]
	lines.append("")
	return "\n".join(lines)


def emitSdkKernelCmake(kernels: list[dict]) -> str:
	lines = [
	 "# AUTO-GENERATED by tools/gen/fn/generate.py -- DO NOT EDIT.",
	 "# Source of truth: SDK-owned tools/gen/fn schemas.",
	 "set(OA_SDK_ENVIRONMENT_KERNEL_NAMES",
	]
	entries = sorted(kernels, key=lambda item: item["name"])
	lines += [f"\t{entry['name']}" for entry in entries]
	lines += [")", "set(OA_SDK_ENVIRONMENT_KERNEL_SOURCES"]
	lines += [f"\t{entry['source']}" for entry in entries]
	lines += [")", ""]
	return "\n".join(lines)


def writeSdkKernelCmake(
 kernels: list[dict], outRoot: Path, *, live: bool, dryRun: bool
) -> None:
	path = repositoryOutputPath(
	 outRoot, Path("cmake/gen/sdkEnvironmentKernels.cmake")
	)
	if dryRun:
		print(f"  would write: {path}")
		return
	writeGeneratedText(path, emitSdkKernelCmake(kernels))


