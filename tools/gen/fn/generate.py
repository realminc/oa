	surfacePath = outRoot / "py" / "oa" / "_schemaSurface.py"
	if dryRun:
		print(f"  would write: {surfacePath}")
	else:
		writeGeneratedText(
		 surfacePath,
		 emitPythonSurfaceInventory(surfaceBindings),
		)


