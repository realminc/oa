def _fnv1a64(data: bytes) -> int:
	value = 14695981039346656037
	for byte in data:
		value ^= byte
		value = (value * 1099511628211) & 0xffffffffffffffff
	return value


def _packedValueKinds(kinds: list[str]) -> int:
	packed = 0
	for index, kind in enumerate(kinds):
		packed |= _VALUE_KIND_NIBBLE[kind] << (index * 4)
	return packed


def _packedOutputAliasInputs(aliases: list[int]) -> int:
	packed = 0xffffffff
	for index, inputIndex in enumerate(aliases):
		value = 0x0f if inputIndex < 0 else inputIndex
		packed &= ~(0x0f << (index * 4))
		packed |= value << (index * 4)
	return packed


def _mutatedInputMask(indices: list[int]) -> int:
	mask = 0
	for index in indices:
		mask |= 1 << index
	return mask


def _optionalInputMask(indices: list[int]) -> int:
	mask = 0
	for index in indices:
		mask |= 1 << index
	return mask


def operationAttributeSignatureHash(op: dict) -> int:
	attributes = [
	 {"name": attribute["name"], "kind": attribute["kind"]}
	 for attribute in semanticAttributeSpecs(op)
	]
	if not attributes:
		return 0
	payload = bytearray()
	for attribute in attributes:
		payload.append(_ATTRIBUTE_KIND_BYTE[attribute["kind"]])
		payload.extend(attribute["name"].encode("utf-8"))
		payload.append(0)
	return _fnv1a64(bytes(payload))


def operationContractHash(namespace: str, op: dict) -> int:
	"""Stable semantic hash. Kernel/problem/runtime details are excluded."""
	contract = dict(op["contract"])
	contract.pop("attributes", None)
	payload = {
	 "schema": "oa.operation_contract.v1",
	 "namespace": namespace,
	 "name": op["name"],
	 "api_params": op.get("api_params", []),
	 "api_return": op.get("api_return", "oa::Matrix"),
	 "contract": contract,
	}
	attributes = [
	 {"name": attribute["name"], "kind": attribute["kind"]}
	 for attribute in semanticAttributeSpecs(op)
	]
	if attributes:
		payload["attributes"] = attributes
	canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
	return _fnv1a64(canonical.encode("utf-8"))


def operationRegistryReference(namespace: str, name: str) -> str:
	"""Return the collision-free C++ path for a semantic contract."""
	return f"oa::detail::opRegistry::{namespaceLeaf(namespace)}::{name}"


def emitOperationRegistry(contracts: list[tuple[str, dict]]) -> str:
	lines = [
	 "// AUTO-GENERATED by tools/gen/fn/generate.py — DO NOT EDIT.",
	 "// Source of truth: tools/gen/fn/schema/**.toml [ops.contract].",
	 "// Regenerate via: python3 tools/gen/fn/generate.py --live",
	 "#pragma once",
	 "",
	 "#include <oa/core/op.h>",
	 "",
	 "namespace oa::detail::opRegistry {",
	]
	grouped: dict[str, list[dict]] = defaultdict(list)
	for namespace, op in contracts:
		grouped[namespace].append(op)
	for namespace, ops in sorted(grouped.items()):
		registryNamespace = namespaceLeaf(namespace)
		lines += [f"namespace {registryNamespace} {{", ""]
		for op in sorted(ops, key=lambda item: item["name"]):
			contract = op["contract"]
			variadicInputs = contract.get("variadic_inputs")
			variadicOutputs = contract.get("variadic_outputs")
			inputKinds = _packedValueKinds(contract["input_kinds"])
			outputKinds = _packedValueKinds(contract["output_kinds"])
			effects = " | ".join(_EFFECT_CPP[effect] for effect in contract["effects"])
			mutatedInputs = _mutatedInputMask(contract["mutated_inputs"])
			optionalInputs = _optionalInputMask(
			 contract.get("optional_inputs", [])
			)
			outputAliasInputs = _packedOutputAliasInputs(
			 contract["output_alias_inputs"]
			)
			attributes = semanticAttributeSpecs(op)
			attributeSignature = operationAttributeSignatureHash(op)
			hashValue = operationContractHash(namespace, op)
			lines += [
			 f"inline const oa::OpContract {op['name']}{{",
			 f"\t.name = \"{namespace}::{op['name']}\",",
			 f"\t.hash = 0x{hashValue:016x}ULL,",
			 f"\t.inputKinds = 0x{inputKinds:08x}U,",
			 f"\t.outputKinds = 0x{outputKinds:08x}U,",
			 f"\t.inputCount = {len(contract['input_kinds'])}U,",
			 f"\t.outputCount = {len(contract['output_kinds'])}U,",
			 (
			  "\t.variadicInputKind = "
			  f"{_VALUE_KIND_CPP[variadicInputs['kind']]},"
			  if variadicInputs else
			  "\t.variadicInputKind = oa::OpValueKind::None,"
			 ),
			 (
			  "\t.variadicOutputKind = "
			  f"{_VALUE_KIND_CPP[variadicOutputs['kind']]},"
			  if variadicOutputs else
			  "\t.variadicOutputKind = oa::OpValueKind::None,"
			 ),
			 (
			  "\t.minimumVariadicInputCount = "
			  f"{variadicInputs['minimum']}U,"
			  if variadicInputs else
			  "\t.minimumVariadicInputCount = 0U,"
			 ),
			 (
			  "\t.minimumVariadicOutputCount = "
			  f"{variadicOutputs['minimum']}U,"
			  if variadicOutputs else
			  "\t.minimumVariadicOutputCount = 0U,"
			 ),
			 f"\t.attributeCount = {len(attributes)}U,",
			 f"\t.attributeSignatureHash = 0x{attributeSignature:016x}ULL,",
			 f"\t.shapeRule = {_SHAPE_RULE_CPP[contract['shape_rule']]},",
			 f"\t.dtypeRule = {_DTYPE_RULE_CPP[contract['dtype_rule']]},",
			 f"\t.differentiation = {_DIFFERENTIATION_CPP[contract['differentiation']]},",
			 f"\t.lowering = {_LOWERING_CPP[contract['lowering']]},",
			 f"\t.effects = {effects},",
			 f"\t.mutatedInputMask = 0x{mutatedInputs:02x}U,",
			 f"\t.optionalInputMask = 0x{optionalInputs:02x}U,",
			 f"\t.outputAliasInputs = 0x{outputAliasInputs:08x}U,",
			 f"\t.controlFlow = {_CONTROL_FLOW_CPP[contract['control_flow']]},",
			 "};",
			 "",
			]
		lines += [f"}} // namespace {registryNamespace}", ""]
	lines += ["} // namespace oa::detail::opRegistry", ""]
	return "\n".join(lines)


def writeOperationRegistry(
 schemaPaths: list[Path], outRoot: Path, *, dryRun: bool
) -> None:
	contracts: list[tuple[str, dict]] = []
	seen: set[tuple[str, str]] = set()
	for schemaPath in schemaPaths:
		with schemaPath.open("rb") as file:
			data = tomllib.load(file)
		domain = inferDomain(schemaPath)
		namespace = data.get("namespace", DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix"))
		for op in data.get("ops", []):
			if "contract" not in op:
				continue
			key = (namespace, op["name"])
			if key in seen:
				fail(f"duplicate operation contract: {namespace}::{op['name']}")
			seen.add(key)
			contracts.append((namespace, op))

	path = outRoot / "cpp" / "lib" / "oa" / "core" / "opRegistry.gen.h"
	if dryRun:
		print(f"  would write: {path}")
		return
	writeGeneratedText(path, emitOperationRegistry(contracts))
	legacyPath = outRoot / "cpp" / "include" / "oa" / "core" / "opRegistry.gen.h"
	if legacyPath != path and legacyPath.exists():
		legacyPath.unlink()


def writeSdkOperationRegistry(
 schemaPaths: list[Path], outRoot: Path, *, live: bool, dryRun: bool
) -> None:
	contracts: list[tuple[str, dict]] = []
	for schemaPath in schemaPaths:
		with schemaPath.open("rb") as file:
			data = tomllib.load(file)
			namespace = data["namespace"]
			for op in data.get("ops", []):
				if "contract" in op:
					contracts.append((namespace, op))
	root = REPO_ROOT if live else outRoot
	path = root / "sdk" / "cpp" / "lib" / "ml" / "rl" / "gen" / "environmentOpRegistry.h"
	if dryRun:
		print(f"  would write: {path}")
		return
	writeGeneratedText(path, emitOperationRegistry(contracts))


