def _pythonBindingParamsAndArgs(op: dict) -> tuple[str, str]:
	"""Adapt native span parameters to ordinary Python list boundaries."""
	params: list[str] = []
	args: list[str] = []
	for param in op.get("api_params", []):
		paramType, name, _ = _apiParamParts(param)
		compactType = re.sub(r"\s+", "", paramType)
		constSpan = re.fullmatch(r"oa::Span<const(.+)>", compactType)
		if constSpan:
			elementType = constSpan.group(1)
			params.append(f"std::vector<{elementType}> {name}")
			args.append(
			 f"oa::Span<const {elementType}>({name}.data(), {name}.size())"
			)
		elif compactType == "oa::Span<oa::Matrix>":
			params.append(f"std::vector<oa::Matrix> {name}")
			args.append(
			 f"oa::Span<oa::Matrix>({name}.data(), {name}.size())"
			)
		elif compactType == "oa::Span<oa::I64>":
			params.append(f"std::vector<oa::I64> {name}")
			args.append(
			 f"oa::Span<oa::I64>({name}.data(), {name}.size())"
			)
		else:
			params.append(f"{paramType} {name}")
			args.append(name)
	return ", ".join(params), ", ".join(args)


def _toCamel(name: str) -> str:
	"""Convert PascalCase or UpperCase identifier to camelCase."""
	if not name:
		return name
	return name[0].lower() + name[1:]


def emitPythonBinding(namespace: str, op: dict) -> list[str]:
	python = op["python"]
	params, args = _pythonBindingParamsAndArgs(op)
	pythonName = _toCamel(python.get("name", op["name"]))
	call = f"{namespace}::{op['name']}({args})"
	apiReturn = op.get("api_return", "oa::Matrix")
	if apiReturn == "oa::Matrix":
		result = f"matrixPtr({call})"
		ownedResult = "matrixPtr(std::move(result))"
	elif apiReturn == "oa::Image":
		result = f"imagePtr({call})"
		ownedResult = "imagePtr(std::move(result))"
	elif apiReturn == "void":
		result = call
		ownedResult = ""
	elif apiReturn == "oa::Vec<oa::Matrix>":
		result = ""
		ownedResult = ""
	else:
		resultType = op.get("python_result", {}).get(
		 "cpp_type", apiReturn
		)
		result = f"new {resultType}({call})"
		ownedResult = f"new {resultType}(std::move(result))"
	lines = [
	 f'\tm.def("{pythonName}", []({params}) {{',
	]
	resultValidation = python.get("result_validation")
	if apiReturn == "oa::Vec<oa::Matrix>":
		lines += [
		 f"\t\tauto result = {call};",
		 "\t\tnb::list values;",
		 "\t\tfor (auto& value : result) {",
		 "\t\t\tvalues.append(nb::cast(",
		 "\t\t\t\tmatrixPtr(std::move(value)),",
		 "\t\t\t\tnb::rv_policy::take_ownership));",
		 "\t\t}",
		 "\t\treturn values;",
		]
	elif apiReturn == "void":
		lines.append(f"\t\t{result};")
	elif resultValidation is None:
		lines.append(f"\t\treturn {result};")
	else:
		lines.append(f"\t\tauto result = {call};")
		if resultValidation == "not_empty":
			invalid = "result.isEmpty()"
		else:
			invalid = "not result.isValid()"
		error = python.get(
		 "error",
		 f"{op['name']} rejected its input",
		)
		lines += [
		 f"\t\tif ({invalid}) {{",
		 f"\t\t\tthrow std::runtime_error({json.dumps(error)});",
		 "\t\t}",
		 f"\t\treturn {ownedResult};",
		]
	lines.append("\t},")
	argSpecs = []
	for pythonArg, apiParam in zip(python["args"], op["api_params"]):
		paramType, _, default = _apiParamParts(apiParam)
		spec = f'nb::arg("{_toCamel(pythonArg)}")'
		if default is not None:
			if default == "{}":
				typedDefault = re.sub(r"\bconst\b", "", paramType)
				typedDefault = typedDefault.replace("&", "").strip()
				default = f"{typedDefault}{{}}"
			spec += f" = {default}"
		argSpecs.append(spec)
	lines.append("\t  " + ", ".join(argSpecs) + ",")
	lines.append("\t  nb::rv_policy::take_ownership,")
	doc = python.get("doc", op.get("notes", ""))
	lines.append(f"\t  {json.dumps(doc, ensure_ascii=True)});")
	lines.append("")
	return lines


def emitPythonBindings(bindings: list[tuple[str, dict]]) -> str:
	bindings = [
	 (namespace, op)
	 for namespace, op in bindings
	 if op["python"].get("binding", "generated") == "generated"
	]
	lines = [
	 "// AUTO-GENERATED by tools/gen/fn/generate.py — DO NOT EDIT.",
	 "// Source of truth: tools/gen/fn/schema/**.toml.",
	 "// Included inside the owning bind function.",
	 "",
	]
	resultTypes: dict[str, dict] = {}
	for _, op in bindings:
		result = op.get("python_result")
		if result is None:
			continue
		cppType = result["cpp_type"]
		previous = resultTypes.get(cppType)
		if previous is not None and previous != result:
			fail(
			 f"{op['name']}: conflicting Python result descriptors for "
			 f"{cppType}"
			)
		resultTypes[cppType] = result
	for cppType, result in sorted(resultTypes.items()):
		if not result.get("bind_type", True):
			continue
		pythonName = result.get("name", cppType.rsplit("::", 1)[-1])
		lines.append(f'\tnb::class_<{cppType}>(m, "{pythonName}")')
		for index, member in enumerate(result["members"]):
			terminator = ";" if index == len(result["members"]) - 1 else ""
			lines.append(
			 f'\t\t.def_ro("{member}", &{cppType}::{member}){terminator}'
			)
		lines.append("")
	for namespace, op in sorted(bindings, key=lambda item: item[1]["name"]):
		lines.extend(emitPythonBinding(namespace, op))
	return "\n".join(lines).rstrip() + "\n"


def emitPythonSurfaceInventory(
 bindings: list[tuple[str, str, dict]],
) -> str:
	"""Emit schema-owned C++-parity namespace mappings."""

	grouped: dict[str, dict[str, set[tuple[str, str]]]] = defaultdict(
	 lambda: defaultdict(set)
	)
	resultExports: dict[str, dict[str, str]] = defaultdict(dict)
	for domain, namespace, op in bindings:
		python = op["python"]
		nativeName = _toCamel(python.get("name", op["name"]))
		family = namespaceLeaf(namespace)
		grouped[family][domain.lower()].add((nativeName, nativeName))
		result = op.get("python_result")
		if result is None or not result.get("bind_type", True):
			continue
		resultName = result.get(
		 "name", result["cpp_type"].rsplit("::", 1)[-1]
		)
		previous = resultExports[family].get(resultName)
		if previous is not None and previous != result["cpp_type"]:
			fail(
			 f"{family}.{resultName}: conflicting Python result types "
			 f"{previous} and {result['cpp_type']}"
			)
		resultExports[family][resultName] = result["cpp_type"]

	lines = [
	 "# AUTO-GENERATED by tools/gen/fn/generate.py — DO NOT EDIT.",
	 "# Source of truth: tools/gen/fn/schema/**.toml [ops.python].",
	 "",
	 "SCHEMA_ROOT_EXPORTS = {",
	]
	for namespace, results in sorted(resultExports.items()):
		lines.append(f'\t"{namespace}": (')
		for resultName in sorted(results):
			lines.append(f'\t\t("{resultName}", "{resultName}"),')
		lines.append("\t),")
	lines += [
	 "}",
	 "",
	 "SCHEMA_NAMESPACE_EXPORTS = {",
	]
	for namespace, domains in sorted(grouped.items()):
		lines.append(f'\t"{namespace}": {{')
		for domain, mappings in sorted(domains.items()):
			lines.append(f'\t\t"{domain}": (')
			for nativeName, publicName in sorted(mappings):
				lines.append(
				 f'\t\t\t("{nativeName}", "{publicName}"),'
				)
			lines.append("\t\t),")
		lines.append("\t},")
	lines += [
	 "}",
	 "",
	 '__all__ = ["SCHEMA_NAMESPACE_EXPORTS", "SCHEMA_ROOT_EXPORTS"]',
	 "",
	]
	return "\n".join(lines)


def writePythonBindings(
 schemaPaths: list[Path], outRoot: Path, *, dryRun: bool
) -> None:
	groups: dict[tuple[str, str], list[tuple[str, dict]]] = defaultdict(list)
	surfaceBindings: list[tuple[str, str, dict]] = []
	for schemaPath in schemaPaths:
		with schemaPath.open("rb") as file:
			data = tomllib.load(file)
		domain = inferDomain(schemaPath)
		namespace = data.get("namespace", DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix"))
		filePrefix = data.get("file_prefix", DOMAIN_FILE_PREFIX.get(domain, "FnMatrix"))
		for op in data.get("ops", []):
			applySchemaDefaults(data, op)
			if "python" in op:
				surfaceBindings.append((domain, namespace, op))
				if op["python"].get("binding", "generated") == "generated":
					groups[(domain, filePrefix)].append((namespace, op))

	for (domain, filePrefix), bindings in sorted(groups.items()):
		path = (
		 outRoot / "py" / domain
		 / f"{camelFileStem(filePrefix)}Ops.gen.inl"
		)
		if dryRun:
			print(f"  would write: {path}")
