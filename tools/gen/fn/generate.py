# ─── Manifest emission ───────────────────────────────────────────────────────


def _pascalToUpperSnake(name: str) -> str:
	return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def _sourceRel(path: Path, outRoot: Path) -> str:
 # Always emit repo-root-relative source/... paths so the .cmake content is
 # byte-identical in --live and scratch (--out) mode. The drift gate
 # (tools/gen/checkDrift.py) relies on scratch output matching live.
	rel = path.relative_to(outRoot).as_posix()
	return rel if rel.startswith("source/") else f"source/{rel}"


def _manifestVar(layout: SchemaLayout) -> str:
	if layout.domain == "crypto":
		return f"OA_CRYPTO_{layout.cppSubdir.upper()}_{_pascalToUpperSnake(layout.filePrefix)}_GENERATED_SOURCES"
	return f"OA_{layout.domain.upper()}_{_pascalToUpperSnake(layout.filePrefix)}_GENERATED_SOURCES"


def emitUmbrellaHeader(layouts: list[SchemaLayout]) -> str:
	first = layouts[0]
	lines = [
	 GEN_HEADER.format(schema_name=f"{first.domain}/{first.filePrefix} manifest"),
	 f"// {first.namespace} — generated declarations for {first.domain}/{first.cppSubdir}.\n",
	]
	manifestParent = (
	 first.headerPath.parents[1]
	 if first.headerPath.parent.name != first.cppSubdir.lower()
	 else first.headerPath.parent
	)
	for layout in layouts:
		if not layout.emitHeader:
			continue
		includePath = layout.headerPath.relative_to(manifestParent).as_posix()
		lines.append(f'#include "{includePath}"')
	lines.append("")
	return "\n".join(lines)


def emitCmakeSources(layouts: list[SchemaLayout], outRoot: Path) -> str:
	first = layouts[0]
	varName = _manifestVar(first)
	lines = [
	 "# AUTO-GENERATED by tools/gen/fn/generate.py -- DO NOT EDIT.",
	 "# Regenerate via: python3 tools/gen/fn/generate.py --live",
	 f"set({varName}",
	]
	for layout in layouts:
		if not layout.emitCpp:
			continue
		lines.append(f"\t{_sourceRel(layout.cppPath, outRoot)}")
	lines.append(")")
	lines.append("")
	return "\n".join(lines)


def emitAutogradManifest(domain: str, layouts: list[SchemaLayout]) -> str:
	publicAutograd = (
	 "oa/core/autograd.h" if domain == "core" else "oa/ml/autograd.h"
	)
	manifestParent = layouts[0].autogradHeaderPath.parent.parent
	lines = [
	 "// AUTO-GENERATED by tools/gen/fn/generate.py — DO NOT EDIT.",
	 "// Includes schema-generated gradient-node catalogs for this domain.",
	 "// Regenerate via: python3 tools/gen/fn/generate.py --live",
	 "",
	 "#pragma once",
	 "",
	 f"#include <{publicAutograd}>",
	]
	for layout in sorted(
	 layouts, key=lambda item: item.autogradHeaderPath.as_posix()
	):
		includePath = layout.autogradHeaderPath.relative_to(
		 manifestParent
		).as_posix()
		lines.append(f'#include "{includePath}"')
	lines.append("")
	return "\n".join(lines)


def writeAutogradManifestFiles(
 layouts: list[SchemaLayout], outRoot: Path, *, dryRun: bool
) -> None:
	byDomain: dict[str, list[SchemaLayout]] = defaultdict(list)
	for layout in layouts:
		if layout.emitAutograd:
			byDomain[layout.domain].append(layout)

	for domain in ("core", "ml"):
		autogradRoot = outRoot / "cpp" / "lib" / "oa" / domain / "autograd"
		manifest = autogradRoot / "autograd.gen.h"
		domainLayouts = byDomain.get(domain, [])
		if dryRun:
			if domainLayouts:
				print(f"  would write: {manifest}")
			continue
		if domainLayouts:
			writeGeneratedText(
			 manifest, emitAutogradManifest(domain, domainLayouts)
			)
		elif manifest.exists():
			manifest.unlink()

		expected = {
		 layout.autogradHeaderPath for layout in domainLayouts
		}
		if not autogradRoot.exists():
			continue
		for generated in autogradRoot.rglob("autograd*.gen.h"):
			if generated in expected or generated.name in (
			 "autograd.gen.h", "autogradAttach.gen.h"
			):
				continue
			if generated.read_text(encoding="utf-8").startswith(
			 "// AUTO-GENERATED by tools/gen/fn/generate.py"
			):
				generated.unlink()


def writeManifestFiles(layouts: list[SchemaLayout], outRoot: Path, *, dryRun: bool) -> None:
	groups: dict[tuple[str, str, str, str], list[SchemaLayout]] = defaultdict(list)
	sourceGroups: dict[tuple[str, str], list[SchemaLayout]] = defaultdict(list)
	for layout in layouts:
		groups[(layout.domain, layout.namespace, layout.filePrefix, layout.cppSubdir)].append(layout)
		sourceGroups[(layout.domain, layout.filePrefix)].append(layout)

	generatedHeaders = {layout.headerPath for layout in layouts if layout.emitHeader}
	autogradManifests = {
	 outRoot / "cpp" / "lib" / "oa" / domain / "autograd" / "autograd.gen.h"
	 for domain in ("core", "ml")
	}
	for grouped in groups.values():
		grouped.sort(key=lambda item: item.headerPath.name)
		first = grouped[0]
		hasHeaders = any(layout.emitHeader for layout in grouped)

		manifestParent = (
		 outRoot / "cpp" / "lib" / "oa" / first.domain / first.cppSubdir.lower()
		)
		manifestHeader = manifestParent / f"{camelFileStem(first.filePrefix)}.gen.h"
		emitHeader = (
		 hasHeaders and manifestHeader not in generatedHeaders and first.domain != "crypto"
		)
		if dryRun:
			if emitHeader:
				print(f"  would write: {manifestHeader}")
			continue
		if emitHeader:
			writeGeneratedText(manifestHeader, emitUmbrellaHeader(grouped))
			legacyHeader = (
			 outRoot / "cpp" / "include" / "oa" / first.domain
			 / f"{first.filePrefix}.gen.h"
			)
			if legacyHeader != manifestHeader and legacyHeader.exists():
				legacyHeader.unlink()
			legacyPublicHeader = (
			 outRoot / "cpp" / "include" / "oa" / first.domain
			 / first.cppSubdir / f"{first.filePrefix}.gen.h"
			)
			if legacyPublicHeader != manifestHeader and legacyPublicHeader.exists():
				legacyPublicHeader.unlink()
		elif (
		 manifestHeader.exists()
		 and manifestHeader not in generatedHeaders
		 and manifestHeader not in autogradManifests
		):
			manifestHeader.unlink()
		legacyPublicHeader = (
		 outRoot / "cpp" / "include" / "oa" / first.domain
		 / f"{first.filePrefix}.gen.h"
		)
		if legacyPublicHeader != manifestHeader and legacyPublicHeader.exists():
			legacyPublicHeader.unlink()

	# CMake inventories are keyed only by their domain/Fn family. Several
	# private lowering directories can contribute to one family, and an empty
	# sibling must never delete a manifest emitted by another group.
	for (domain, filePrefix), grouped in sourceGroups.items():
		grouped.sort(key=lambda item: item.cppPath.as_posix())
		manifestCmake = repositoryOutputPath(
			outRoot,
			Path("cmake/gen") / f"{domain}{filePrefix}Sources.cmake",
		)
		hasCpp = any(layout.emitCpp for layout in grouped)
		if dryRun:
			if hasCpp:
				print(f"  would write: {manifestCmake}")
			continue
		if hasCpp:
			writeGeneratedText(manifestCmake, emitCmakeSources(grouped, outRoot))
		elif manifestCmake.exists():
			manifestCmake.unlink()


# ─── Main ──────────────────────────────────────────────────────────────────


def processSchema(schemaPath: Path, registry: set[str], outRoot: Path,
                   *, live: bool, dryRun: bool) -> SchemaLayout | list[SchemaLayout]:
	with schemaPath.open("rb") as f:
		data = tomllib.load(f)
	ops = data.get("ops", [])
	if not ops:
		fail(f"no [[ops]] entries in {schemaPath}")
	for op in ops:
		applySchemaDefaults(data, op)
	validateSchemaMetadata(schemaPath, data)
	validateSchema(schemaPath, ops, registry, data.get("surface"))
	category, fileCategory = categoryFromSchema(schemaPath, data)
	anyManual = any(op.get("body", "auto") == "manual_session" for op in ops)
	mode = "additive (manual bodies)" if anyManual else "fully generated"
	print(f"fnGen: {schemaPath.name} — {len(ops)} ops, category={category}, "
	      f"file_category={fileCategory}, mode={mode}")

	# For Loss domain, emit per-function subdirectories (e.g., /Loss/Mse/FnLossMse.gen.h)
	domain = inferDomain(schemaPath)
	namespace = data.get("namespace", DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix"))
	filePrefix = data.get("file_prefix", DOMAIN_FILE_PREFIX.get(domain, "FnMatrix"))
	cppSubdir = data.get("cpp_subdir", inferCppSubdir(domain, fileCategory))

	def emitsHeader(op: dict) -> bool:
		return op.get("generate_declaration", True) and (
		 op.get("body", "auto") not in ("manual_session", "cpu_util")
		 or bool(op.get("api_params"))
		)

	def emitsCpp(op: dict) -> bool:
		return op.get("body", "auto") not in ("manual_session", "cpu_util") or bool(
		 op.get("api_params") and op.get("generate_forwarder", False)
		)

	if domain == "ml" and cppSubdir == "FnLoss":
	 # Per-function subdirectories for Loss
		layouts = []
		for op in ops:
			opName = op["name"]
			headerSubdir = (
			 outRoot / "cpp" / "lib" / "oa" / domain / cppSubdir.lower()
			 / opName.lower()
			)
			cppSubdirPath = headerSubdir
			fileStem = camelFileStem(
			 f"{filePrefix}{opName[:1].upper()}{opName[1:]}"
			)
			hPath = headerSubdir / f"{fileStem}.gen.h"
			cppPath = cppSubdirPath / f"{fileStem}.gen.cpp"
			schemaName = schemaLabel(schemaPath)
			opEmitHeader = emitsHeader(op)
			opEmitCpp = emitsCpp(op)

			if dryRun:
				if opEmitHeader:
					print(f"  would write: {hPath}")
				if opEmitCpp:
					print(f"  would write: {cppPath}")
				layouts.append(SchemaLayout(
				 domain=domain,
				 namespace=namespace,
				 filePrefix=filePrefix,
				 cppSubdir=cppSubdir,
				 headerPath=hPath,
				 cppPath=cppPath,
				 autogradHeaderPath=Path(""),
				 testPath=Path(""),
				 emitHeader=opEmitHeader,
				 emitCpp=opEmitCpp,
				))
				continue

			headerSubdir.mkdir(parents=True, exist_ok=True)
			cppSubdirPath.mkdir(parents=True, exist_ok=True)
			if opEmitHeader:
				writeGeneratedText(hPath, emitHeaderFragment([op], schemaName, opName, namespace))
				legacyPublicHeader = (
				 outRoot / "cpp" / "include" / "oa" / domain / cppSubdir.lower()
				 / opName.lower() / hPath.name
				)
				if legacyPublicHeader.exists():
					legacyPublicHeader.unlink()
			elif hPath.exists():
				hPath.unlink()
			if opEmitCpp:
				writeGeneratedText(cppPath, emitCppFile([op], schemaName, opName, domain, namespace))
			elif cppPath.exists():
				cppPath.unlink()
			print(f"  wrote {opName}: header={opEmitHeader}, cpp={opEmitCpp}")
			layouts.append(SchemaLayout(
			 domain=domain,
			 namespace=namespace,
			 filePrefix=filePrefix,
			 cppSubdir=cppSubdir,
			 headerPath=hPath,
			 cppPath=cppPath,
			 autogradHeaderPath=Path(""),
			 testPath=Path(""),
			 emitHeader=opEmitHeader,
			 emitCpp=opEmitCpp,
			))
  # Return list of layouts for Loss domain
		return layouts

 # Standard processing for other domains
	emitHeader = any(emitsHeader(op) for op in ops)
	emitCpp = any(emitsCpp(op) for op in ops)
	emitAutograd = any(bool(emitAutogradClass(op)) for op in ops)
	layout = buildSchemaLayout(
	 schemaPath, data, fileCategory, outRoot, live=live,
	 emitHeader=emitHeader, emitCpp=emitCpp,
	 emitAutograd=emitAutograd,
	)
	schemaName = schemaLabel(schemaPath)
	testBody = emitFnTests(ops, schemaName, fileCategory, layout.domain)
	# Emit tests if any op has forward_op OR has test config
	emitTests = any(op.get("forward_op") or op.get("test") for op in ops)
	if dryRun:
		if emitHeader:
			print(f"  would write: {layout.headerPath}")
		if emitCpp:
			print(f"  would write: {layout.cppPath}")
		if emitTests:
			print(f"  would write: {layout.testPath}")
		for op in ops:
			if op.get("forward_op"):
				print(f"  would write: {opSlangPath(op, outRoot, live=live)}")
		return layout
	if emitHeader:
		writeGeneratedText(layout.headerPath, emitHeaderFragment(ops, schemaName, category, layout.namespace))
	elif layout.headerPath.exists():
		layout.headerPath.unlink()
	relativeHeader = layout.headerPath.relative_to(
	 outRoot / "cpp" / "lib" / "oa")
	legacyPublicHeader = outRoot / "cpp" / "include" / "oa" / relativeHeader
	if legacyPublicHeader.exists():
		legacyPublicHeader.unlink()
	if emitCpp:
		writeGeneratedText(layout.cppPath, emitCppFile(ops, schemaName, category, layout.domain, layout.namespace))
	elif layout.cppPath.exists():
		layout.cppPath.unlink()
	if emitTests:
		writeGeneratedText(layout.testPath, testBody)
	elif layout.testPath.exists():
		layout.testPath.unlink()
	nSlang = 0
	for op in ops:
		if op.get("forward_op"):
			sp = opSlangPath(op, outRoot, live=live)
			# Skip if manual .slang file exists (check without .gen suffix)
			manualPath = sp.parent / f"{op['name']}.slang"
			if manualPath.exists() and sp.name.endswith('.gen.slang'):
				continue
			writeGeneratedText(sp, emitSlang(op, schemaName))
			nSlang += 1
 # Autograd generation
	autogradSubdir = layout.autogradHeaderPath.parent.name if layout.autogradHeaderPath else "Matrix"
	autogradBody = emitAutogradHeader(
	 ops, schemaName, fileCategory, layout.domain, autogradSubdir
	)
	if autogradBody and layout.autogradHeaderPath:
		writeGeneratedText(layout.autogradHeaderPath, autogradBody)
		print(f"  wrote {layout.autogradHeaderPath.name}")
	elif layout.autogradHeaderPath and layout.autogradHeaderPath.exists():
		layout.autogradHeaderPath.unlink()
	print(f"  wrote {schemaPath.name}: header={emitHeader}, cpp={emitCpp}, slang={nSlang}")
	return layout


def main() -> int:
	ap = argparse.ArgumentParser(description="Generate Fn* C++/Slang from schema.")
	ap.add_argument("--schema-dir", dest="schemaDir", type=Path, default=SCHEMA_DIR,
	                help="Directory containing *.toml schemas (default: tools/gen/fn/schema/)")
	ap.add_argument("--schema", type=Path, default=None,
	                help="Single schema file (overrides --schema-dir)")
	ap.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY,
	                help="composed kernelRegistry.h to cross-check kernel names against")
	ap.add_argument("--out", type=Path, default=DEFAULT_OUTPUT,
	                help="Preview output root (default: build/gen/fn)")
	ap.add_argument("--live", action="store_true",
	                help="Write drop-in replacements directly to source/ tree.")
	ap.add_argument("--dry-run", dest="dryRun", action="store_true",
	                help="Print summary, don't write files")
	args = ap.parse_args()
	if args.live and args.schema and not args.dryRun:
		fail("--schema cannot be combined with --live because shared manifests require the complete schema set")
	outRoot = LIVE_SOURCE_ROOT if args.live else args.out
	if args.live:
		print("fnGen: LIVE MODE — updating generated source artifacts")
	if args.schema:
		schemas = [args.schema]
	else:
	 # Recursively find all .toml files in schema/ subdirectories.
		schemas = sorted(args.schemaDir.rglob("*.toml"))
		if not schemas:
			fail(f"no schemas found in {args.schemaDir}")
	validateSchemaSet(schemas)
	coreSchemas, sdkSchemas = partitionSchemaOwners(schemas)
	coreKernels = collectSchemaKernels(coreSchemas)
	sdkKernels = collectSchemaKernels(sdkSchemas)
	validateSchemaKernelOwnership(coreKernels + sdkKernels, args.registry)
	registry = loadKernelRegistry(args.registry)
	registry.update(kernel["name"] for kernel in coreKernels + sdkKernels)
	print(
	 f"fnGen: registry {args.registry.name} — {len(registry)} kernels "
	 f"({len(coreKernels)} core, {len(sdkKernels)} SDK schema-owned)"
	)
	layouts = []
	for schemaPath in coreSchemas:
		result = processSchema(schemaPath, registry, outRoot, live=args.live, dryRun=args.dryRun)
		# process_schema may return a list (for Loss) or a single SchemaLayout
		if isinstance(result, list):
			layouts.extend(result)
		else:
			layouts.append(result)
	writeManifestFiles(layouts, outRoot, dryRun=args.dryRun)
	writeAutogradManifestFiles(layouts, outRoot, dryRun=args.dryRun)
	for schemaPath in sdkSchemas:
		with schemaPath.open("rb") as file:
			data = tomllib.load(file)
		for op in data.get("ops", []):
			applySchemaDefaults(data, op)
		validateSchemaMetadata(schemaPath, data)
		validateSchema(schemaPath, data["ops"], registry, data.get("surface"))
	writeOperationRegistry(coreSchemas, outRoot, dryRun=args.dryRun)
	writeSdkOperationRegistry(
	 sdkSchemas, outRoot, live=args.live, dryRun=args.dryRun)
	writeDnnOperationRoles(coreSchemas, outRoot, dryRun=args.dryRun)
	writeManualAutogradAttachFiles(coreSchemas, outRoot, dryRun=args.dryRun)
	writePythonBindings(coreSchemas, outRoot, dryRun=args.dryRun)
	writeSchemaKernelFiles(coreKernels, outRoot, dryRun=args.dryRun)
	writeSdkKernelCmake(
	 sdkKernels, outRoot, live=args.live, dryRun=args.dryRun)
	writeOperationReference(
	 coreSchemas, outRoot, live=args.live, dryRun=args.dryRun
	)
	return 0


if __name__ == "__main__":
	sys.exit(main())
