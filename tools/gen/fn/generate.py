def emitDnnOperationRoles(operations: list[tuple[str, dict]]) -> str:
	lines = [
	 "// AUTO-GENERATED by tools/gen/fn/generate.py — DO NOT EDIT.",
	 "// Source of truth: tools/gen/fn/schema/**.toml [ops.dnn].",
	 "// Regenerate via: python3 tools/gen/fn/generate.py --live",
	 "const DnnOpRole kDnnOpRoles[] = {",
	]
	for namespace, op in sorted(
	 operations, key=lambda item: (item[0], item[1]["name"])
	):
		dnn = op["dnn"]
		name = f"{namespace}::{op['name']}"
		requiredInput = dnn.get("epilogue_requires_input", 0xff)
		lines += [
		 "\t{",
		 f'\t\t.name = "{name}",',
		 f"\t\t.contractHash = 0x{operationContractHash(namespace, op):016x}ULL,",
		 f"\t\t.type = {_DNN_ROLE_CPP[dnn['role']]},",
		 f"\t\t.epilogue = {_DNN_EPILOGUE_CPP[dnn.get('epilogue', 'none')]},",
		 f"\t\t.epilogueRequiredInput = {requiredInput}U,",
		 "\t},",
		]
	lines += ["};", ""]
	return "\n".join(lines)


def writeDnnOperationRoles(
 schemaPaths: list[Path], outRoot: Path, *, dryRun: bool
) -> None:
	operations: list[tuple[str, dict]] = []
	for schemaPath in schemaPaths:
		with schemaPath.open("rb") as file:
			data = tomllib.load(file)
