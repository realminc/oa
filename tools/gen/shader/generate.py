#!/usr/bin/env python3
"""Compatibility entry point for the schema-owned operation generator.

Shader metadata is no longer generated by an independent directory scanner.
The normalized operation schema owns its Rust registry and Slang sources.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path


def main() -> None:
	repository = Path(__file__).resolve().parents[3]
	generator = repository / "tools/gen/fn/generate.py"
	os.execv(sys.executable, [sys.executable, str(generator), *sys.argv[1:]])


if __name__ == "__main__":
	main()
