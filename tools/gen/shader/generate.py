class KernelMetadata:
    """Metadata for a single kernel."""

    def __init__(self):
        self.module: str = ""
        self.entry: str = ""
        self.domain: str = ""
        self.op: str = ""
        self.variant: str = ""
        self.requirements: List[str] = []
        self.dtypes: List[str] = []
        self.layout: str = ""
        self.status: str = "experimental"


class ShaderGenerator:
    """Generates Rust metadata from Slang shaders"""

    def __init__(self, slang_root: Path, output_path: Path):
        self.slang_root = slang_root
        self.output_path = output_path
        self.kernels: List[KernelMetadata] = []

    def scan_slang_directory(self, directory: Path) -> List[Path]:
        """Scan for .slang files in directory"""
        return list(directory.rglob("*.slang"))

    def extract_attributes(self, slang_file: Path) -> List[KernelMetadata]:
        """Extract OA attributes from Slang file"""
        # TODO: Use Slang reflection API to extract attributes
        # For now, return empty list
        return []

    def generate_rust_code(self) -> str:
        """Generate Rust code for kernel metadata"""
        lines = [
            "// Generated by tools/gen/shader/generate.py",
            "// DO NOT EDIT MANUALLY",
            "",
            "use super::metadata::{Domain, KernelDesc, Op, CapabilitySet, DType};",
            "",
        ]

        for kernel in self.kernels:
            # Generate kernel descriptor
            kernel_name = self._rust_kernel_name(kernel)
            lines.append(f"pub static {kernel_name}: KernelDesc = KernelDesc {{")
            lines.append(f'    module: "{kernel.module}",')
            lines.append(f'    entry: "{kernel.entry}",')
            lines.append(f'    domain: Domain::{self._rust_domain(kernel.domain)},')
            lines.append(f'    op: Op::{self._rust_op(kernel.op)},')
            lines.append(f'    variant: "{kernel.variant}",')
            lines.append(f'    requirements: CapabilitySet::new(&{self._rust_requirements(kernel.requirements)}),')
            lines.append(f'    dtypes: &[{self._rust_dtypes(kernel.dtypes)}],')
            lines.append("};")
            lines.append("")

        return "\n".join(lines)

    def _rust_kernel_name(self, kernel: KernelMetadata) -> str:
        """Convert kernel metadata to Rust constant name"""
        parts = [kernel.domain.upper(), kernel.op.upper(), kernel.variant.upper()]
        return "_".join(parts)

    def _rust_domain(self, domain: str) -> str:
        """Convert domain string to Rust enum variant"""
        domain_map = {
            "matrix": "Matrix",
            "vision": "Vision",
            "ml": "Ml",
            "audio": "Audio",
            "video": "Video",
            "render": "Render",
        }
        return domain_map.get(domain.lower(), "Matrix")

    def _rust_op(self, op: str) -> str:
        """Convert op string to Rust enum variant"""
        # TODO: Map operation names to Rust enum variants
        return "Add"  # placeholder

    def _rust_requirements(self, requirements: List[str]) -> str:
        """Convert requirements to Rust code"""
        # TODO: Generate CapabilitySet construction
        return "[]"

    def _rust_dtypes(self, dtypes: List[str]) -> str:
        """Convert dtypes to Rust code"""
        dtype_map = {
            "f16": "DType::Float16",
            "f32": "DType::Float32",
        }
        return ", ".join([dtype_map.get(d, "DType::Float32") for d in dtypes])

    def run(self):
        """Main generation pipeline"""
        print(f"Scanning Slang directory: {self.slang_root}")
        slang_files = self.scan_slang_directory(self.slang_root)
        print(f"Found {len(slang_files)} Slang files")

        for slang_file in slang_files:
            kernels = self.extract_attributes(slang_file)
            self.kernels.extend(kernels)

        print(f"Extracted {len(self.kernels)} kernels")

        rust_code = self.generate_rust_code()
        self.output_path.write_text(rust_code)
        print(f"Generated Rust metadata to: {self.output_path}")


def main():
    """Entry point"""
    script_dir = Path(__file__).parent
    repo_root = script_dir.parent.parent.parent
    slang_root = repo_root / "src" / "slang"
    output_path = repo_root / "src" / "rs" / "shader" / "generated.rs"

    generator = ShaderGenerator(slang_root, output_path)
    generator.run()


if __name__ == "__main__":
    main()
