"""Generate paired beginner examples and their build/publication inventory."""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path, PurePosixPath
from typing import Any


REPO_ROOT_PATH = Path(__file__).resolve().parents[3]
if str(REPO_ROOT_PATH) not in sys.path:
	sys.path.insert(0, str(REPO_ROOT_PATH))

from tools.gen.io import writeGeneratedText


REPO_ROOT = REPO_ROOT_PATH
SCHEMA = Path(__file__).resolve().parent / "schema" / "examples.toml"
DEFAULT_OUTPUT = REPO_ROOT / "build" / "gen" / "example"
PUBLIC_MODULES = {"Audio", "Core", "Crypto", "Data", "Ml", "Ui", "Vision"}
ID_PATTERN = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")
NAME_PATTERN = re.compile(r"^[a-z][A-Za-z0-9]*$")
CPP_TARGET_PATTERN = re.compile(r"^[A-Z][A-Za-z0-9]*$")
GENERATED_CPP = "// AUTO-GENERATED by tools/gen/example/generate.py - DO NOT EDIT."
GENERATED_PYTHON = "# AUTO-GENERATED by tools/gen/example/generate.py - DO NOT EDIT."
GENERATED_JSON = "tools/gen/example/generate.py"


class ExampleError(ValueError):
	pass


def requireString(owner: dict[str, Any], key: str, context: str) -> str:
	value = owner.get(key)
	if not isinstance(value, str) or not value.strip():
		raise ExampleError(f"{context}: {key} must be a non-empty string")
	return value


def requireStrings(owner: dict[str, Any], key: str, context: str) -> list[str]:
	value = owner.get(key)
	if not isinstance(value, list) or not value or any(
		not isinstance(item, str) or not item.strip() for item in value
	):
		raise ExampleError(f"{context}: {key} must be a non-empty string list")
	return value


def requireNumbers(owner: dict[str, Any], key: str, context: str) -> list[int | float]:
	value = owner.get(key)
	if not isinstance(value, list) or len(value) < 2 or any(
		isinstance(item, bool) or not isinstance(item, (int, float)) for item in value
	):
		raise ExampleError(f"{context}: {key} must contain at least two numbers")
	return value


def safeRelative(value: str, context: str) -> PurePosixPath:
	path = PurePosixPath(value)
	if path.is_absolute() or not path.parts or ".." in path.parts:
		raise ExampleError(f"{context}: unsafe relative path {value!r}")
	return path


def number(owner: dict[str, Any], key: str, context: str) -> int | float:
	value = owner.get(key)
	if isinstance(value, bool) or not isinstance(value, (int, float)):
		raise ExampleError(f"{context}: {key} must be numeric")
	return value


def integer(owner: dict[str, Any], key: str, context: str) -> int:
	value = owner.get(key)
	if isinstance(value, bool) or not isinstance(value, int):
		raise ExampleError(f"{context}: {key} must be an integer")
	return value


def cppFloat(value: int | float) -> str:
	formatted = f"{float(value):.8g}"
	if "." not in formatted and "e" not in formatted.lower():
		formatted += ".0"
	return formatted + "F"


def pythonFloat(value: int | float) -> str:
	formatted = f"{float(value):.8g}"
	if "." not in formatted and "e" not in formatted.lower():
		formatted += ".0"
	return formatted


def cppShape(shape: list[int]) -> str:
	return "{" + ", ".join(str(dimension) for dimension in shape) + "}"


def pythonShape(shape: list[int]) -> str:
	return "[" + ", ".join(str(dimension) for dimension in shape) + "]"


def quoted(value: str) -> str:
	return json.dumps(value, ensure_ascii=False)


def stepForResult(example: dict[str, Any], result: str) -> dict[str, Any]:
	return next(step for step in example["steps"] if step.get("result") == result)


def assetInventory() -> set[str]:
	manifestPath = REPO_ROOT / "sdk" / "asset" / "manifest.toml"
	with manifestPath.open("rb") as stream:
		manifest = tomllib.load(stream)
	return {entry["path"] for entry in manifest.get("asset", [])}


def sourcePaths(example: dict[str, Any], context: str) -> tuple[str, str]:
	if example["generated"]:
		directory = requireString(example, "directory", context)
		stem = requireString(example, "stem", context)
		if not NAME_PATTERN.fullmatch(directory) or not NAME_PATTERN.fullmatch(stem):
			raise ExampleError(f"{context}: directory and stem must be lower camelCase")
		return (
			f"sdk/cpp/examples/{directory}/{stem}.cpp",
			f"sdk/py/examples/{directory}/{stem}.py",
		)
	return (
		requireString(example, "cppPath", context),
		requireString(example, "pythonPath", context),
	)


def validateShape(value: Any, context: str) -> list[int]:
	if not isinstance(value, list) or not value or any(
		isinstance(item, bool) or not isinstance(item, int) or item <= 0
		for item in value
	):
		raise ExampleError(f"{context}: shape must contain positive integers")
	return value


def requireVariable(
	variables: dict[str, str], owner: dict[str, Any], key: str,
	expectedKind: str, context: str,
) -> str:
	name = requireString(owner, key, context)
	if variables.get(name) != expectedKind:
		raise ExampleError(
			f"{context}: {key} references {name!r}, expected {expectedKind}"
		)
	return name


def declareVariable(
	variables: dict[str, str], owner: dict[str, Any], kind: str, context: str,
) -> str:
	name = requireString(owner, "result", context)
	if not NAME_PATTERN.fullmatch(name):
		raise ExampleError(f"{context}: result must be lower camelCase")
	if name in variables:
		raise ExampleError(f"{context}: duplicate result {name!r}")
	variables[name] = kind
	return name


def validateGenerated(example: dict[str, Any], context: str, assets: set[str]) -> None:
	steps = example.get("steps")
	checks = example.get("checks")
	if not isinstance(steps, list) or not steps:
		raise ExampleError(f"{context}: generated example requires steps")
	if not isinstance(checks, list) or not checks:
		raise ExampleError(f"{context}: generated example requires checks")
	declaredAssets = set(example.get("assets", []))
	if any(not isinstance(asset, str) for asset in declaredAssets):
		raise ExampleError(f"{context}: assets must be strings")
	for asset in declaredAssets:
		safeRelative(asset, context)
		if asset not in assets:
			raise ExampleError(f"{context}: asset is absent from sdk/asset/manifest.toml: {asset}")

	variables: dict[str, str] = {}
	for index, step in enumerate(steps):
		stepContext = f"{context}.steps[{index}]"
		if not isinstance(step, dict):
			raise ExampleError(f"{stepContext}: step must be a table")
		operation = requireString(step, "operation", stepContext)
		if operation in ("matrix.ones", "matrix.full"):
			declareVariable(variables, step, "Matrix", stepContext)
			validateShape(step.get("shape"), stepContext)
			if operation == "matrix.full":
				number(step, "value", stepContext)
		elif operation == "matrix.add":
			inputs = step.get("inputs")
			if not isinstance(inputs, list) or len(inputs) != 2:
				raise ExampleError(f"{stepContext}: matrix.add requires two inputs")
			for inputName in inputs:
				if not isinstance(inputName, str) or variables.get(inputName) != "Matrix":
					raise ExampleError(f"{stepContext}: matrix.add inputs must be matrices")
			declareVariable(variables, step, "Matrix", stepContext)
		elif operation == "bytes.asciiRows":
			rows = requireStrings(step, "values", stepContext)
			if any(not row.isascii() for row in rows):
				raise ExampleError(f"{stepContext}: values must be ASCII")
			if len({len(row.encode("ascii")) for row in rows}) != 1:
				raise ExampleError(f"{stepContext}: values must have equal byte lengths")
			declareVariable(variables, step, "ByteRows", stepContext)
		elif operation == "crypto.shake256":
			requireVariable(variables, step, "input", "ByteRows", stepContext)
			if integer(step, "digestBytes", stepContext) <= 0:
				raise ExampleError(f"{stepContext}: digestBytes must be positive")
			declareVariable(variables, step, "Matrix", stepContext)
		elif operation == "image.decodeAsset":
			path = requireString(step, "path", stepContext)
			if path not in declaredAssets:
				raise ExampleError(f"{stepContext}: decoded asset must be declared by the example")
			if requireString(step, "format", stepContext) not in {"Rgb", "Rgba"}:
				raise ExampleError(f"{stepContext}: unsupported beginner image format")
			declareVariable(variables, step, "Image", stepContext)
		elif operation == "image.resize":
			requireVariable(variables, step, "input", "Image", stepContext)
			if integer(step, "width", stepContext) <= 0 or integer(step, "height", stepContext) <= 0:
				raise ExampleError(f"{stepContext}: image extent must be positive")
			declareVariable(variables, step, "Image", stepContext)
		elif operation == "image.grayscale":
			requireVariable(variables, step, "input", "Image", stepContext)
			declareVariable(variables, step, "Image", stepContext)
		elif operation == "image.save":
			requireVariable(variables, step, "input", "Image", stepContext)
			safeRelative(requireString(step, "path", stepContext), stepContext)
			quality = integer(step, "quality", stepContext)
			if not 1 <= quality <= 100:
				raise ExampleError(f"{stepContext}: quality must be in [1, 100]")
			declareVariable(variables, step, "Path", stepContext)
		elif operation == "plot.lineFigure":
			requireString(step, "title", stepContext)
			requireString(step, "xLabel", stepContext)
			requireString(step, "yLabel", stepContext)
			if requireString(step, "theme", stepContext) not in {"Dark", "Light"}:
				raise ExampleError(f"{stepContext}: unsupported plot theme")
			if integer(step, "width", stepContext) <= 0 or integer(step, "height", stepContext) <= 0:
				raise ExampleError(f"{stepContext}: figure extent must be positive")
			requireNumbers(step, "values", stepContext)
			declareVariable(variables, step, "Figure", stepContext)
		elif operation == "plot.render":
			requireVariable(variables, step, "input", "Figure", stepContext)
			declareVariable(variables, step, "Image", stepContext)
		elif operation == "audio.decodeAsset":
			path = requireString(step, "path", stepContext)
			if path not in declaredAssets:
				raise ExampleError(f"{stepContext}: decoded asset must be declared by the example")
			declareVariable(variables, step, "Audio", stepContext)
		elif operation in ("audio.toMono", "audio.normalize", "audio.fade", "audio.saturate", "audio.reverb"):
			requireVariable(variables, step, "input", "Audio", stepContext)
			if operation == "audio.normalize":
				number(step, "targetDb", stepContext)
			elif operation == "audio.fade":
				if integer(step, "fadeInSamples", stepContext) < 0 or integer(step, "fadeOutSamples", stepContext) < 0:
					raise ExampleError(f"{stepContext}: fade sample counts must be non-negative")
			elif operation == "audio.saturate":
				number(step, "driveDb", stepContext)
				mix = number(step, "mix", stepContext)
				if not 0.0 <= float(mix) <= 1.0:
					raise ExampleError(f"{stepContext}: mix must be in [0, 1]")
			elif operation == "audio.reverb":
				decaySeconds = float(number(step, "decaySeconds", stepContext))
				wet = float(number(step, "wet", stepContext))
				if not 0.1 <= decaySeconds <= 10.0 or not 0.0 <= wet <= 1.0:
					raise ExampleError(f"{stepContext}: reverb decaySeconds or wet is outside the public API range")
			declareVariable(variables, step, "Audio", stepContext)
		elif operation == "audio.saveWavF32":
			requireVariable(variables, step, "input", "Audio", stepContext)
			safeRelative(requireString(step, "path", stepContext), stepContext)
			declareVariable(variables, step, "Path", stepContext)
		else:
			raise ExampleError(f"{stepContext}: unsupported operation {operation!r}")

	for index, check in enumerate(checks):
		checkContext = f"{context}.checks[{index}]"
		if not isinstance(check, dict):
			raise ExampleError(f"{checkContext}: check must be a table")
		kind = requireString(check, "kind", checkContext)
		if kind == "matrixAllClose":
			requireVariable(variables, check, "input", "Matrix", checkContext)
			if integer(check, "count", checkContext) <= 0:
				raise ExampleError(f"{checkContext}: count must be positive")
			number(check, "value", checkContext)
			if float(number(check, "tolerance", checkContext)) <= 0.0:
				raise ExampleError(f"{checkContext}: tolerance must be positive")
		elif kind == "shake256CpuOracle":
			requireVariable(variables, check, "input", "ByteRows", checkContext)
			requireVariable(variables, check, "output", "Matrix", checkContext)
		elif kind == "imageMetadata":
			requireVariable(variables, check, "input", "Image", checkContext)
			if integer(check, "width", checkContext) <= 0 or integer(check, "height", checkContext) <= 0:
				raise ExampleError(f"{checkContext}: image extent must be positive")
			if requireString(check, "format", checkContext) not in {"Gray", "Rgb", "Rgba"}:
				raise ExampleError(f"{checkContext}: unsupported image format")
		elif kind == "audioMetadata":
			requireVariable(variables, check, "input", "Audio", checkContext)
			if integer(check, "sampleRate", checkContext) <= 0 or integer(check, "channels", checkContext) <= 0:
				raise ExampleError(f"{checkContext}: audio metadata must be positive")
		elif kind == "fileExists":
			requireVariable(variables, check, "input", "Path", checkContext)
		elif kind == "audioTail":
			requireVariable(variables, check, "input", "Audio", checkContext)
			requireVariable(variables, check, "source", "Audio", checkContext)
			if integer(check, "tailMilliseconds", checkContext) <= 0:
				raise ExampleError(f"{checkContext}: tailMilliseconds must be positive")
		else:
			raise ExampleError(f"{checkContext}: unsupported check {kind!r}")

	preview = example.get("preview")
	if preview is not None:
		previewContext = f"{context}.preview"
		if not isinstance(preview, dict):
			raise ExampleError(f"{previewContext}: preview must be a table")
		requireVariable(variables, preview, "input", "Path", previewContext)
		requireString(preview, "title", previewContext)
		if requireString(preview, "mode", previewContext) not in {"audio", "image", "video"}:
			raise ExampleError(f"{previewContext}: unsupported Viewer mode")
		for key in ("width", "height"):
			if integer(preview, key, previewContext) <= 0:
				raise ExampleError(f"{previewContext}: {key} must be positive")


def validatePresentation(example: dict[str, Any], context: str, assets: set[str]) -> None:
	presentations = example.get("presentation")
	if presentations is None:
		return
	if not isinstance(presentations, list) or not presentations:
		raise ExampleError(f"{context}: presentation must be a non-empty table list")
	declaredAssets = set(example.get("assets", []))
	for presentationIndex, presentation in enumerate(presentations):
		presentationContext = f"{context}.presentation[{presentationIndex}]"
		if not isinstance(presentation, dict):
			raise ExampleError(f"{presentationContext}: presentation must be a table")
		kind = requireString(presentation, "kind", presentationContext)
		requireString(presentation, "title", presentationContext)
		requireString(presentation, "description", presentationContext)
		if kind == "terminalOutput":
			for key in ("filename", "language", "generatedBy", "code"):
				requireString(presentation, key, presentationContext)
			continue
		if kind == "viewerCapture":
			asset = requireString(presentation, "asset", presentationContext)
			safeRelative(asset, presentationContext)
			if asset not in declaredAssets or asset not in assets:
				raise ExampleError(f"{presentationContext}: Viewer capture must be a declared checked asset")
			for key in ("mimeType", "alt", "generatedBy"):
				requireString(presentation, key, presentationContext)
			for key in ("width", "height"):
				if integer(presentation, key, presentationContext) <= 0:
					raise ExampleError(f"{presentationContext}: {key} must be positive")
			continue
		if kind == "imageGallery":
			items = presentation.get("items")
			if not isinstance(items, list) or not items:
				raise ExampleError(f"{presentationContext}: imageGallery requires at least one item")
			roles: set[str] = set()
			for itemIndex, item in enumerate(items):
				itemContext = f"{presentationContext}.items[{itemIndex}]"
				if not isinstance(item, dict):
					raise ExampleError(f"{itemContext}: item must be a table")
				role = requireString(item, "role", itemContext)
				if role in roles:
					raise ExampleError(f"{itemContext}: image roles must be unique")
				roles.add(role)
				for key in ("label", "description", "mimeType", "alt", "generatedBy"):
					requireString(item, key, itemContext)
				asset = requireString(item, "asset", itemContext)
				safeRelative(asset, itemContext)
				if asset not in declaredAssets or asset not in assets:
					raise ExampleError(f"{itemContext}: image must be a declared checked asset")
				for key in ("width", "height"):
					if integer(item, key, itemContext) <= 0:
						raise ExampleError(f"{itemContext}: {key} must be positive")
			continue
		if kind != "audioComparison":
			raise ExampleError(f"{presentationContext}: unsupported presentation kind")
		items = presentation.get("items")
		if not isinstance(items, list) or len(items) != 2:
			raise ExampleError(f"{presentationContext}: audioComparison requires two items")
		roles: set[str] = set()
		for itemIndex, item in enumerate(items):
			itemContext = f"{presentationContext}.items[{itemIndex}]"
			if not isinstance(item, dict):
				raise ExampleError(f"{itemContext}: item must be a table")
			role = requireString(item, "role", itemContext)
			if role not in {"source", "processed"} or role in roles:
				raise ExampleError(f"{itemContext}: roles must be unique source/processed values")
			roles.add(role)
			for key in ("label", "description", "mimeType", "fallbackMimeType", "generatedBy"):
				requireString(item, key, itemContext)
			for key in ("asset", "fallbackAsset"):
				asset = requireString(item, key, itemContext)
				safeRelative(asset, itemContext)
				if asset not in declaredAssets:
					raise ExampleError(f"{itemContext}: {key} must be declared by the example")
				if asset not in assets:
					raise ExampleError(f"{itemContext}: {asset} is absent from sdk/asset/manifest.toml")
			for key in ("sampleRate", "channelCount", "sampleCount"):
				if integer(item, key, itemContext) <= 0:
					raise ExampleError(f"{itemContext}: {key} must be positive")
			if float(number(item, "durationSeconds", itemContext)) <= 0.0:
				raise ExampleError(f"{itemContext}: durationSeconds must be positive")
		if roles != {"source", "processed"}:
			raise ExampleError(f"{presentationContext}: audioComparison requires source and processed roles")


def loadExamples(schemaPath: Path) -> list[dict[str, Any]]:
	with schemaPath.open("rb") as stream:
		schema = tomllib.load(stream)
	if schema.get("schemaVersion") != 1:
		raise ExampleError(f"{schemaPath}: schemaVersion must be 1")
	examples = schema.get("examples")
	if not isinstance(examples, list) or not examples:
		raise ExampleError(f"{schemaPath}: no [[examples]] entries")

	assets = assetInventory()
	ids: set[str] = set()
	targets: set[str] = set()
	paths: set[str] = set()
	for index, example in enumerate(examples):
		context = f"{schemaPath}:examples[{index}]"
		if not isinstance(example, dict):
			raise ExampleError(f"{context}: example must be a table")
		exampleId = requireString(example, "id", context)
		if not ID_PATTERN.fullmatch(exampleId) or exampleId in ids:
			raise ExampleError(f"{context}: invalid or duplicate id {exampleId!r}")
		ids.add(exampleId)
		module = requireString(example, "module", context)
		if module not in PUBLIC_MODULES:
			raise ExampleError(f"{context}: unsupported module {module!r}")
		for key in ("title", "summary", "capability", "expectedOutput"):
			if key != "expectedOutput" or example.get("generated"):
				requireString(example, key, context)
		target = requireString(example, "cppTarget", context)
		if not CPP_TARGET_PATTERN.fullmatch(target) or target in targets:
			raise ExampleError(f"{context}: invalid or duplicate C++ target {target!r}")
		targets.add(target)
		requireString(example, "pythonProfile", context)
		requireStrings(example, "cppSymbols", context)
		requireStrings(example, "pythonSymbols", context)
		if not isinstance(example.get("generated"), bool):
			raise ExampleError(f"{context}: generated must be boolean")
		validatePresentation(example, context, assets)
		cppPath, pythonPath = sourcePaths(example, context)
		for sourcePath, prefix, suffix in (
			(cppPath, "sdk/cpp/examples/", ".cpp"),
			(pythonPath, "sdk/py/examples/", ".py"),
		):
			safeRelative(sourcePath, context)
			if not sourcePath.startswith(prefix) or not sourcePath.endswith(suffix):
				raise ExampleError(f"{context}: invalid example source path {sourcePath}")
			if sourcePath in paths:
				raise ExampleError(f"{context}: duplicate source path {sourcePath}")
			paths.add(sourcePath)
			if not example["generated"] and not (REPO_ROOT / sourcePath).is_file():
				raise ExampleError(f"{context}: missing existing source {sourcePath}")
		if example["generated"]:
			validateGenerated(example, context, assets)
	return examples


def generatedHeader(comment: str, schemaPath: Path) -> list[str]:
	return [
		comment,
		f"{comment[:2].rstrip()} Source: {schemaPath.relative_to(REPO_ROOT).as_posix()}",
	]


def emitCpp(example: dict[str, Any], schemaPath: Path) -> str:
	hasMatrix = any(step["operation"].startswith("matrix.") for step in example["steps"])
	hasAudio = any(step["operation"].startswith("audio.") for step in example["steps"])
	hasCrypto = any(step["operation"].startswith("crypto.") for step in example["steps"])
	hasImage = any(step["operation"].startswith("image.") for step in example["steps"])
	hasPlot = any(step["operation"].startswith("plot.") for step in example["steps"])
	preview = example.get("preview")
	lines = [GENERATED_CPP, f"// Source: {schemaPath.relative_to(REPO_ROOT).as_posix()}",
		f"// OA_DOC_BEGIN: {example['id']}", "#include <oa/oa.h>", ""]
	if hasMatrix or hasCrypto or hasPlot:
		lines.append("#include <array>")
	if hasMatrix:
		lines.append("#include <cmath>")
	if hasCrypto:
		lines.append("#include <cstring>")
	lines.extend(["#include <cstdio>", "#include <utility>", ""])
	if preview is not None and hasPlot:
		lines.append(
			f'OA_MAIN_MODE("{example["cppTarget"]}", argc > 1 '
			'and oa::StringView(argv[1]) == "--preview" '
			'? oa::PresentationMode::Swapchain : oa::PresentationMode::Headless) {'
		)
	elif preview is not None:
		lines.append(f'OA_MAIN_PREVIEW("{example["cppTarget"]}") {{')
	else:
		lines.append(f'OA_MAIN("{example["cppTarget"]}") {{')

	for step in example["steps"]:
		op = step["operation"]
		result = step["result"]
		if op == "matrix.ones":
			lines.append(f"\tauto {result} = oa::FnMatrix::ones({cppShape(step['shape'])});")
		elif op == "matrix.full":
			lines.append(f"\tauto {result} = oa::FnMatrix::full({cppShape(step['shape'])}, {cppFloat(step['value'])});")
		elif op == "matrix.add":
			lines.append(f"\tauto {result} = oa::FnMatrix::add({step['inputs'][0]}, {step['inputs'][1]});")
		elif op == "bytes.asciiRows":
			rows = step["values"]
			values = [byte for row in rows for byte in row.encode("ascii")]
			lines.extend([
				f"\tconstexpr std::array<oa::U8, {len(values)}> {result}Bytes{{",
				"\t\t" + ", ".join(f"{value}U" for value in values),
				"\t};",
				f"\tauto {result} = oa::FnMatrix::fromBytes(",
				f"\t\toa::Span<const oa::U8>({result}Bytes.data(), {result}Bytes.size()),",
				f"\t\t{{{len(rows)}, {len(rows[0].encode('ascii'))}}},",
				"\t\toa::ScalarType::UInt8);",
			])
		elif op == "crypto.shake256":
			lines.append(
				f"\tauto {result} = oa::FnHash::shake256({step['input']}, {step['digestBytes']}U);"
			)
		elif op == "image.decodeAsset":
			lines.extend([
				f"\tauto {result}Result = oa::FnImage::decodeFile(",
				f"\t\toa::Paths::asset({quoted(step['path'])}), oa::ImageFormat::{step['format']});",
				f"\tif (not {result}Result.isOk()) return 1;",
				f"\tauto {result} = std::move({result}Result).getValue();",
			])
		elif op == "image.resize":
			lines.append(
				f"\tauto {result} = oa::FnImage::resize({step['input']}, {step['width']}U, {step['height']}U);"
			)
		elif op == "image.grayscale":
			lines.append(f"\tauto {result} = oa::FnImage::grayscale({step['input']});")
		elif op == "image.save":
			lines.extend([
				f"\tconst oa::Path {result} = oa::Paths::var({quoted(step['path'])});",
				f"\tif (not oa::Filesystem::createDirectories({result}.parentPath()).isOk()) return 1;",
				f"\tif (not oa::FnImage::saveFile({result}, {step['input']}, {step['quality']}U).isOk()) return 1;",
			])
		elif op == "plot.lineFigure":
			lines.extend([
				f"\toa::plot::Figure {result}({{",
				f"\t\t.title = {quoted(step['title'])},",
				f"\t\t.width = {step['width']}U,",
				f"\t\t.height = {step['height']}U,",
				f"\t\t.theme = oa::plot::Theme::{step['theme']},",
				"\t});",
				f"\tconstexpr std::array<oa::F32, {len(step['values'])}> {result}Values{{",
				"\t\t" + ", ".join(cppFloat(value) for value in step["values"]),
				"\t};",
				f"\t{result}.ax(0, 0).xLabel({quoted(step['xLabel'])});",
				f"\t{result}.ax(0, 0).yLabel({quoted(step['yLabel'])});",
				f"\t{result}.ax(0, 0).plot({result}Values);",
			])
		elif op == "plot.render":
			lines.extend([
				f"\tauto {result}Result = {step['input']}.render(engine);",
				f"\tif (not {result}Result.isOk()) return 1;",
				f"\tauto {result} = std::move({result}Result).getValue();",
			])
		elif op == "audio.decodeAsset":
			lines.extend([
				f"\tauto {result}Result = oa::FnAudio::decodeFile(oa::Paths::asset(\"{step['path']}\"));",
				f"\tif (not {result}Result.isOk()) {{",
				"\t\treturn 1;",
				"\t}",
				f"\tauto {result} = std::move({result}Result).getValue();",
			])
		elif op == "audio.toMono":
			lines.append(f"\tauto {result} = oa::FnAudio::toMono({step['input']});")
		elif op == "audio.normalize":
			lines.append(f"\tauto {result} = oa::FnAudio::normalize({step['input']}, {cppFloat(step['targetDb'])});")
		elif op == "audio.fade":
			lines.append(
				f"\tauto {result} = oa::FnAudio::fade({step['input']}, "
				f"{step['fadeInSamples']}U, {step['fadeOutSamples']}U);"
			)
		elif op == "audio.saturate":
			lines.append(
				f"\tauto {result} = oa::FnAudio::saturate({step['input']}, "
				f"{cppFloat(step['driveDb'])}, {cppFloat(step['mix'])});"
			)
		elif op == "audio.reverb":
			lines.append(
				f"\tauto {result} = oa::FnAudio::reverb({step['input']}, "
				f"{cppFloat(step['decaySeconds'])}, {cppFloat(step['wet'])});"
			)
		elif op == "audio.saveWavF32":
			lines.extend([
				f"\tconst oa::Path {result} = oa::Paths::var(\"{step['path']}\");",
				f"\tif (not oa::Filesystem::createDirectories({result}.parentPath()).isOk()) {{",
				"\t\treturn 1;",
				"\t}",
				f"\tif (not oa::FnAudio::saveWavF32({result}, {step['input']}).isOk()) {{",
				"\t\treturn 1;",
				"\t}",
			])
		lines.append("")

	for check in example["checks"]:
		if check["kind"] == "matrixAllClose":
			lines.extend([
				f"\tstd::array<oa::F32, {check['count']}> values{{}};",
				f"\tif (not oa::FnMatrix::copyToHost({check['input']}, values.data(), sizeof(values)).isOk()) {{",
				"\t\treturn 1;",
				"\t}",
				"\tfor (const oa::F32 value : values) {",
				f"\t\tif (std::abs(value - {cppFloat(check['value'])}) > {cppFloat(check['tolerance'])}) {{",
				"\t\t\treturn 1;",
				"\t\t}",
				"\t}",
			])
		elif check["kind"] == "shake256CpuOracle":
			inputStep = stepForResult(example, check["input"])
			outputStep = stepForResult(example, check["output"])
			rowCount = len(inputStep["values"])
			rowBytes = len(inputStep["values"][0].encode("ascii"))
			digestBytes = outputStep["digestBytes"]
			totalBytes = rowCount * digestBytes
			lines.extend([
				f"\tstd::array<oa::U8, {totalBytes}> gpu{{}};",
				f"\tstd::array<oa::U8, {totalBytes}> cpu{{}};",
				f"\tif (not oa::FnMatrix::copyToHost({check['output']}, gpu.data(), gpu.size()).isOk()) return 1;",
				f"\tfor (oa::Usize row = 0; row < {rowCount}U; ++row) {{",
				"\t\toa::shake256(",
				f"\t\t\t{check['input']}Bytes.data() + row * {rowBytes}U, {rowBytes}U,",
				f"\t\t\tcpu.data() + row * {digestBytes}U, {digestBytes}U);",
				"\t}",
				"\tif (std::memcmp(gpu.data(), cpu.data(), gpu.size()) != 0) return 1;",
			])
		elif check["kind"] == "imageMetadata":
			lines.extend([
				f"\tif (not {check['input']}.validate()) return 1;",
				f"\tif ({check['input']}.width() != {check['width']} or {check['input']}.height() != {check['height']}) return 1;",
				f"\tif ({check['input']}.format() != oa::ImageFormat::{check['format']}) return 1;",
			])
		elif check["kind"] == "audioMetadata":
			lines.extend([
				f"\tif (not {check['input']}.validate()) return 1;",
				f"\tif ({check['input']}.sampleRate() != {check['sampleRate']}U) return 1;",
				f"\tif ({check['input']}.channels() != {check['channels']}) return 1;",
			])
		elif check["kind"] == "fileExists":
			lines.append(f"\tif (not oa::Filesystem::isFile({check['input']})) return 1;")
		elif check["kind"] == "audioTail":
			lines.extend([
				f"\tif ({check['input']}.samples() != {check['source']}.samples()",
				f"\t\t+ static_cast<oa::I64>({check['input']}.sampleRate())",
				f"\t\t\t* {check['tailMilliseconds']} / 1'000) {{",
				"\t\treturn 1;",
				"\t}",
			])
	lines.append("")
	if hasAudio:
		output = next(step["result"] for step in example["steps"] if step["operation"] == "audio.saveWavF32")
		lines.append(f"\tstd::printf(\"{example['expectedOutput']} %s\\n\", {output}.cStr());")
	elif hasImage:
		output = next(step["result"] for step in example["steps"] if step["operation"] == "image.save")
		lines.append(f"\tstd::printf(\"{example['expectedOutput']} %s\\n\", {output}.cStr());")
	else:
		lines.append(f"\tstd::puts(\"{example['expectedOutput']}\");")
	if preview is not None:
		previewStep = next(step for step in example["steps"] if step["result"] == preview["input"])
		viewerMode = preview["mode"].capitalize()
		lines.extend([
			"",
			'\tif (argc > 1 and oa::StringView(argv[1]) == "--preview") {',
			"\t\toa::ViewerConfig previewConfig;",
			f"\t\tpreviewConfig.mode = oa::ViewerMode::{viewerMode};",
			f'\t\tpreviewConfig.title = "{preview["title"]}";',
			f'\t\tpreviewConfig.width = {preview["width"]}U;',
			f'\t\tpreviewConfig.height = {preview["height"]}U;',
			f'\t\tif (not oa::Viewer::preview(engine, oa::Paths::var("{previewStep["path"]}").string(),',
			"\t\t\tpreviewConfig).isOk()) {",
			"\t\t\treturn 1;",
			"\t\t}",
			"\t}",
		])
	lines.append("\treturn 0;")
	lines.extend(["}", f"// OA_DOC_END: {example['id']}", ""])
	return "\n".join(lines)


def emitPython(example: dict[str, Any], schemaPath: Path) -> str:
	lines = [GENERATED_PYTHON, f"# Source: {schemaPath.relative_to(REPO_ROOT).as_posix()}",
		f"# OA_DOC_BEGIN: {example['id']}"]
	if any(step["operation"].startswith("crypto.") for step in example["steps"]):
		lines.extend(["import hashlib", ""])
	if example.get("preview") is not None:
		lines.extend(["import sys", ""])
	lines.extend(["import oa", ""])
	for step in example["steps"]:
		op = step["operation"]
		result = step["result"]
		if op == "matrix.ones":
			lines.append(f"{result} = oa.FnMatrix.ones({pythonShape(step['shape'])})")
		elif op == "matrix.full":
			lines.append(f"{result} = oa.FnMatrix.full({pythonShape(step['shape'])}, {pythonFloat(step['value'])})")
		elif op == "matrix.add":
			lines.append(f"{result} = oa.FnMatrix.add({step['inputs'][0]}, {step['inputs'][1]})")
		elif op == "bytes.asciiRows":
			rows = ", ".join(f"b{quoted(row)}" for row in step["values"])
			rowBytes = len(step["values"][0].encode("ascii"))
			lines.extend([
				f"{result}Rows = [{rows}]",
				f"{result} = oa.FnMatrix.fromBytes(",
				f"\tlist(b\"\".join({result}Rows)),",
				f"\t[{len(step['values'])}, {rowBytes}],",
				"\toa.ScalarType.UInt8,",
				")",
			])
		elif op == "crypto.shake256":
			lines.append(f"{result} = oa.FnHash.shake256({step['input']}, {step['digestBytes']})")
		elif op == "image.decodeAsset":
			lines.append(
				f"{result} = oa.FnImage.decodeFile(oa.Paths.asset({quoted(step['path'])}), oa.ImageFormat.{step['format']})"
			)
		elif op == "image.resize":
			lines.append(f"{result} = oa.FnImage.resize({step['input']}, {step['width']}, {step['height']})")
		elif op == "image.grayscale":
			lines.append(f"{result} = oa.FnImage.grayscale({step['input']})")
		elif op == "image.save":
			lines.extend([
				f"{result} = oa.Paths.var({quoted(step['path'])})",
				f"oa.Filesystem.createDirectories({result}.parentPath())",
				f"oa.FnImage.saveFile({result}, {step['input']}, {step['quality']})",
			])
		elif op == "plot.lineFigure":
			lines.extend([
				f"{result}Config = oa.plot.FigureConfig()",
				f"{result}Config.title = {quoted(step['title'])}",
				f"{result}Config.width = {step['width']}",
				f"{result}Config.height = {step['height']}",
				f"{result}Config.theme = oa.plot.Theme.{step['theme']}",
				f"{result} = oa.plot.Figure({result}Config)",
				f"{result}.ax(0, 0).xLabel({quoted(step['xLabel'])})",
				f"{result}.ax(0, 0).yLabel({quoted(step['yLabel'])})",
				f"{result}.ax(0, 0).plot({step['values']!r})",
			])
		elif op == "plot.render":
			lines.append(f"{result} = {step['input']}.render()")
		elif op == "audio.decodeAsset":
			lines.append(f"{result} = oa.FnAudio.decodeFile(oa.Paths.asset(\"{step['path']}\"))")
		elif op == "audio.toMono":
			lines.append(f"{result} = oa.FnAudio.toMono({step['input']})")
		elif op == "audio.normalize":
			lines.append(f"{result} = oa.FnAudio.normalize({step['input']}, {pythonFloat(step['targetDb'])})")
		elif op == "audio.fade":
			lines.append(
				f"{result} = oa.FnAudio.fade({step['input']}, "
				f"{step['fadeInSamples']}, {step['fadeOutSamples']})"
			)
		elif op == "audio.saturate":
			lines.append(
				f"{result} = oa.FnAudio.saturate({step['input']}, "
				f"{pythonFloat(step['driveDb'])}, {pythonFloat(step['mix'])})"
			)
		elif op == "audio.reverb":
			lines.append(
				f"{result} = oa.FnAudio.reverb({step['input']}, "
				f"{pythonFloat(step['decaySeconds'])}, {pythonFloat(step['wet'])})"
			)
		elif op == "audio.saveWavF32":
			lines.extend([
				f"{result} = oa.Paths.var(\"{step['path']}\")",
				f"oa.Filesystem.createDirectories({result}.parentPath())",
				f"oa.FnAudio.saveWavF32({result}, {step['input']})",
			])
		lines.append("")
	for check in example["checks"]:
		if check["kind"] == "matrixAllClose":
			lines.extend([
				f"values = oa.FnMatrix.copyToHost({check['input']})",
				f"assert len(values) == {check['count']}",
				f"assert all(abs(value - {pythonFloat(check['value'])}) <= {pythonFloat(check['tolerance'])} for value in values)",
			])
		elif check["kind"] == "shake256CpuOracle":
			outputStep = stepForResult(example, check["output"])
			lines.extend([
				f"gpu = bytes(oa.FnMatrix.copyToHost({check['output']}))",
				f"cpu = b\"\".join(hashlib.shake_256(row).digest({outputStep['digestBytes']}) for row in {check['input']}Rows)",
				"assert gpu == cpu",
			])
		elif check["kind"] == "imageMetadata":
			lines.extend([
				f"assert {check['input']}.validate()",
				f"assert {check['input']}.width() == {check['width']}",
				f"assert {check['input']}.height() == {check['height']}",
				f"assert {check['input']}.format() == oa.ImageFormat.{check['format']}",
			])
		elif check["kind"] == "audioMetadata":
			lines.extend([
				f"assert {check['input']}.isValid()",
				f"assert {check['input']}.sampleRate == {check['sampleRate']}",
				f"assert {check['input']}.channelCount == {check['channels']}",
			])
		elif check["kind"] == "fileExists":
			lines.append(f"assert oa.Filesystem.isFile({check['input']})")
		elif check["kind"] == "audioTail":
			lines.append(
				f"assert {check['input']}.sampleCount == {check['source']}.sampleCount "
				f"+ {check['input']}.sampleRate * {check['tailMilliseconds']} // 1000"
			)
	lines.append("")
	if any(step["operation"] == "audio.saveWavF32" for step in example["steps"]):
		output = next(step["result"] for step in example["steps"] if step["operation"] == "audio.saveWavF32")
		lines.append(f"print(f\"{example['expectedOutput']} {{{output}}}\")")
	elif any(step["operation"] == "image.save" for step in example["steps"]):
		output = next(step["result"] for step in example["steps"] if step["operation"] == "image.save")
		lines.append(f"print(f\"{example['expectedOutput']} {{{output}}}\")")
	else:
		lines.append(f"print(\"{example['expectedOutput']}\")")
	preview = example.get("preview")
	if preview is not None:
		lines.extend([
			"",
			'if "--preview" in sys.argv:',
			f'\toa.Viewer.preview({preview["input"]}, title="{preview["title"]}", width={preview["width"]}, height={preview["height"]})',
		])
	lines.extend([f"# OA_DOC_END: {example['id']}", ""])
	return "\n".join(lines)


def emitCmake(examples: list[dict[str, Any]], schemaPath: Path) -> str:
	lines = [
		"# AUTO-GENERATED by tools/gen/example/generate.py - DO NOT EDIT.",
		f"# Source: {schemaPath.relative_to(REPO_ROOT).as_posix()}",
		"",
	]
	for example in examples:
		if not example["generated"]:
			continue
		cppPath, _ = sourcePaths(example, example["id"])
		relative = PurePosixPath(cppPath).relative_to("sdk/cpp/examples")
		registration = (
			f"oa_add_example({example['cppTarget']} {relative.as_posix()} {example['directory']})"
		)
		if example["module"] == "Crypto":
			lines.extend(["if(OA_BUILD_CRYPTO)", f"\t{registration}", "endif()"])
		else:
			lines.append(registration)
	lines.append("")
	return "\n".join(lines)


def emitPythonTests(examples: list[dict[str, Any]], schemaPath: Path) -> str:
	lines = [
		GENERATED_PYTHON,
		f"# Source: {schemaPath.relative_to(REPO_ROOT).as_posix()}",
		"",
		"from pathlib import Path",
		"",
		"import pytest",
		"",
		"from example_runner import runExample",
		"",
		"",
	]
	for example in examples:
		if not example["generated"]:
			continue
		_, pythonPath = sourcePaths(example, example["id"])
		profile = example["pythonProfile"]
		if "crypto" in profile:
			lines.append("@pytest.mark.oa_crypto")
		if "gpu" in profile:
			lines.append("@pytest.mark.oa_gpu")
		functionName = "test_" + example["id"].replace("-", "_")
		lines.extend([
			f"def {functionName}(tmp_path: Path):",
			f"\toutput = runExample(\"{pythonPath}\", tmp_path)",
			f"\tassert \"{example['expectedOutput']}\" in output",
			"",
			"",
		])
	return "\n".join(lines).rstrip() + "\n"


def manifestEntry(example: dict[str, Any], context: str) -> dict[str, Any]:
	cppPath, pythonPath = sourcePaths(example, context)
	entry: dict[str, Any] = {
		"id": example["id"],
		"title": example["title"],
		"summary": example["summary"],
		"module": example["module"],
		"capability": example["capability"],
	}
	if example.get("assets"):
		entry["assets"] = example["assets"]
	if example.get("presentation"):
		entry["presentation"] = example["presentation"]
	entry["cpp"] = {
		"path": cppPath,
		"target": example["cppTarget"],
		"symbols": example["cppSymbols"],
	}
	entry["python"] = {
		"path": pythonPath,
		"profile": example["pythonProfile"],
		"symbols": example["pythonSymbols"],
	}
	return entry


def emitManifest(examples: list[dict[str, Any]]) -> str:
	return json.dumps({
		"schema": 2,
		"generatedBy": GENERATED_JSON,
		"examples": [manifestEntry(example, example["id"]) for example in examples],
	}, indent=2, ensure_ascii=False) + "\n"


def outputMap(examples: list[dict[str, Any]], schemaPath: Path) -> dict[Path, str]:
	outputs: dict[Path, str] = {}
	for example in examples:
		if not example["generated"]:
			continue
		cppPath, pythonPath = sourcePaths(example, example["id"])
		outputs[Path(cppPath)] = emitCpp(example, schemaPath)
		outputs[Path(pythonPath)] = emitPython(example, schemaPath)
	outputs[Path("sdk/cpp/examples/gen/examples.cmake")] = emitCmake(examples, schemaPath)
	outputs[Path("test/py/examples/test_generated_examples.py")] = emitPythonTests(examples, schemaPath)
	outputs[Path("sdk/examples.json")] = emitManifest(examples)
	return outputs


def removeStale(root: Path, expected: set[Path], *, dryRun: bool) -> None:
	for base in (
		root / "sdk" / "cpp" / "examples",
		root / "sdk" / "py" / "examples",
		root / "test" / "py" / "examples",
	):
		if not base.exists():
			continue
		for candidate in base.rglob("*"):
			if not candidate.is_file() or candidate in expected:
				continue
			try:
				firstLine = candidate.open(encoding="utf-8").readline().rstrip("\r\n")
			except (OSError, UnicodeError):
				continue
			if firstLine not in (GENERATED_CPP, GENERATED_PYTHON, "# AUTO-GENERATED by tools/gen/example/generate.py - DO NOT EDIT."):
				continue
			if dryRun:
				print(f"exampleGen: would remove stale {candidate}")
			else:
				candidate.unlink()
				print(f"exampleGen: removed stale {candidate}")


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--schema", type=Path, default=SCHEMA)
	parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
	parser.add_argument("--live", action="store_true")
	parser.add_argument("--dry-run", dest="dryRun", action="store_true")
	args = parser.parse_args()

	try:
		examples = loadExamples(args.schema)
		outputs = outputMap(examples, args.schema)
	except (ExampleError, OSError, tomllib.TOMLDecodeError) as error:
		print(f"exampleGen: ERROR: {error}", file=sys.stderr)
		return 1

	root = REPO_ROOT if args.live else args.out
	if args.live:
		print("exampleGen: LIVE MODE - updating generated SDK examples")
	expected = {root / relative for relative in outputs}
	for relative, content in outputs.items():
		path = root / relative
		if args.dryRun:
			print(f"exampleGen: would write {path}")
		else:
			writeGeneratedText(path, content)
			print(f"exampleGen: wrote {path}")
	removeStale(root, expected, dryRun=args.dryRun)
	print(f"exampleGen: generated {sum(1 for example in examples if example['generated'])} paired examples; indexed {len(examples)}")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
