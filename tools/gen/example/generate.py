#!/usr/bin/env python3
"""Validate source-owned SDK examples and generate their inventories."""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path, PurePosixPath
from typing import Any


REPO_ROOT_PATH = Path(__file__).resolve().parents[3]
if str(REPO_ROOT_PATH) not in sys.path:
	sys.path.insert(0, str(REPO_ROOT_PATH))

from tools.gen.io import writeGeneratedText


REPO_ROOT = REPO_ROOT_PATH
SCHEMA = Path(__file__).resolve().parent / "schema" / "examples.toml"
DEFAULT_OUTPUT = REPO_ROOT / "build" / "gen" / "example"
PUBLIC_MODULES = {"Audio", "Core", "Crypto", "Data", "Ml", "Ui", "Vision"}
ID_PATTERN = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")
NAME_PATTERN = re.compile(r"^[a-z][A-Za-z0-9]*$")
CPP_TARGET_PATTERN = re.compile(r"^[A-Z][A-Za-z0-9]*$")
GENERATED_JSON = "AUTO-GENERATED by tools/gen/example/generate.py"


class ExampleError(ValueError):
	pass


def requireString(owner: dict[str, Any], key: str, context: str) -> str:
	value = owner.get(key)
	if not isinstance(value, str) or not value.strip():
		raise ExampleError(f"{context}: {key} must be a non-empty string")
	return value


def requireStrings(owner: dict[str, Any], key: str, context: str) -> list[str]:
	value = owner.get(key)
	if not isinstance(value, list) or not value or any(
		not isinstance(item, str) or not item.strip() for item in value
	):
		raise ExampleError(f"{context}: {key} must be a non-empty string list")
	return value


def integer(owner: dict[str, Any], key: str, context: str) -> int:
	value = owner.get(key)
	if isinstance(value, bool) or not isinstance(value, int):
		raise ExampleError(f"{context}: {key} must be an integer")
	return value


def number(owner: dict[str, Any], key: str, context: str) -> int | float:
	value = owner.get(key)
	if isinstance(value, bool) or not isinstance(value, (int, float)):
		raise ExampleError(f"{context}: {key} must be numeric")
	return value


def safeRelative(value: str, context: str) -> PurePosixPath:
	path = PurePosixPath(value)
	if path.is_absolute() or not path.parts or ".." in path.parts:
		raise ExampleError(f"{context}: unsafe relative path {value!r}")
	return path


def assetInventory() -> set[str]:
	manifestPath = REPO_ROOT / "sdk" / "asset" / "manifest.toml"
	with manifestPath.open("rb") as stream:
		manifest = tomllib.load(stream)
	return {entry["path"] for entry in manifest.get("asset", [])}


def sourcePaths(example: dict[str, Any], context: str) -> tuple[str, str]:
	directory = requireString(example, "directory", context)
	stem = requireString(example, "stem", context)
	if not NAME_PATTERN.fullmatch(directory) or not NAME_PATTERN.fullmatch(stem):
		raise ExampleError(f"{context}: directory and stem must be lower camelCase")
	return (
		f"sdk/cpp/examples/{directory}/{stem}.cpp",
		f"sdk/py/examples/{directory}/{stem}.py",
	)


def validateSource(path: str, exampleId: str, comment: str, context: str) -> None:
	source = REPO_ROOT / path
	if not source.is_file():
		raise ExampleError(f"{context}: missing source {path}")
	text = source.read_text(encoding="utf-8")
	begin = f"{comment} OA_DOC_BEGIN: {exampleId}"
	end = f"{comment} OA_DOC_END: {exampleId}"
	if text.count(begin) != 1 or text.count(end) != 1 or text.index(begin) >= text.index(end):
		raise ExampleError(f"{context}: {path} requires one ordered {begin!r}/{end!r} pair")
	if "AUTO-GENERATED by tools/gen/example" in text[:512]:
		raise ExampleError(f"{context}: {path} must be source-owned, not generator-owned")


def validatePresentation(example: dict[str, Any], context: str, assets: set[str]) -> None:
	presentations = example.get("presentation")
	if presentations is None:
		return
	if not isinstance(presentations, list) or not presentations:
		raise ExampleError(f"{context}: presentation must be a non-empty table list")
	declaredAssets = set(example.get("assets", []))
	for presentationIndex, presentation in enumerate(presentations):
		presentationContext = f"{context}.presentation[{presentationIndex}]"
		if not isinstance(presentation, dict):
			raise ExampleError(f"{presentationContext}: presentation must be a table")
		kind = requireString(presentation, "kind", presentationContext)
		for key in ("title", "description"):
			requireString(presentation, key, presentationContext)
		if kind == "terminalOutput":
			for key in ("filename", "language", "generatedBy", "code"):
				requireString(presentation, key, presentationContext)
			continue
		if kind == "viewerCapture":
			asset = requireString(presentation, "asset", presentationContext)
			if asset not in declaredAssets or asset not in assets:
				raise ExampleError(f"{presentationContext}: Viewer capture must be a declared checked asset")
			for key in ("mimeType", "alt", "generatedBy"):
				requireString(presentation, key, presentationContext)
			for key in ("width", "height"):
				if integer(presentation, key, presentationContext) <= 0:
					raise ExampleError(f"{presentationContext}: {key} must be positive")
			continue
		items = presentation.get("items")
		if kind == "imageGallery":
			if not isinstance(items, list) or not items:
				raise ExampleError(f"{presentationContext}: imageGallery requires items")
		elif kind == "audioComparison":
			if not isinstance(items, list) or len(items) != 2:
				raise ExampleError(f"{presentationContext}: audioComparison requires two items")
		else:
			raise ExampleError(f"{presentationContext}: unsupported presentation kind {kind!r}")
		roles: set[str] = set()
		for itemIndex, item in enumerate(items):
			itemContext = f"{presentationContext}.items[{itemIndex}]"
			if not isinstance(item, dict):
				raise ExampleError(f"{itemContext}: item must be a table")
			role = requireString(item, "role", itemContext)
			if role in roles:
				raise ExampleError(f"{itemContext}: roles must be unique")
			roles.add(role)
			for key in ("label", "description", "mimeType", "generatedBy"):
				requireString(item, key, itemContext)
			asset = requireString(item, "asset", itemContext)
			if asset not in declaredAssets or asset not in assets:
				raise ExampleError(f"{itemContext}: asset must be declared and checked")
			if kind == "imageGallery":
				requireString(item, "alt", itemContext)
				for key in ("width", "height"):
					if integer(item, key, itemContext) <= 0:
						raise ExampleError(f"{itemContext}: {key} must be positive")
			else:
				fallback = requireString(item, "fallbackAsset", itemContext)
				if fallback not in declaredAssets or fallback not in assets:
					raise ExampleError(f"{itemContext}: fallback asset must be declared and checked")
				requireString(item, "fallbackMimeType", itemContext)
				for key in ("sampleRate", "channelCount", "sampleCount"):
					if integer(item, key, itemContext) <= 0:
						raise ExampleError(f"{itemContext}: {key} must be positive")
				if float(number(item, "durationSeconds", itemContext)) <= 0.0:
					raise ExampleError(f"{itemContext}: durationSeconds must be positive")
		if kind == "audioComparison" and roles != {"source", "processed"}:
			raise ExampleError(f"{presentationContext}: source and processed roles are required")


def loadExamples(schemaPath: Path) -> list[dict[str, Any]]:
	with schemaPath.open("rb") as stream:
		schema = tomllib.load(stream)
	if schema.get("schemaVersion") != 1:
		raise ExampleError(f"{schemaPath}: schemaVersion must be 1")
	examples = schema.get("examples")
	if not isinstance(examples, list) or not examples:
		raise ExampleError(f"{schemaPath}: no [[examples]] entries")

	assets = assetInventory()
	ids: set[str] = set()
	targets: set[str] = set()
	paths: set[str] = set()
	for index, example in enumerate(examples):
		context = f"{schemaPath}:examples[{index}]"
		if not isinstance(example, dict):
			raise ExampleError(f"{context}: example must be a table")
		exampleId = requireString(example, "id", context)
		if not ID_PATTERN.fullmatch(exampleId) or exampleId in ids:
			raise ExampleError(f"{context}: invalid or duplicate id {exampleId!r}")
		ids.add(exampleId)
		module = requireString(example, "module", context)
		if module not in PUBLIC_MODULES:
			raise ExampleError(f"{context}: unsupported module {module!r}")
		for key in ("title", "summary", "capability", "expectedOutput", "pythonProfile"):
			requireString(example, key, context)
		target = requireString(example, "cppTarget", context)
		if not CPP_TARGET_PATTERN.fullmatch(target) or target in targets:
			raise ExampleError(f"{context}: invalid or duplicate C++ target {target!r}")
		targets.add(target)
		requireStrings(example, "cppSymbols", context)
		requireStrings(example, "pythonSymbols", context)
		declaredAssets = example.get("assets", [])
		if not isinstance(declaredAssets, list) or any(not isinstance(asset, str) for asset in declaredAssets):
			raise ExampleError(f"{context}: assets must be strings")
		for asset in declaredAssets:
			safeRelative(asset, context)
			if asset not in assets:
				raise ExampleError(f"{context}: asset is absent from sdk/asset/manifest.toml: {asset}")
		validatePresentation(example, context, assets)
		cppPath, pythonPath = sourcePaths(example, context)
		for sourcePath, prefix, suffix, comment in (
			(cppPath, "sdk/cpp/examples/", ".cpp", "//"),
			(pythonPath, "sdk/py/examples/", ".py", "#"),
		):
			safeRelative(sourcePath, context)
			if not sourcePath.startswith(prefix) or not sourcePath.endswith(suffix):
				raise ExampleError(f"{context}: invalid source path {sourcePath}")
			if sourcePath in paths:
				raise ExampleError(f"{context}: duplicate source path {sourcePath}")
			paths.add(sourcePath)
			validateSource(sourcePath, exampleId, comment, context)
	return examples


def emitCmake(examples: list[dict[str, Any]], schemaPath: Path) -> str:
	lines = [
		"# AUTO-GENERATED by tools/gen/example/generate.py - DO NOT EDIT.",
		f"# Source: {schemaPath.relative_to(REPO_ROOT).as_posix()}",
		"",
	]
	for example in examples:
		cppPath, _ = sourcePaths(example, example["id"])
		relative = PurePosixPath(cppPath).relative_to("sdk/cpp/examples")
		registration = f"oa_add_example({example['cppTarget']} {relative.as_posix()} {example['directory']})"
		if example["module"] == "Crypto":
			lines.extend(["if(OA_BUILD_CRYPTO)", f"\t{registration}", "endif()"])
		else:
			lines.append(registration)
	lines.append("")
	return "\n".join(lines)


def emitPythonTests(examples: list[dict[str, Any]], schemaPath: Path) -> str:
	lines = [
		"# AUTO-GENERATED by tools/gen/example/generate.py - DO NOT EDIT.",
		f"# Source: {schemaPath.relative_to(REPO_ROOT).as_posix()}",
		"",
		"from pathlib import Path",
		"",
		"import pytest",
		"",
		"from example_runner import runExample",
		"",
		"",
	]
	for example in examples:
		_, pythonPath = sourcePaths(example, example["id"])
		profile = example["pythonProfile"]
		if "crypto" in profile:
			lines.append("@pytest.mark.oa_crypto")
		if "gpu" in profile:
			lines.append("@pytest.mark.oa_gpu")
		functionName = "test_" + example["id"].replace("-", "_")
		lines.extend([
			f"def {functionName}(tmp_path: Path):",
			f"\toutput = runExample(\"{pythonPath}\", tmp_path)",
			f"\tassert \"{example['expectedOutput']}\" in output",
			"",
			"",
		])
	return "\n".join(lines).rstrip() + "\n"


def manifestEntry(example: dict[str, Any]) -> dict[str, Any]:
	cppPath, pythonPath = sourcePaths(example, example["id"])
	entry: dict[str, Any] = {
		"id": example["id"],
		"title": example["title"],
		"summary": example["summary"],
		"module": example["module"],
		"capability": example["capability"],
	}
	if example.get("assets"):
		entry["assets"] = example["assets"]
	if example.get("presentation"):
		entry["presentation"] = example["presentation"]
	entry["cpp"] = {
		"path": cppPath,
		"target": example["cppTarget"],
		"symbols": example["cppSymbols"],
	}
	entry["python"] = {
		"path": pythonPath,
		"profile": example["pythonProfile"],
		"symbols": example["pythonSymbols"],
	}
	return entry


def emitManifest(examples: list[dict[str, Any]]) -> str:
	return json.dumps({
		"schema": 2,
		"generatedBy": GENERATED_JSON,
		"examples": [manifestEntry(example) for example in examples],
	}, indent=2, ensure_ascii=False) + "\n"


def outputMap(examples: list[dict[str, Any]], schemaPath: Path) -> dict[Path, str]:
	return {
		Path("sdk/cpp/examples/gen/examples.cmake"): emitCmake(examples, schemaPath),
		Path("test/py/examples/test_sdk_examples.py"): emitPythonTests(examples, schemaPath),
		Path("sdk/examples.json"): emitManifest(examples),
	}


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--schema", type=Path, default=SCHEMA)
	parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
	parser.add_argument("--live", action="store_true")
	parser.add_argument("--dry-run", dest="dryRun", action="store_true")
	args = parser.parse_args()

	try:
		examples = loadExamples(args.schema)
		outputs = outputMap(examples, args.schema)
	except (ExampleError, OSError, tomllib.TOMLDecodeError) as error:
		print(f"exampleGen: ERROR: {error}", file=sys.stderr)
		return 1

	root = REPO_ROOT if args.live else args.out
	if args.live:
		print("exampleGen: LIVE MODE - updating source-owned example inventories")
	for relative, content in outputs.items():
		path = root / relative
		if args.dryRun:
			print(f"exampleGen: would write {path}")
		else:
			writeGeneratedText(path, content)
			print(f"exampleGen: wrote {path}")
	print(f"exampleGen: indexed {len(examples)} source-owned paired examples")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
