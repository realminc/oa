#!/usr/bin/env python3
"""
checkDrift — the regeneration-safety gate for OA's source generators.

Run this BEFORE any `--live` regen. It runs every generator (Type / Fn / Nn /
Tile / Kernel / Example)
into a throwaway scratch tree and diffs the result against the committed
`.gen.*` files in `source/`, `test/`, and the internal operation reference when that
documentation tree is present. Any difference means the working tree and the
generators have diverged, which is the *only* way a `--live` regen can silently
destroy work:

  * a .gen.* file was hand-patched but the schema was never updated  → regen
    REVERTS the patch.
  * the schema/generator changed but the tree was never regenerated  → regen
    REWRITES the file (stale tree).

Either way you want to know and reconcile (fold the fix into the schema, or
regen on purpose) — not discover it after the fact.

Exit codes:
  0  clean — `--live` is safe, tree == generator output.
  1  drift — files differ; nothing was written. Resolve before regenerating.

Usage:
  python3 tools/gen/checkDrift.py            # summary
  python3 tools/gen/checkDrift.py --verbose  # unified diffs for each file

Stdlib only. The generators are run via the live source root so cmake/source
paths are repo-relative and identical to a real `--live` run.
"""
from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CoordinatedMarkers = tuple(
	f"AUTO-GENERATED by tools/gen/{authority}/"
	for authority in ("type", "fn", "nn", "kernel", "tile", "example")
)

# (script, scratch-subdir). Each generator mirrors the canonical source/test
# layout under its output root.
GENERATORS = [
 ("tools/gen/type/generate.py", "ty"),
 ("tools/gen/fn/generate.py", "fn"),
 ("tools/gen/nn/generate.py", "nn"),
 ("tools/gen/tile/generate.py", "tile"),
 ("tools/gen/kernel/generate.py", "kernel"),
 ("tools/gen/example/generate.py", "example"),
]

# The release tool adds this marker to sanitized public snapshots. Only marked
# trees may omit generated documentation; generated source and test artifacts
# remain mandatory everywhere.
PUBLIC_SNAPSHOT_MARKER = REPO_ROOT / ".oa-public-snapshot"
PUBLIC_SNAPSHOT_MARKER_CONTENT = b"OA sanitized public source snapshot\n"
PUBLIC_OMITTED_OPERATION_REFERENCE = (
 Path("docs") / "internal" / "architecture" / "oaOperations.gen.md"
)


def treeTarget(rel: Path) -> Path:
	"""Map a generated scratch-relative path to its committed counterpart."""
	parts = rel.parts
	if not parts:
		return REPO_ROOT / rel
 # Type/Fn output mirrors `source/cpp` and `source/py`. Nn/Kernel output
 # starts at the C++ language root. Tests and docs are repository-rooted.
	if parts[0] in ("cpp", "py"):
		return REPO_ROOT / "source" / rel
	if parts[0] in ("include", "lib"):
		return REPO_ROOT / "source" / "cpp" / rel
	return REPO_ROOT / rel


def norm(path: Path) -> list[str]:
	return path.read_bytes().replace(b"\r\n", b"\n").decode("utf-8", "replace").splitlines()


def isGeneratedOutput(path: Path) -> bool:
	try:
		prefix = path.read_text(encoding="utf-8")[:512]
	except (OSError, UnicodeError):
		return False
	return any(marker in prefix for marker in CoordinatedMarkers)


def isSanitizedPublicSnapshot() -> bool:
	try:
		return (
		 PUBLIC_SNAPSHOT_MARKER.read_bytes()
		 == PUBLIC_SNAPSHOT_MARKER_CONTENT
		)
	except OSError:
		return False


def intentionallyOmittedPublicDoc(target: Path) -> bool:
	if not isSanitizedPublicSnapshot():
		return False
	try:
		rel = target.relative_to(REPO_ROOT)
	except ValueError:
		return False
	return rel == PUBLIC_OMITTED_OPERATION_REFERENCE and not target.exists()


def runGenerators(scratch: Path) -> int:
	rc = 0
	for script, sub in GENERATORS:
		out = scratch / sub
		out.mkdir(parents=True, exist_ok=True)
		# Force UTF-8 so the scratch run can never introduce its own encoding
		# noise on a Windows console (the generators write utf-8 regardless).
		res = subprocess.run(
		 [sys.executable, script, "--out", str(out)],
		 cwd=REPO_ROOT, capture_output=True, text=True,
		)
		if res.returncode != 0:
			sys.stderr.write(f"[check] generator failed: {script}\n{res.stdout}\n{res.stderr}\n")
			rc |= res.returncode
	return rc


def main() -> int:
	ap = argparse.ArgumentParser(description="Gate that the tree matches generator output before --live regen.")
	ap.add_argument("--verbose", action="store_true", help="Print a unified diff for every drifted file.")
	args = ap.parse_args()

	with tempfile.TemporaryDirectory(prefix="oa_generation_check_") as tmp:
		scratch = Path(tmp)
		if runGenerators(scratch) != 0:
			return 1

  # Regeneration must preserve timestamps when every emitted byte is
  # unchanged. Otherwise an idempotent schema check invalidates Ninja's
  # dependency graph and can rebuild the complete shader/archive surface.
		firstMtimes = {
		 path: path.stat().st_mtime_ns
		 for path in scratch.rglob("*")
		 if path.is_file()
		}
		time.sleep(0.02)
		if runGenerators(scratch) != 0:
			return 1
		mtimeDrift = [
		 path.relative_to(scratch)
		 for path, firstMtime in firstMtimes.items()
		 if not path.exists() or path.stat().st_mtime_ns != firstMtime
		]
		if mtimeDrift:
			print(f"[check] NON-IDEMPOTENT — {len(mtimeDrift)} unchanged generated file(s) were rewritten:")
			for path in sorted(mtimeDrift):
				print(f"          ! {path.as_posix()}")
			return 1

		drift: list[tuple[Path, list[str], list[str]]] = []
		missing: list[Path] = []  # generator would CREATE (no tree counterpart)
		omittedPublicDocs: list[Path] = []
		omissionContractError = False
		expectedTargets: set[Path] = set()
		checked = 0
		for _, sub in GENERATORS:
			root = scratch / sub
			for genFile in root.rglob("*"):
				if not genFile.is_file() or not isGeneratedOutput(genFile):
					continue
				rel = genFile.relative_to(root)
				tgt = treeTarget(rel)
				expectedTargets.add(tgt)
				# Operation generation never writes <Name>.gen.slang when a hand-written
				# <Name>.slang sits beside it in the live tree — so live regen can
				# neither create nor clobber it. The scratch run can't see that
				# sibling; honor the same rule here (whether or not it exists).
				if genFile.name.endswith(".gen.slang"):
					manual = tgt.parent / genFile.name.replace(".gen.slang", ".slang")
					if manual.exists():
						continue
				if not tgt.exists() and intentionallyOmittedPublicDoc(tgt):
					omittedPublicDocs.append(rel)
					continue
				checked += 1
				if not tgt.exists():
					missing.append(rel)
					continue
				a, b = norm(tgt), norm(genFile)
				if a != b:
					drift.append((rel, b, a))

  # A scratch-only comparison cannot see files that a generator stopped
  # emitting. Ownership markers, not filename suffixes, define the complete
  # stale-output authority.
		stale: list[Path] = []
		candidates: set[Path] = set()
		for base in (
		 REPO_ROOT / "source",
		 REPO_ROOT / "test",
		 REPO_ROOT / "docs",
		 REPO_ROOT / "cmake",
		 REPO_ROOT / "sdk" / "cpp",
		 REPO_ROOT / "sdk" / "py",
		 REPO_ROOT / "sdk" / "examples.json",
		):
			if base.is_file():
				candidates.add(base)
			elif base.exists():
				candidates.update(base.rglob("*"))
		for candidate in candidates:
			if not candidate.is_file() or candidate in expectedTargets:
				continue
			try:
				prefix = candidate.read_text(encoding="utf-8")[:512]
			except (OSError, UnicodeError):
				continue
			if any(marker in prefix for marker in CoordinatedMarkers):
				stale.append(candidate.relative_to(REPO_ROOT))

		if isSanitizedPublicSnapshot():
			expectedOmissions = [PUBLIC_OMITTED_OPERATION_REFERENCE]
			if sorted(omittedPublicDocs) != expectedOmissions:
				omissionContractError = True

	print(f"[check] compared {checked} generated output files")
	if omittedPublicDocs:
		print(
		 f"[check] skipped {len(omittedPublicDocs)} documentation output(s) "
		 "intentionally absent from the sanitized public tree:"
		)
		for rel in sorted(omittedPublicDocs):
			print(f"          ~ {rel.as_posix()}")
	if missing:
		print(f"[check] {len(missing)} file(s) the generator would CREATE (not in tree):")
		for rel in sorted(missing):
			print(f"          + {rel.as_posix()}")
	if stale:
		print(f"[check] {len(stale)} stale generator-owned file(s) are no longer emitted:")
		for rel in sorted(stale):
			print(f"          - {rel.as_posix()}")
	if omissionContractError:
		print("[check] sanitized-snapshot omission contract mismatch:")
		print(f"          expected: {PUBLIC_OMITTED_OPERATION_REFERENCE.as_posix()}")
		observed = ", ".join(path.as_posix() for path in sorted(omittedPublicDocs))
		print(f"          observed: {observed or '<none>'}")
	if not drift:
		if missing or stale or omissionContractError:
			return 1
		print("[check] CLEAN — tree matches generator output. --live regen is safe.")
		return 0

	print(f"[check] DRIFT — {len(drift)} file(s) differ from generator output.")
	print("        A --live regen would overwrite these. Reconcile (fold the manual")
	print("        change into the schema, or regen on purpose) before regenerating.\n")
	for rel, genLines, treeLines in sorted(drift, key=lambda d: d[0].as_posix()):
		print(f"  DRIFT  {rel.as_posix()}")
		if args.verbose:
			for line in difflib.unified_diff(genLines, treeLines,
			                                 fromfile="generator", tofile="tree",
			                                 lineterm="", n=1):
				print(f"    {line}")
			print()
	return 1


if __name__ == "__main__":
	sys.exit(main())
