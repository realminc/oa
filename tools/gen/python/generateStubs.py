#!/usr/bin/env python3
"""Generate OA's public and private Python typing stubs from the live bindings."""

from __future__ import annotations

import argparse
import ast
import keyword
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from types import ModuleType

try:
	from nanobind.stubgen import StubGen
except ModuleNotFoundError:
 # vcpkg keeps its Python package beside include/lib while the private
 # private interpreter lives under tools/python3 and does not add that prefix.
	vcpkgPrefix = Path(sys.executable).resolve().parents[2]
	if (vcpkgPrefix / "nanobind").is_dir():
		sys.path.insert(0, str(vcpkgPrefix))
	from nanobind.stubgen import StubGen


REPO_ROOT = Path(__file__).resolve().parents[3]
PACKAGE_ROOT = REPO_ROOT / "source" / "py" / "oa"
SCHEMA_ROOT = REPO_ROOT / "tools" / "gen" / "fn" / "schema"
GENERATED_HEADER = (
 "# AUTO-GENERATED by tools/gen/python/generateStubs.py — DO NOT EDIT.\n"
 "# Sources of truth: the live nanobind signatures and oa/_surface.py.\n\n"
)


def _sanitizePythonKeywords(source: str) -> str:
	"""Make C++ identifiers that are Python keywords valid in a stub."""

	for name in keyword.kwlist:
		source = re.sub(
		 rf"(?m)^([ \t]*)@{re.escape(name)}\.setter$",
		 rf'\1# Runtime member "{name}" setter is available through setattr().',
		 source,
		)
		source = re.sub(
		 rf"(?m)^([ \t]*)@property\n\1def {re.escape(name)}\([^\n]*$",
		 rf'\1# Runtime member "{name}" is available through getattr().',
		 source,
		)
		source = re.sub(
		 rf"(?m)^([ \t]*)def {re.escape(name)}\([^\n]*$",
		 rf'\1# Runtime member "{name}" is available through getattr().',
		 source,
		)
		source = re.sub(
		 rf"(?m)^([ \t]+){re.escape(name)} = .*$",
		 rf'\1# Runtime member "{name}" is available through getattr().',
		 source,
		)
		source = source.replace(
		 f".{name}", f'.__members__["{name}"]'
		)
	return source


def _useTabIndentation(source: str) -> str:
	"""Use one tab for each four-space block emitted by nanobind stubgen."""

	return re.sub(
	 r"(?m)^(?: {4})+",
	 lambda match: "\t" * (len(match.group(0)) // 4),
	 source,
	)


def _refineSchemaReturnTypes(source: str) -> str:
	"""Restore element types erased by explicit Python container adapters."""

	matrixVectorOps: set[str] = set()
	for schemaPath in SCHEMA_ROOT.rglob("*.toml"):
		schema = tomllib.loads(schemaPath.read_text(encoding="utf-8"))
		matrixVectorOps.update(
		 op["python"].get("name", op["name"])
		 for op in schema.get("ops", [])
		 if op.get("api_return") == "oa::Vector<oa::Matrix>"
		 and "python" in op
		)

	for operation in matrixVectorOps:
		source = re.sub(
		 rf"(?m)(^def {re.escape(operation)}\([^\n]*\) -> )list(:)",
		 r"\1list[oa.Matrix]\2",
		 source,
		)
	return source


def _writeModuleStub(
 module: ModuleType, outputFile: Path, *, recursive: bool
) -> None:
	outputFile.parent.mkdir(parents=True, exist_ok=True)
	generator = StubGen(
	 module=module,
	 recursive=recursive,
	 include_docstrings=True,
	 include_private=False,
	 include_internal_imports=True,
	 include_external_imports=False,
	 max_expr_length=0,
	 quiet=True,
	 output_file=outputFile,
	)
	generator.put(module)
	outputFile.write_text(
	 _refineSchemaReturnTypes(
	  _useTabIndentation(_sanitizePythonKeywords(generator.get()))
	 ),
	 encoding="utf-8",
	)


def _declaredRootNames(rootStub: Path) -> set[str]:
	tree = ast.parse(rootStub.read_text(encoding="utf-8"), filename=str(rootStub))
	names: set[str] = set()
	for node in tree.body:
		if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
			names.add(node.name)
		elif isinstance(node, ast.ImportFrom):
			names.update(alias.asname or alias.name for alias in node.names)
		elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
			names.add(node.target.id)
		elif isinstance(node, ast.Assign):
			names.update(
			 target.id for target in node.targets if isinstance(target, ast.Name)
			)
	return names


def _generateTree(outputRoot: Path) -> None:
	import oa
	from oa._native import native

	_writeModuleStub(oa, outputRoot / "__init__.pyi", recursive=True)
	_writeModuleStub(
	 native, outputRoot / "_oa" / "__init__.pyi", recursive=True
	)
	for name in (
	 "audio", "core", "crypto", "ml", "plot", "runtime", "ui", "vision",
	 "FnAdvantage", "FnAudio", "FnAutograd", "FnDetection", "FnEnvironment",
	 "FnHash", "FnImage", "FnLoss", "FnMatrix", "FnMetric", "FnPolicy",
	):
		module = getattr(native, name, None)
		if module is not None:
			_writeModuleStub(
			 module, outputRoot / "_oa" / f"{name}.pyi", recursive=False
			)

	for stub in sorted(outputRoot.rglob("*.pyi")):
		source = _refineSchemaReturnTypes(
		 _useTabIndentation(
		  _sanitizePythonKeywords(stub.read_text(encoding="utf-8"))
		 )
		)
		if not source.startswith(GENERATED_HEADER):
			source = GENERATED_HEADER + source
		stub.write_text(source, encoding="utf-8")
		ast.parse(stub.read_text(encoding="utf-8"), filename=str(stub))

	(outputRoot / "py.typed").write_text("", encoding="utf-8")

	declared = _declaredRootNames(outputRoot / "__init__.pyi")
	missing = sorted(set(oa.__all__) - declared)
	if missing:
		raise RuntimeError(
		 "generated root stub is missing public exports: " + ", ".join(missing)
		)

	namespaceStubs = {
	 path.stem
	 for path in outputRoot.glob("Fn*.pyi")
	 if path.is_file()
	}
	expectedNamespaces = {name for name in oa.__all__ if name.startswith("Fn")}
	if namespaceStubs != expectedNamespaces:
		missingNamespaces = sorted(expectedNamespaces - namespaceStubs)
		extraNamespaces = sorted(namespaceStubs - expectedNamespaces)
		raise RuntimeError(
		 "generated namespace stubs disagree with oa.__all__: "
		 f"missing={missingNamespaces}, extra={extraNamespaces}"
		)


def _inventory(root: Path) -> dict[Path, bytes]:
	result = {
	 path.relative_to(root): path.read_bytes()
	 for path in root.rglob("*.pyi")
	 if path.is_file()
	}
	marker = root / "py.typed"
	if marker.is_file():
		result[marker.relative_to(root)] = marker.read_bytes()
	return result


def _compare(expectedRoot: Path, actualRoot: Path) -> list[str]:
	expected = _inventory(expectedRoot)
	actual = _inventory(actualRoot)
	differences: list[str] = []
	for path in sorted(expected.keys() | actual.keys()):
		if path not in actual:
			differences.append(f"missing {path}")
		elif path not in expected:
			differences.append(f"stale {path}")
		elif expected[path] != actual[path]:
			differences.append(f"changed {path}")
	return differences


def _install(generatedRoot: Path) -> None:
	expected = _inventory(generatedRoot)
	existing = _inventory(PACKAGE_ROOT)

	for stale in sorted(existing.keys() - expected.keys()):
		(PACKAGE_ROOT / stale).unlink()
	for relative, content in expected.items():
		destination = PACKAGE_ROOT / relative
		destination.parent.mkdir(parents=True, exist_ok=True)
		if not destination.is_file() or destination.read_bytes() != content:
			destination.write_bytes(content)

	for directory in sorted(
	 (path for path in PACKAGE_ROOT.rglob("*") if path.is_dir()),
	 key=lambda path: len(path.parts),
	 reverse=True,
	):
		if directory != PACKAGE_ROOT and not any(directory.iterdir()):
			directory.rmdir()


def _runFromCanonicalPackageLayout() -> int | None:
	"""Re-enter from a wheel-shaped package when testing a CMake build.

	CMake emits top-level ``_oa`` while wheels install ``oa._oa``. Nanobind keeps
	the loaded module name on function objects, which otherwise makes stubgen
	produce different imports for the same API. Stage the selected build exactly
	as a wheel package and use ``-S`` so an editable-install finder cannot override
	the staged package.
	"""

	buildDirValue = os.getenv("OA_PYTHON_BUILD_DIR")
	if not buildDirValue or os.getenv("OA_STUB_CANONICAL_PACKAGE"):
		return None
	buildDir = Path(buildDirValue).expanduser().resolve()
	extensions = sorted(buildDir.glob("_oa*.so")) + sorted(buildDir.glob("_oa*.pyd"))
	if len(extensions) != 1:
		raise RuntimeError(
		 f"expected one built _oa extension in {buildDir}, found {len(extensions)}"
		)

	with tempfile.TemporaryDirectory(prefix="oa-stub-package-") as temporary:
		stage = Path(temporary)
		package = stage / "oa"
		shutil.copytree(
		 PACKAGE_ROOT,
		 package,
		 ignore=shutil.ignore_patterns("*.pyi", "py.typed", "__pycache__"),
		)
		shutil.copy2(extensions[0], package / extensions[0].name)
		for library in sorted(buildDir.glob("liboa.so*")):
			shutil.copy2(library, package / library.name)

		dependencyPaths = [
		 Path(path).resolve()
		 for path in sys.path
		 if path and (Path(path) / "nanobind").is_dir()
		]
		environment = os.environ.copy()
		environment.pop("OA_PYTHON_BUILD_DIR", None)
		environment["OA_STUB_CANONICAL_PACKAGE"] = "1"
		environment["PYTHONPATH"] = os.pathsep.join(
		 str(path) for path in (stage, REPO_ROOT, *dependencyPaths)
		)
		result = subprocess.run(
		 [sys.executable, "-S", str(Path(__file__).resolve()), *sys.argv[1:]],
		 env=environment,
		 check=False,
		)
		return result.returncode


def main() -> int:
	canonicalResult = _runFromCanonicalPackageLayout()
	if canonicalResult is not None:
		return canonicalResult

	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument(
	 "--check",
	 action="store_true",
	 help="fail when checked-in stubs differ from fresh generation",
	)
	args = parser.parse_args()

	with tempfile.TemporaryDirectory(prefix="oa-stubs-") as temporary:
		generatedRoot = Path(temporary)
		_generateTree(generatedRoot)
		if args.check:
			differences = _compare(generatedRoot, PACKAGE_ROOT)
			if differences:
				for difference in differences:
					print(f"OA Python stub drift: {difference}", file=sys.stderr)
				return 1
		else:
			_install(generatedRoot)
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
