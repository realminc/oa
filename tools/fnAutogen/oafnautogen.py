def input_param_name(name: str) -> str:
	"""Apply OA's input-direction prefix without destroying camelCase."""
	if name.startswith("in") and len(name) > 2 and name[2].isupper():
		return name
	return f"in{name[:1].upper()}{name[1:]}"


def extra_param_decls(op: dict) -> list[str]:
	"""Return non-value parameters, for example `oa::I32 inDim = -1`."""
	out = []
	for ep in op.get("extra_params", []):
		decl = f"{ep['type']} {input_param_name(ep['name'])}"
		if "default" in ep:
			decl = f"{decl} = {ep['default']}"
		out.append(decl)
	return out


def cpp_param_list(op: dict, *, with_defaults: bool = True) -> str:
	"""Build the parameter list for a context-based forward overload.

	with_defaults: emit `= -1` defaults in declarations, but not in definitions.
	Context is obtained automatically inside the function, not passed as parameter.
	"""
	if op.get("api_params"):
		return api_param_list(op, with_defaults=with_defaults)
	parts: list[str] = []
	kind = op["kind"]
	if kind == "binary":
		parts += ["const oa::Matrix& inA", "const oa::Matrix& inB"]
	elif kind in ("unary", "reduce_full"):
		parts += ["const oa::Matrix& inA"]
	elif kind == "unary_scalar":
		sp = op["scalar_param"]
		parts += ["const oa::Matrix& inA", f"{sp['type']} {input_param_name(sp['name'])}"]
	elif kind == "nullary_scalar":
		# Factory convention: shape/extra params first, then the fill value —
		# matching Full(shape, value) and torch.full(size, fill_value). The
		# scalar is appended *after* the extra params below.
		sp = op["scalar_param"]
		for ep in extra_param_decls(op):
			if not with_defaults:
				ep = re.sub(r"\s*=\s*[^,]+$", "", ep)
			parts.append(ep)
		parts += [f"{sp['type']} {input_param_name(sp['name'])}"]
		return ", ".join(parts)
	# extra params (after main tensor args)
	for ep in extra_param_decls(op):
		if not with_defaults:
			ep = re.sub(r"\s*=\s*[^,]+$", "", ep)
		parts.append(ep)
	return ", ".join(parts)


def _api_param_parts(param: str | dict) -> tuple[str, str, str | None]:
	if isinstance(param, str):
		decl, separator, default = param.partition("=")
		decl = decl.strip()
		param_type, name = decl.rsplit(None, 1)
		return param_type, name, default.strip() if separator else None
	name = input_param_name(param["name"])
	return param["type"], name, param.get("default")


def api_param_list(op: dict, *, with_defaults: bool = True) -> str:
	"""Exact schema-owned public parameter list for non-uniform manual ops."""
	parts = []
	for param in op.get("api_params", []):
		param_type, name, default = _api_param_parts(param)
		decl = f"{param_type} {name}"
		if with_defaults and default is not None:
			decl += f" = {default}"
		parts.append(decl)
	return ", ".join(parts)


def api_arg_list(op: dict) -> str:
	return ", ".join(_api_param_parts(param)[1] for param in op.get("api_params", []))


def apply_schema_defaults(data: dict, op: dict) -> None:
	"""Apply schema-level generation policy without duplicating API facts."""
	if op.get("autograd") and data.get("autograd_node_header"):
		op["autograd"].setdefault(
			"node_header",
			data["autograd_node_header"],
		)
	auto_python = (
		data.get("generate_python_bindings", False)
		and op.get("generate_python_binding", True)
		and "python" not in op
		and (
			op.get("api_return", "oa::Matrix")
			in ("oa::Matrix", "oa::Audio", "oa::Image")
			or "python_result" in op
		)
		and op.get("surface", data.get("surface"))
			in ("public_operation", "stable_composite")
	)
	if auto_python and not op.get("api_params"):
		# Uniform operation kinds already define an exact C++ signature. Freeze
		# that derived signature into the normalized in-memory schema so C++,
		# Python, documentation, and validation consume the same parameter list.
		op["api_params"] = [
			part
			for part in cpp_param_list(op).split(", ")
			if part
		]
	if op.get("api_params"):
		op.setdefault(
			"generate_engine_overload",
			data.get("generate_engine_overloads", False),
		)
		op.setdefault(
			"generate_forwarder",
			data.get("generate_forwarders", False),
		)
	if auto_python and op.get("api_params"):
		args = []
		for param in op["api_params"]:
			_, name, _ = _api_param_parts(param)
			# Strip the C++ input-direction prefix while preserving Python's
			# camelCase argument spelling (inA → a, inMatrix → matrix).
			if name.startswith("in") and len(name) > 2 and name[2].isupper():
				bare = name[2:]
				arg = bare[0].lower() + bare[1:]
			elif name.startswith("In") and len(name) > 2:
				bare = name[2:]
				arg = bare[0].lower() + bare[1:]
			else:
				arg = name
			args.append(arg)
		op["python"] = {"args": args}


def header_fragment_for_op(op: dict, namespace: str = "oa::FnMatrix") -> list[str]:
	name = op["name"]
	notes = op.get("notes", "")
	body = op.get("body", "auto")
	if not op.get("generate_declaration", True):
		return []
	if op.get("api_params"):
		lines = [f"\t/// {name}: {notes}"]
		return_type = op.get("api_return", "oa::Matrix")
		params = api_param_list(op)
		result_attribute = "[[nodiscard]] " if return_type != "void" else ""
		if op.get("generate_engine_overload", False):
			engine_params = f"oa::Engine& inEngine, {params}" if params else "oa::Engine& inEngine"
			lines.append(
				f"\t{result_attribute}{return_type} {name}({engine_params});"
			)
			lines.append(f"\t{result_attribute}{return_type} {name}({params});")
		else:
			lines.append(f"\t{result_attribute}{return_type} {name}({params});")
		lines.append("")
		return lines
	# Entirely handwritten operations own no generated declaration. Emitting a
	# comment-only placeholder makes the generated surface look non-empty and
	# leaves stale noise in otherwise useful mixed-category headers.
	if body in ("manual_session", "cpu_util"):
		return []
	lines = [f"\t/// {name}: {notes}"]
	lines.append(f"\t/// Session-recorded: auto y = {namespace}::{name}(...);")
	lines.append(f"\t/// Records operation to thread-local default context.")
	lines.append(f"\t[[nodiscard]] oa::Matrix {name}({cpp_param_list(op)});")
	lines.append("")
	return lines


def emit_manual_forwarder(op: dict, namespace: str) -> str:
	"""Generate the active-context convenience overload for a manual GPU body."""
	if not (op.get("api_params") and op.get("generate_forwarder", False)):
		return ""
	name = op["name"]
	return_type = op.get("api_return", "oa::Matrix")
	params = api_param_list(op, with_defaults=False)
	args = api_arg_list(op)
	if "contract" not in op:
		fail(
			f"{name}: generated manual forwarding requires a semantic contract "
			"so it can lower through the active context"
		)
	if return_type != "oa::Matrix":
		fail(
			f"{name}: generated manual semantic forwarding currently requires "
			"api_return = 'oa::Matrix'"
		)
	matrix_inputs = []
	for param in op["api_params"]:
		param_type, param_name, _ = _api_param_parts(param)
		if "oa::Matrix" in param_type:
			matrix_inputs.append(f"&{param_name}")
	expected_inputs = op["contract"]["input_kinds"]
	if expected_inputs != ["matrix"] * len(matrix_inputs):
		fail(
			f"{name}: generated manual semantic forwarding requires one "
			"oa::Matrix API parameter per matrix contract input"
		)
	call_args = f"session.engine(), {args}" if args else "session.engine()"
	semantic_inputs = "{" + ", ".join(matrix_inputs) + "}"
	attribute_values = _semantic_attribute_cpp_values(op)
	semantic_attributes = "{" + ", ".join(attribute_values) + "}"
	return (
		f"{return_type} {namespace}::{name}({params}) {{\n"
		"\tauto& session = oa::ExecutionSession::getActive();\n"
		"\toa::OpLoweringScope lowering(session);\n"
		f"\tauto out = {namespace}::{name}({call_args});\n"
		"\tconst auto status = lowering.commit(\n"
		f"\t\t{operation_registry_reference(namespace, name)}, "
		f"{semantic_inputs}, {{&out}}, {semantic_attributes});\n"
		"\tif (not status.isOk()) return {};\n"
		"\treturn out;\n"
		f"}}\n"
	)


def schema_label(schema_path: Path) -> str:
	try:
		return schema_path.resolve().relative_to(SCHEMA_DIR.resolve()).as_posix()
	except ValueError:
		return schema_path.name


def namespace_leaf(namespace: str) -> str:
	"""Return the public family/session name from one qualified oa namespace."""
	return namespace.rsplit("::", 1)[-1]


def emit_header_fragment(ops: list[dict], schema_name: str, category: str, namespace: str = "oa::FnMatrix") -> str:
	lines = [GEN_HEADER.format(schema_name=schema_name)]
	lines.append(f"// {namespace} — {category} overloads.\n")
	for op in ops:
		lines.extend(header_fragment_for_op(op, namespace))
	return "\n".join(lines)


