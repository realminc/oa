def emit_operation_reference(operations: list[tuple[str, dict]]) -> str:
	lines = [
		"<!-- AUTO-GENERATED by tools/fnAutogen/oafnautogen.py — DO NOT EDIT. -->",
		"<!-- Source of truth: tools/fnAutogen/schema/**.toml. -->",
		"# OA operation contracts",
		"",
		"This reference is generated from the same schemas as the C++ declarations,",
		"Python registrations, and runtime semantic hashes.",
		"",
	]
	contract_surfaces = {
		"public_operation",
		"public_cpp_operation",
		"stable_composite",
		"internal_operation",
	}
	counts: dict[str, list[int]] = defaultdict(lambda: [0, 0])
	for _, op in operations:
		surface = op["surface"]
		counts[surface][0] += 1
		if "contract" in op:
			counts[surface][1] += 1
	required = sum(
		counts[surface][0]
		for surface in contract_surfaces
	)
	contracted = sum(
		counts[surface][1]
		for surface in contract_surfaces
	)
	session_rows = [
		op for _, op in operations if op["surface"] == "session_command"
	]
	described_sessions = sum("session" in op for op in session_rows)
	lines += [
		"## Migration inventory",
		"",
		f"- Classified rows: `{len(operations)}`",
		f"- Rows requiring semantic operation contracts: `{required}`",
		f"- Contracted required rows: `{contracted}`",
		f"- Remaining required rows: `{required - contracted}`",
		f"- Session command rows requiring state/effect descriptors: `{len(session_rows)}`",
		f"- Described session command rows: `{described_sessions}`",
		f"- Remaining session descriptors: `{len(session_rows) - described_sessions}`",
		"",
		"| Surface | Rows | Operation contracts | Session descriptors | Remaining required |",
		"| --- | ---: | ---: | ---: | ---: |",
	]
	for surface in sorted(counts):
		total, surface_contracted = counts[surface]
		surface_sessions = sum(
			1
			for op in session_rows
			if op["surface"] == surface and "session" in op
		)
		if surface in contract_surfaces:
			remaining = total - surface_contracted
		elif surface == "session_command":
			remaining = total - surface_sessions
		else:
			remaining = 0
		lines.append(
			f"| `{surface}` | {total} | {surface_contracted} | "
			f"{surface_sessions} | {remaining} |"
		)
	lines += [
		"",
		"`value_view`, `kernel`, `alias`, `host_utility`, and `session_command`",
		"rows intentionally do not require stateless semantic operation contracts.",
		"Host observations require a typed host-boundary descriptor rather than",
		"pretending a CPU scalar is a device value. Session commands instead own",
		"an explicit session state/effect/completion descriptor.",
		"",
		"## Session command descriptors",
		"",
	]
	for namespace, op in sorted(
		(
			(namespace, op)
			for namespace, op in operations
			if op["surface"] == "session_command"
		),
		key=lambda item: (item[0], item[1]["name"]),
	):
		session = op["session"]
		lines += [
			f"### `{namespace}::{op['name']}`",
			"",
			f"- Owners: `{', '.join(session['owners'])}`",
			f"- Transition: `{session['transition']}`",
			f"- Effects: `{', '.join(session['effects'])}`",
			f"- Completion: `{session['completion']}`",
			"",
		]
	lines += [
		"## Contracted operations",
		"",
	]
	contracts = [
		(namespace, op)
		for namespace, op in operations
		if "contract" in op
	]
	for namespace, op in sorted(contracts, key=lambda item: (item[0], item[1]["name"])):
		contract = op["contract"]
		input_values = ", ".join(contract["input_kinds"])
		output_values = ", ".join(contract["output_kinds"])
		if variadic := contract.get("variadic_inputs"):
			input_values = (
				f"{input_values}, " if input_values else ""
			) + f"{variadic['kind']}... (min {variadic['minimum']})"
		if variadic := contract.get("variadic_outputs"):
			output_values = (
				f"{output_values}, " if output_values else ""
			) + f"{variadic['kind']}... (min {variadic['minimum']})"
		attributes = semantic_attribute_specs(op)
		attribute_text = ", ".join(
			f"{attribute['name']}:{attribute['kind']}"
			for attribute in attributes
		) if attributes else "none"
		cpp_surface = (
			"internal session command"
			if op.get("kind") == "session_command"
			else f"`{op.get('api_return', 'oa::Matrix')} {op['name']}({api_param_list(op)})`"
		)
		lines += [
			f"## `{namespace}::{op['name']}`",
			"",
			f"- C++: {cpp_surface}",
			f"- Contract: `0x{operation_contract_hash(namespace, op):016x}`",
			f"- Values: `{input_values}` → `{output_values}`",
			f"- Shape: `{contract['shape_rule']}`",
			f"- Dtype: `{contract['dtype_rule']}`",
			f"- Effects: `{', '.join(contract['effects'])}`",
			f"- Mutated inputs: `{contract['mutated_inputs']}`",
			f"- Optional inputs: `{contract.get('optional_inputs', [])}`",
			f"- Output aliases: `{contract['output_alias_inputs']}`",
			f"- Attributes: `{attribute_text}`",
			f"- Control flow: `{contract['control_flow']}`",
			f"- Differentiation: `{contract['differentiation']}`",
			f"- Lowering: `{contract['lowering']}`",
		]
		if contract.get("value_validation") == "session_command":
			lines += [
				"- Value validation: private session command; `match_input` is the "
				"frozen descriptor sentinel, not generic homogeneous-dtype validation",
			]
		if python := op.get("python"):
			python_params = []
			for python_arg, api_param in zip(python["args"], op["api_params"]):
				_, _, default = _api_param_parts(api_param)
				python_params.append(
					python_arg if default is None else f"{python_arg}={default}"
				)
			lines.append(
				f"- Python: `{python.get('name', op['name'])}({', '.join(python_params)})`"
			)
		if autograd := op.get("autograd"):
			if grad_class := autograd.get("grad_class"):
				lines.append(
					f"- Autograd: `{grad_class}` (`{autograd.get('formula', 'manual')}`)"
				)
		lines += ["", op.get("notes", ""), ""]
	return "\n".join(lines).rstrip() + "\n"


def write_operation_reference(
	schema_paths: list[Path], out_root: Path, *, live: bool, dry_run: bool
) -> None:
	operations: list[tuple[str, dict]] = []
	for schema_path in schema_paths:
		with schema_path.open("rb") as file:
			data = tomllib.load(file)
		domain = infer_domain(schema_path)
		namespace = data.get("namespace", DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix"))
		default_surface = data.get("surface")
		for source_op in data.get("ops", []):
			op = dict(source_op)
			op["surface"] = op.get("surface", default_surface)
			apply_schema_defaults(data, op)
			operations.append((namespace, op))
	root = REPO_ROOT if live else out_root
	path = root / "docs" / "internal" / "architecture" / "oaOperations.gen.md"
	if dry_run:
		print(f"  would write: {path}")
		return
	write_generated_text(path, emit_operation_reference(operations))


