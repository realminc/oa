# ─── Manifest emission ───────────────────────────────────────────────────────


def _pascal_to_upper_snake(name: str) -> str:
	return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def _source_rel(path: Path, out_root: Path) -> str:
	# Always emit repo-root-relative source/... paths so the .cmake content is
	# byte-identical in --live and scratch (--out) mode. The drift gate
	# (tools/check_autogen_drift.py) relies on scratch output matching live.
	rel = path.relative_to(out_root).as_posix()
	return rel if rel.startswith("source/") else f"source/{rel}"


def _manifest_var(layout: SchemaLayout) -> str:
	if layout.domain == "crypto":
		return f"OA_CRYPTO_{layout.cpp_subdir.upper()}_{_pascal_to_upper_snake(layout.file_prefix)}_GENERATED_SOURCES"
	return f"OA_{layout.domain.upper()}_{_pascal_to_upper_snake(layout.file_prefix)}_GENERATED_SOURCES"


def emit_umbrella_header(layouts: list[SchemaLayout]) -> str:
	first = layouts[0]
	lines = [
		GEN_HEADER.format(schema_name=f"{first.domain}/{first.file_prefix} manifest"),
		f"// {first.namespace} — generated declarations for {first.domain}/{first.cpp_subdir}.\n",
	]
	manifest_parent = (
		first.header_path.parents[1]
		if first.header_path.parent.name != first.cpp_subdir.lower()
		else first.header_path.parent
	)
	for layout in layouts:
		if not layout.emit_header:
			continue
		include_path = layout.header_path.relative_to(manifest_parent).as_posix()
		lines.append(f'#include "{include_path}"')
	lines.append("")
	return "\n".join(lines)


def emit_cmake_sources(layouts: list[SchemaLayout], out_root: Path) -> str:
	first = layouts[0]
	var_name = _manifest_var(first)
	lines = [
		"# AUTO-GENERATED by tools/fnAutogen/oafnautogen.py -- DO NOT EDIT.",
		"# Regenerate via: python3 tools/fnAutogen/oafnautogen.py --live",
		f"set({var_name}",
	]
	for layout in layouts:
		if not layout.emit_cpp:
			continue
		lines.append(f"\t{_source_rel(layout.cpp_path, out_root)}")
	lines.append(")")
	lines.append("")
	return "\n".join(lines)


def emit_autograd_manifest(domain: str, layouts: list[SchemaLayout]) -> str:
	public_autograd = (
		"oa/core/autograd.h" if domain == "core" else "oa/ml/autograd.h"
	)
	manifest_parent = layouts[0].autograd_header_path.parent.parent
	lines = [
		"// AUTO-GENERATED by tools/fnAutogen/oafnautogen.py — DO NOT EDIT.",
		"// Includes schema-generated gradient-node catalogs for this domain.",
		"// Regenerate via: python3 tools/fnAutogen/oafnautogen.py --live",
		"",
		"#pragma once",
		"",
		f"#include <{public_autograd}>",
	]
	for layout in sorted(
		layouts, key=lambda item: item.autograd_header_path.as_posix()
	):
		include_path = layout.autograd_header_path.relative_to(
			manifest_parent
		).as_posix()
		lines.append(f'#include "{include_path}"')
	lines.append("")
	return "\n".join(lines)


def write_autograd_manifest_files(
	layouts: list[SchemaLayout], out_root: Path, *, dry_run: bool
) -> None:
	by_domain: dict[str, list[SchemaLayout]] = defaultdict(list)
	for layout in layouts:
		if layout.emit_autograd:
			by_domain[layout.domain].append(layout)

	for domain in ("core", "ml"):
		autograd_root = out_root / "cpp" / "lib" / "oa" / domain / "autograd"
		manifest = autograd_root / "autograd.gen.h"
		domain_layouts = by_domain.get(domain, [])
		if dry_run:
			if domain_layouts:
				print(f"  would write: {manifest}")
			continue
		if domain_layouts:
			write_generated_text(
				manifest, emit_autograd_manifest(domain, domain_layouts)
			)
		elif manifest.exists():
			manifest.unlink()

		expected = {
			layout.autograd_header_path for layout in domain_layouts
		}
		if not autograd_root.exists():
			continue
		for generated in autograd_root.rglob("autograd*.gen.h"):
			if generated in expected or generated.name in (
				"autograd.gen.h", "autogradAttach.gen.h"
			):
				continue
			if generated.read_text(encoding="utf-8").startswith(
				"// AUTO-GENERATED by tools/fnAutogen/oafnautogen.py"
			):
				generated.unlink()


def write_manifest_files(layouts: list[SchemaLayout], out_root: Path, *, dry_run: bool) -> None:
	groups: dict[tuple[str, str, str, str], list[SchemaLayout]] = defaultdict(list)
	for layout in layouts:
		groups[(layout.domain, layout.namespace, layout.file_prefix, layout.cpp_subdir)].append(layout)

	generated_headers = {layout.header_path for layout in layouts if layout.emit_header}
	autograd_manifests = {
		out_root / "cpp" / "lib" / "oa" / domain / "autograd" / "autograd.gen.h"
		for domain in ("core", "ml")
	}
	for grouped in groups.values():
		grouped.sort(key=lambda item: item.header_path.name)
		first = grouped[0]
		has_headers = any(layout.emit_header for layout in grouped)
		has_cpp = any(layout.emit_cpp for layout in grouped)
		
		manifest_parent = (
			out_root / "cpp" / "lib" / "oa" / first.domain / first.cpp_subdir.lower()
		)
		manifest_header = manifest_parent / f"{camel_file_stem(first.file_prefix)}.gen.h"
		# The public declaration manifest follows header_path. The build-source
		# manifest follows cpp_path and remains private.
		if first.cpp_path.parent.name == first.cpp_subdir.lower():
			cmake_parent = first.cpp_path.parent
		else:
			cmake_parent = first.cpp_path.parent.parent
		manifest_cmake = cmake_parent / f"{camel_file_stem(first.file_prefix)}Sources.gen.cmake"
		emit_header = (
			has_headers and manifest_header not in generated_headers and first.domain != "crypto"
		)
		if dry_run:
			if emit_header:
				print(f"  would write: {manifest_header}")
			if has_cpp:
				print(f"  would write: {manifest_cmake}")
			continue
		if emit_header:
			write_generated_text(manifest_header, emit_umbrella_header(grouped))
			legacy_header = (
				out_root / "cpp" / "include" / "oa" / first.domain
				/ f"{first.file_prefix}.gen.h"
			)
			if legacy_header != manifest_header and legacy_header.exists():
				legacy_header.unlink()
			legacy_public_header = (
				out_root / "cpp" / "include" / "oa" / first.domain
				/ first.cpp_subdir / f"{first.file_prefix}.gen.h"
			)
			if legacy_public_header != manifest_header and legacy_public_header.exists():
				legacy_public_header.unlink()
		elif (
			manifest_header.exists()
			and manifest_header not in generated_headers
			and manifest_header not in autograd_manifests
		):
			manifest_header.unlink()
		legacy_public_header = (
			out_root / "cpp" / "include" / "oa" / first.domain
			/ f"{first.file_prefix}.gen.h"
		)
		if legacy_public_header != manifest_header and legacy_public_header.exists():
			legacy_public_header.unlink()
		if has_cpp:
			write_generated_text(manifest_cmake, emit_cmake_sources(grouped, out_root))
		elif manifest_cmake.exists():
			manifest_cmake.unlink()


# ─── Main ──────────────────────────────────────────────────────────────────


def process_schema(schema_path: Path, registry: set[str], out_root: Path,
                   *, live: bool, dry_run: bool) -> SchemaLayout | list[SchemaLayout]:
	with schema_path.open("rb") as f:
		data = tomllib.load(f)
	ops = data.get("ops", [])
	if not ops:
		fail(f"no [[ops]] entries in {schema_path}")
	for op in ops:
		apply_schema_defaults(data, op)
	validate_schema_metadata(schema_path, data)
	validate_schema(schema_path, ops, registry, data.get("surface"))
	category, file_category = category_from_schema(schema_path, data)
	any_manual = any(op.get("body", "auto") == "manual_session" for op in ops)
	mode = "additive (manual bodies)" if any_manual else "full autogen"
	print(f"oafnautogen: {schema_path.name} — {len(ops)} ops, category={category}, "
	      f"file_category={file_category}, mode={mode}")
	
	# For Loss domain, emit per-function subdirectories (e.g., /Loss/Mse/FnLossMse.gen.h)
	domain = infer_domain(schema_path)
	namespace = data.get("namespace", DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix"))
	file_prefix = data.get("file_prefix", DOMAIN_FILE_PREFIX.get(domain, "FnMatrix"))
	cpp_subdir = data.get("cpp_subdir", infer_cpp_subdir(domain, file_category))

	def emits_header(op: dict) -> bool:
		return op.get("generate_declaration", True) and (
			op.get("body", "auto") not in ("manual_session", "cpu_util")
			or bool(op.get("api_params"))
		)

	def emits_cpp(op: dict) -> bool:
		return op.get("body", "auto") not in ("manual_session", "cpu_util") or bool(
			op.get("api_params") and op.get("generate_forwarder", False)
		)
	
	if domain == "ml" and cpp_subdir == "FnLoss":
		# Per-function subdirectories for Loss
		layouts = []
		for op in ops:
			op_name = op["name"]
			header_subdir = (
				out_root / "cpp" / "lib" / "oa" / domain / cpp_subdir.lower()
				/ op_name.lower()
			)
			cpp_subdir_path = header_subdir
			file_stem = camel_file_stem(
				f"{file_prefix}{op_name[:1].upper()}{op_name[1:]}"
			)
			h_path = header_subdir / f"{file_stem}.gen.h"
			cpp_path = cpp_subdir_path / f"{file_stem}.gen.cpp"
			schema_name = schema_label(schema_path)
			op_emit_header = emits_header(op)
			op_emit_cpp = emits_cpp(op)
			
			if dry_run:
				if op_emit_header:
					print(f"  would write: {h_path}")
				if op_emit_cpp:
					print(f"  would write: {cpp_path}")
				layouts.append(SchemaLayout(
					domain=domain,
					namespace=namespace,
					file_prefix=file_prefix,
					cpp_subdir=cpp_subdir,
					header_path=h_path,
					cpp_path=cpp_path,
					autograd_header_path=Path(""),
					test_path=Path(""),
					emit_header=op_emit_header,
					emit_cpp=op_emit_cpp,
				))
				continue
			
			header_subdir.mkdir(parents=True, exist_ok=True)
			cpp_subdir_path.mkdir(parents=True, exist_ok=True)
			if op_emit_header:
				write_generated_text(h_path, emit_header_fragment([op], schema_name, op_name, namespace))
				legacy_public_header = (
					out_root / "cpp" / "include" / "oa" / domain / cpp_subdir.lower()
					/ op_name.lower() / h_path.name
				)
				if legacy_public_header.exists():
					legacy_public_header.unlink()
			elif h_path.exists():
				h_path.unlink()
			if op_emit_cpp:
				write_generated_text(cpp_path, emit_cpp_file([op], schema_name, op_name, domain, namespace))
			elif cpp_path.exists():
				cpp_path.unlink()
			print(f"  wrote {op_name}: header={op_emit_header}, cpp={op_emit_cpp}")
			layouts.append(SchemaLayout(
				domain=domain,
				namespace=namespace,
				file_prefix=file_prefix,
				cpp_subdir=cpp_subdir,
				header_path=h_path,
				cpp_path=cpp_path,
				autograd_header_path=Path(""),
				test_path=Path(""),
				emit_header=op_emit_header,
				emit_cpp=op_emit_cpp,
			))
		# Return list of layouts for Loss domain
		return layouts
	
	# Standard processing for other domains
	emit_header = any(emits_header(op) for op in ops)
	emit_cpp = any(emits_cpp(op) for op in ops)
	emit_autograd = any(bool(emit_autograd_class(op)) for op in ops)
	layout = build_schema_layout(
		schema_path, data, file_category, out_root, live=live,
		emit_header=emit_header, emit_cpp=emit_cpp,
		emit_autograd=emit_autograd,
	)
	schema_name = schema_label(schema_path)
	test_body = emit_fn_tests(ops, schema_name, file_category, layout.domain)
	# Emit tests if any op has forward_op OR has test config
	emit_tests = any(op.get("forward_op") or op.get("test") for op in ops)
	if dry_run:
		if emit_header:
			print(f"  would write: {layout.header_path}")
		if emit_cpp:
			print(f"  would write: {layout.cpp_path}")
		if emit_tests:
			print(f"  would write: {layout.test_path}")
		for op in ops:
			if op.get("forward_op"):
				print(f"  would write: {op_slang_path(op, out_root, live=live)}")
		return layout
	if emit_header:
		write_generated_text(layout.header_path, emit_header_fragment(ops, schema_name, category, layout.namespace))
	elif layout.header_path.exists():
		layout.header_path.unlink()
	relative_header = layout.header_path.relative_to(
		out_root / "cpp" / "lib" / "oa")
	legacy_public_header = out_root / "cpp" / "include" / "oa" / relative_header
	if legacy_public_header.exists():
		legacy_public_header.unlink()
	if emit_cpp:
		write_generated_text(layout.cpp_path, emit_cpp_file(ops, schema_name, category, layout.domain, layout.namespace))
	elif layout.cpp_path.exists():
		layout.cpp_path.unlink()
	if emit_tests:
		write_generated_text(layout.test_path, test_body)
	elif layout.test_path.exists():
		layout.test_path.unlink()
	n_slang = 0
	for op in ops:
		if op.get("forward_op"):
			sp = op_slang_path(op, out_root, live=live)
			# Skip if manual .slang file exists (check without .gen suffix)
			manual_path = sp.parent / f"{op['name']}.slang"
			if manual_path.exists() and sp.name.endswith('.gen.slang'):
				continue
			write_generated_text(sp, emit_slang(op, schema_name))
			n_slang += 1
	# Autograd generation
	autograd_subdir = layout.autograd_header_path.parent.name if layout.autograd_header_path else "Matrix"
	autograd_body = emit_autograd_header(
		ops, schema_name, file_category, layout.domain, autograd_subdir
	)
	if autograd_body and layout.autograd_header_path:
		write_generated_text(layout.autograd_header_path, autograd_body)
		print(f"  wrote {layout.autograd_header_path.name}")
	elif layout.autograd_header_path and layout.autograd_header_path.exists():
		layout.autograd_header_path.unlink()
	print(f"  wrote {schema_path.name}: header={emit_header}, cpp={emit_cpp}, slang={n_slang}")
	return layout


def main() -> int:
	ap = argparse.ArgumentParser(description="Generate Fn* C++/Slang from schema.")
	ap.add_argument("--schema-dir", type=Path, default=SCHEMA_DIR,
	                help="Directory containing *.toml schemas (default: tools/fnAutogen/schema/)")
	ap.add_argument("--schema", type=Path, default=None,
	                help="Single schema file (overrides --schema-dir)")
	ap.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY,
	                help="composed kernelRegistry.h to cross-check kernel names against")
	ap.add_argument("--out", type=Path, default=DEFAULT_OUTPUT,
	                help="Output root (default: tools/fnAutogen/output)")
	ap.add_argument("--live", action="store_true",
	                help="Write drop-in replacements directly to source/ tree.")
	ap.add_argument("--dry-run", action="store_true",
	                help="Print summary, don't write files")
	args = ap.parse_args()
	if args.live and args.schema and not args.dry_run:
		fail("--schema cannot be combined with --live because shared manifests require the complete schema set")
	out_root = LIVE_SOURCE_ROOT if args.live else args.out
	if args.live:
		print("oafnautogen: LIVE MODE — writing to source/ tree (overwrites hand-written files)")
	if args.schema:
		schemas = [args.schema]
	else:
		# Recursively find all .toml files in schema/ subdirectories.
		schemas = sorted(args.schema_dir.rglob("*.toml"))
		if not schemas:
			fail(f"no schemas found in {args.schema_dir}")
	validate_schema_set(schemas)
	core_schemas, sdk_schemas = partition_schema_owners(schemas)
	core_kernels = collect_schema_kernels(core_schemas)
	sdk_kernels = collect_schema_kernels(sdk_schemas)
	validate_schema_kernel_ownership(core_kernels + sdk_kernels, args.registry)
	registry = load_kernel_registry(args.registry)
	registry.update(kernel["name"] for kernel in core_kernels + sdk_kernels)
	print(
		f"oafnautogen: registry {args.registry.name} — {len(registry)} kernels "
		f"({len(core_kernels)} core, {len(sdk_kernels)} SDK schema-owned)"
	)
	layouts = []
	for schema_path in core_schemas:
		result = process_schema(schema_path, registry, out_root, live=args.live, dry_run=args.dry_run)
		# process_schema may return a list (for Loss) or a single SchemaLayout
		if isinstance(result, list):
			layouts.extend(result)
		else:
			layouts.append(result)
	write_manifest_files(layouts, out_root, dry_run=args.dry_run)
	write_autograd_manifest_files(layouts, out_root, dry_run=args.dry_run)
	for schema_path in sdk_schemas:
		with schema_path.open("rb") as file:
			data = tomllib.load(file)
		for op in data.get("ops", []):
			apply_schema_defaults(data, op)
		validate_schema_metadata(schema_path, data)
		validate_schema(schema_path, data["ops"], registry, data.get("surface"))
	write_operation_registry(core_schemas, out_root, dry_run=args.dry_run)
	write_sdk_operation_registry(
		sdk_schemas, out_root, live=args.live, dry_run=args.dry_run)
	write_dnn_operation_roles(core_schemas, out_root, dry_run=args.dry_run)
	write_manual_autograd_attach_files(core_schemas, out_root, dry_run=args.dry_run)
	write_python_bindings(core_schemas, out_root, dry_run=args.dry_run)
	write_schema_kernel_files(core_kernels, out_root, dry_run=args.dry_run)
	write_sdk_kernel_cmake(
		sdk_kernels, out_root, live=args.live, dry_run=args.dry_run)
	write_operation_reference(
		core_schemas, out_root, live=args.live, dry_run=args.dry_run
	)
	return 0


if __name__ == "__main__":
	sys.exit(main())
