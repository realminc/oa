def _python_binding_params_and_args(op: dict) -> tuple[str, str]:
	"""Adapt native span parameters to ordinary Python list boundaries."""
	params: list[str] = []
	args: list[str] = []
	for param in op.get("api_params", []):
		param_type, name, _ = _api_param_parts(param)
		compact_type = re.sub(r"\s+", "", param_type)
		const_span = re.fullmatch(r"oa::Span<const(.+)>", compact_type)
		if const_span:
			element_type = const_span.group(1)
			params.append(f"std::vector<{element_type}> {name}")
			args.append(
				f"oa::Span<const {element_type}>({name}.data(), {name}.size())"
			)
		elif compact_type == "oa::Span<oa::Matrix>":
			params.append(f"std::vector<oa::Matrix> {name}")
			args.append(
				f"oa::Span<oa::Matrix>({name}.data(), {name}.size())"
			)
		elif compact_type == "oa::Span<oa::I64>":
			params.append(f"std::vector<oa::I64> {name}")
			args.append(
				f"oa::Span<oa::I64>({name}.data(), {name}.size())"
			)
		else:
			params.append(f"{param_type} {name}")
			args.append(name)
	return ", ".join(params), ", ".join(args)


def _to_camel(name: str) -> str:
	"""Convert PascalCase or UpperCase identifier to camelCase."""
	if not name:
		return name
	return name[0].lower() + name[1:]


def emit_python_binding(namespace: str, op: dict) -> list[str]:
	python = op["python"]
	params, args = _python_binding_params_and_args(op)
	python_name = _to_camel(python.get("name", op["name"]))
	call = f"{namespace}::{op['name']}({args})"
	api_return = op.get("api_return", "oa::Matrix")
	if api_return == "oa::Matrix":
		result = f"matrixPtr({call})"
		owned_result = "matrixPtr(std::move(result))"
	elif api_return == "oa::Image":
		result = f"imagePtr({call})"
		owned_result = "imagePtr(std::move(result))"
	elif api_return == "void":
		result = call
		owned_result = ""
	elif api_return == "oa::Vec<oa::Matrix>":
		result = ""
		owned_result = ""
	else:
		result_type = op.get("python_result", {}).get(
			"cpp_type", api_return
		)
		result = f"new {result_type}({call})"
		owned_result = f"new {result_type}(std::move(result))"
	lines = [
		f'\tm.def("{python_name}", []({params}) {{',
	]
	result_validation = python.get("result_validation")
	if api_return == "oa::Vec<oa::Matrix>":
		lines += [
			f"\t\tauto result = {call};",
			"\t\tnb::list values;",
			"\t\tfor (auto& value : result) {",
			"\t\t\tvalues.append(nb::cast(",
			"\t\t\t\tmatrixPtr(std::move(value)),",
			"\t\t\t\tnb::rv_policy::take_ownership));",
			"\t\t}",
			"\t\treturn values;",
		]
	elif api_return == "void":
		lines.append(f"\t\t{result};")
	elif result_validation is None:
		lines.append(f"\t\treturn {result};")
	else:
		lines.append(f"\t\tauto result = {call};")
		if result_validation == "not_empty":
			invalid = "result.isEmpty()"
		else:
			invalid = "not result.isValid()"
		error = python.get(
			"error",
			f"{op['name']} rejected its input",
		)
		lines += [
			f"\t\tif ({invalid}) {{",
			f"\t\t\tthrow std::runtime_error({json.dumps(error)});",
			"\t\t}",
			f"\t\treturn {owned_result};",
		]
	lines.append("\t},")
	arg_specs = []
	for python_arg, api_param in zip(python["args"], op["api_params"]):
		param_type, _, default = _api_param_parts(api_param)
		spec = f'nb::arg("{_to_camel(python_arg)}")'
		if default is not None:
			if default == "{}":
				typed_default = re.sub(r"\bconst\b", "", param_type)
				typed_default = typed_default.replace("&", "").strip()
				default = f"{typed_default}{{}}"
			spec += f" = {default}"
		arg_specs.append(spec)
	lines.append("\t  " + ", ".join(arg_specs) + ",")
	lines.append("\t  nb::rv_policy::take_ownership,")
	doc = python.get("doc", op.get("notes", ""))
	lines.append(f"\t  {json.dumps(doc, ensure_ascii=True)});")
	lines.append("")
	return lines


def emit_python_bindings(bindings: list[tuple[str, dict]]) -> str:
	bindings = [
		(namespace, op)
		for namespace, op in bindings
		if op["python"].get("binding", "generated") == "generated"
	]
	lines = [
		"// AUTO-GENERATED by tools/fnAutogen/oafnautogen.py — DO NOT EDIT.",
		"// Source of truth: tools/fnAutogen/schema/**.toml.",
		"// Included inside the owning bind function.",
		"",
	]
	result_types: dict[str, dict] = {}
	for _, op in bindings:
		result = op.get("python_result")
		if result is None:
			continue
		cpp_type = result["cpp_type"]
		previous = result_types.get(cpp_type)
		if previous is not None and previous != result:
			fail(
				f"{op['name']}: conflicting Python result descriptors for "
				f"{cpp_type}"
			)
		result_types[cpp_type] = result
	for cpp_type, result in sorted(result_types.items()):
		if not result.get("bind_type", True):
			continue
		python_name = result.get("name", cpp_type.rsplit("::", 1)[-1])
		lines.append(f'\tnb::class_<{cpp_type}>(m, "{python_name}")')
		for index, member in enumerate(result["members"]):
			terminator = ";" if index == len(result["members"]) - 1 else ""
			lines.append(
				f'\t\t.def_ro("{member}", &{cpp_type}::{member}){terminator}'
			)
		lines.append("")
	for namespace, op in sorted(bindings, key=lambda item: item[1]["name"]):
		lines.extend(emit_python_binding(namespace, op))
	return "\n".join(lines).rstrip() + "\n"


def emit_python_surface_inventory(
	bindings: list[tuple[str, str, dict]],
) -> str:
	"""Emit schema-owned C++-parity namespace mappings."""

	grouped: dict[str, dict[str, set[tuple[str, str]]]] = defaultdict(
		lambda: defaultdict(set)
	)
	result_exports: dict[str, dict[str, str]] = defaultdict(dict)
	for domain, namespace, op in bindings:
		python = op["python"]
		native_name = _to_camel(python.get("name", op["name"]))
		family = namespace_leaf(namespace)
		grouped[family][domain.lower()].add((native_name, native_name))
		result = op.get("python_result")
		if result is None or not result.get("bind_type", True):
			continue
		result_name = result.get(
			"name", result["cpp_type"].rsplit("::", 1)[-1]
		)
		previous = result_exports[family].get(result_name)
		if previous is not None and previous != result["cpp_type"]:
			fail(
				f"{family}.{result_name}: conflicting Python result types "
				f"{previous} and {result['cpp_type']}"
			)
		result_exports[family][result_name] = result["cpp_type"]

	lines = [
		"# AUTO-GENERATED by tools/fnAutogen/oafnautogen.py — DO NOT EDIT.",
		"# Source of truth: tools/fnAutogen/schema/**.toml [ops.python].",
		"",
		"SCHEMA_ROOT_EXPORTS = {",
	]
	for namespace, results in sorted(result_exports.items()):
		lines.append(f'\t"{namespace}": (')
		for result_name in sorted(results):
			lines.append(f'\t\t("{result_name}", "{result_name}"),')
		lines.append("\t),")
	lines += [
		"}",
		"",
		"SCHEMA_NAMESPACE_EXPORTS = {",
	]
	for namespace, domains in sorted(grouped.items()):
		lines.append(f'\t"{namespace}": {{')
		for domain, mappings in sorted(domains.items()):
			lines.append(f'\t\t"{domain}": (')
			for native_name, public_name in sorted(mappings):
				lines.append(
					f'\t\t\t("{native_name}", "{public_name}"),'
				)
			lines.append("\t\t),")
		lines.append("\t},")
	lines += [
		"}",
		"",
		'__all__ = ["SCHEMA_NAMESPACE_EXPORTS", "SCHEMA_ROOT_EXPORTS"]',
		"",
	]
	return "\n".join(lines)


def write_python_bindings(
	schema_paths: list[Path], out_root: Path, *, dry_run: bool
) -> None:
	groups: dict[tuple[str, str], list[tuple[str, dict]]] = defaultdict(list)
	surface_bindings: list[tuple[str, str, dict]] = []
	for schema_path in schema_paths:
		with schema_path.open("rb") as file:
			data = tomllib.load(file)
		domain = infer_domain(schema_path)
		namespace = data.get("namespace", DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix"))
		file_prefix = data.get("file_prefix", DOMAIN_FILE_PREFIX.get(domain, "FnMatrix"))
		for op in data.get("ops", []):
			apply_schema_defaults(data, op)
			if "python" in op:
				surface_bindings.append((domain, namespace, op))
				if op["python"].get("binding", "generated") == "generated":
					groups[(domain, file_prefix)].append((namespace, op))

	for (domain, file_prefix), bindings in sorted(groups.items()):
		path = (
			out_root / "py" / domain
			/ f"{camel_file_stem(file_prefix)}Ops.gen.inl"
		)
		if dry_run:
			print(f"  would write: {path}")
			continue
		write_generated_text(path, emit_python_bindings(bindings))

	surface_path = out_root / "py" / "oa" / "_schemaSurface.py"
	if dry_run:
		print(f"  would write: {surface_path}")
	else:
		write_generated_text(
			surface_path,
			emit_python_surface_inventory(surface_bindings),
		)


