def _dispatch_id_arg(op: dict) -> str:
	"""Argument for oavk::Dispatch::Run (string literal or oa::computeKernelId::*)."""
	if "dispatch_id_macro" in op:
		return f"oa::computeKernelId::{op['dispatch_id_macro']}"
	return f'"{op["kernel_forward"]}"'


def _output_alloc_stmt(op: dict, namespace: str = "oa::FnMatrix") -> str:
	"""Return the canonical output-allocation statement for one generated op."""
	out_spec = op.get("output", {})
	shape = out_spec.get("shape", "match_input")
	dtype = out_spec.get("dtype", "match_input")
	kind = op["kind"]
	
	# For nullary ops, we need explicit shape/dtype from extra_params or output spec
	if kind == "nullary_scalar":
		dt_expr = f"oa::ScalarType::{dtype}" if dtype != "match_input" else "oa::ScalarType::Float32"
		# nullary ops must specify shape via extra_params or output.shape
		if shape == "scalar_1d":
			return f"oa::Matrix out = oa::FnMatrix::zeros(oa::MatrixShape{{1}}, {dt_expr});"
		# For Fill, shape comes from extra_params (inShape)
		return f"oa::Matrix out = oa::FnMatrix::empty(inShape, {dt_expr});"
	
	dt_expr = "inA.getDtype()" if dtype == "match_input" else f"oa::ScalarType::{dtype}"
	if shape == "scalar_1d":
		return f"oa::Matrix out = oa::FnMatrix::zeros(oa::MatrixShape{{1}}, {dt_expr});"
	if shape == "last_dim_half":
		scalar_name = op.get("scalar_param", {}).get("name")
		scalar_param = (
			input_param_name(scalar_name)
			if scalar_name else ""
		)
		param_check = (
			f" and static_cast<oa::I64>({scalar_param}) == inA.size(-1) / 2"
			if scalar_name else ""
		)
		return (
			"oa::MatrixShape outShape = inA.getShape();\n"
			f"\tassert(outShape.rank > 0 and inA.size(-1) % 2 == 0{param_check});\n"
			"\toutShape.dims[static_cast<oa::Usize>(outShape.rank - 1)] = inA.size(-1) / 2;\n"
			f"\toa::Matrix out = oa::FnMatrix::empty(outShape, {dt_expr});"
		)
	# default: match input
	return f"oa::Matrix out = oa::FnMatrix::empty(inA.getShape(), {dt_expr});"


def _dispatch_workgroups_expr(op: dict) -> str:
	wg = op.get("dispatch_workgroups", "elemwise")
	if isinstance(wg, int):
		return str(wg)
	if wg == "elemwise":
		return "divCeil(n, 256)"
	if wg == "output_elemwise":
		return "divCeil(static_cast<oa::U32>(out.numElements()), 256)"
	fail(f"{op['name']}: unsupported dispatch_workgroups {wg!r}")
	return "1"  # unreachable


def emit_autograd_attach(
	op: dict, semantic_operation: str | None = None
) -> str:
	"""Emits the forward-attach tail for an op that declares a [ops.autograd] block.

	The block is purely the *attach* — it constructs a hand-written GradXxx
	(from the schema-selected private node catalog) and assigns it to
	out.mutAutograd().gradFn
	when (a) the tape is active and (b) any of the declared inputs requires grad.

	Schema (under [ops.autograd]):
	  grad_class  — name of the concrete *Grad class
	  inputs      — list of parameter names; populates SetGraphInputs in slot order
	  saved       — list of parameter names; populates Saved_ in vector order
	  ctor_args   — list of expressions passed to oa::makeShared<grad_class>(...)

	Returns the empty string when the op has no autograd block.
	"""
	ag = op.get("autograd")
	if not ag or not ag.get("grad_class"):
		return ""
	grad_class = ag["grad_class"]
	inputs     = ag.get("inputs", [])
	saved      = ag.get("saved", [])
	ctor_args  = ag.get("ctor_args", [])
	if not inputs:
		fail(f"{op['name']}: autograd.inputs must be non-empty when grad_class is set")
		return ""
	req_check = " or ".join(f"{i}.requiresGrad()" for i in inputs)
	ctor_call = "(" + ", ".join(ctor_args) + ")" if ctor_args else "()"
	saved_init = "{" + ", ".join(saved) + "}"
	inputs_init = "{" + ", ".join(inputs) + "}"
	semantic_attach = ""
	if semantic_operation is not None:
		semantic_attach = (
			"\t\tconst auto semanticAttached = oa::FnAutograd::attachSemantic(\n"
			f"\t\t\t_gradFn, {semantic_operation});\n"
			"\t\tif (not semanticAttached.isOk()) return {};\n"
		)
	broadcast_operation = ""
	if ag.get("attach") == "broadcast_binary":
		broadcast_operation = (
			f"\t\t_gradFn->op_ = oa::BcastBinOp::{ag['broadcast_op']};\n"
		)
	return (
		f"\tif (oa::FnAutograd::isEnabled() and ({req_check})) {{\n"
		f"\t\tauto _gradFn = oa::makeShared<{grad_class}>{ctor_call};\n"
		f"{broadcast_operation}"
		f"\t\t_gradFn->saveForBackward({saved_init});\n"
		f"\t\t_gradFn->setGraphInputs(oa::Vec<oa::Matrix>{inputs_init});\n"
		f"\t\t_gradFn->sequenceNr_ = oa::FnAutograd::nextSeq();\n"
		f"\t\t_gradFn->outputShape_ = out.getShape();  // tape normalizes upstream d to this; protects elementwise bwd against viewed-shape fan-out grads\n"
		f"{semantic_attach}"
		f"\t\tout.mutAutograd().gradFn = _gradFn;\n"
		f"\t\tout.setRequiresGrad(true);\n"
		f"\t}}\n"
	)


def _semantic_attribute_cpp_values(op: dict) -> list[str]:
	values: list[str] = []
	scalar = op.get("scalar_param")
	for index, attribute in enumerate(semantic_attribute_specs(op)):
		if scalar is not None and index == 0:
			source = input_param_name(scalar["name"])
		else:
			source = attribute.get("source")
			if not source:
				fail(
					f"{op['name']}: generated semantic attribute "
					f"{attribute['name']!r} requires source"
				)
		factory = _ATTRIBUTE_FACTORY_CPP[attribute["kind"]]
		values.append(
			f'oa::OpAttribute::{factory}("{attribute["name"]}", {source})'
		)
	return values


def emit_session_body(op: dict, namespace: str = "oa::FnMatrix") -> str:
	"""Body of the session-recorded function.

	Skipped when body = manual_session (session recorders) or cpu_util
	(host-only utilities) — those bodies are handwritten in a separate .cpp.
	"""
	if op.get("body", "auto") in ("manual_session", "cpu_util"):
		return ""
	name = op["name"]
	body = op.get("body", "auto")
	loss_name = op.get("loss_name")
	name_stmt = f'\tsetLastName("{loss_name}");\n' if namespace == "oa::FnLoss" and loss_name else ""
	if body == "cpp_expr":
		if op.get("cpp_body"):
			body_src = "\n".join(f"\t{line}" if line else "" for line in op["cpp_body"].splitlines())
		else:
			body_src = f"\treturn {op['cpp_expr']};"
		return (
			f"oa::Matrix {namespace}::{name}({cpp_param_list(op, with_defaults=False)}) {{\n"
			f"{name_stmt}"
			f"{body_src}\n"
			f"}}\n"
		)
	immediate = op.get("immediate", {})
	alias = immediate.get("alias_of")
	if alias:
		# Alias path (Neg → Scale(-1))
		return (
			f"oa::Matrix {namespace}::{name}(const oa::Matrix& inA) {{\n"
			f"\treturn scale(inA, {alias['scalar']}f);\n"
			f"}}\n"
		)
	kind = op["kind"]
	push_struct = "struct { oa::U32 count; } push{n};"
	
	# Autograd removed - no longer tracking differentiability
	# Handle bias_add_broadcast special case
	if body == "bias_add_broadcast":
		kind = "binary"
		mats_init = "{&out, &inB}"
		access = "{oa::BufferAccess::ReadWrite, oa::BufferAccess::Read}"
		push_struct = (
			"oa::U32 rows = static_cast<oa::U32>(inA.numElements() / inA.size(-1));\n"
			"\toa::U32 cols = static_cast<oa::U32>(inA.size(-1));\n"
			"\tstruct { oa::U32 rows; oa::U32 cols; } push{rows, cols};"
		)
	elif kind == "binary":
		mats_init = "{&inA, &inB, &out}"
		access = "{oa::BufferAccess::Read, oa::BufferAccess::Read, oa::BufferAccess::Write}"
	elif kind in ("unary", "reduce_full"):
		mats_init = "{&inA, &out}"
		access = "{oa::BufferAccess::Read, oa::BufferAccess::Write}"
	elif kind == "unary_scalar":
		sp = op["scalar_param"]
		push_struct = (
			"struct { oa::U32 count; " + sp["type"] + " " + _to_camel(sp["push_field"])
			+ "; } push{n, " + input_param_name(sp["name"]) + "};"
		)
		mats_init = "{&inA, &out}"
		access = "{oa::BufferAccess::Read, oa::BufferAccess::Write}"
	elif kind == "nullary_scalar":
		sp = op["scalar_param"]
		push_struct = (
			"struct { oa::U32 count; " + sp["type"] + " " + _to_camel(sp["push_field"])
			+ "; } push{n, " + input_param_name(sp["name"]) + "};"
		)
		mats_init = "{&out}"
		access = "{oa::BufferAccess::Write}"
	else:
		# Unsupported kind in autogen body
		return ""
	
	# Opt-in: push extra_params after Count, matching the manual shader's
	# PushConstants field order (schema key: push_extra_params = true).
	# U8 params are widened to oa::U32 — Slang push fields are 4-byte `uint`,
	# and a 1-byte C++ field would leave the shader reading stale padding.
	push_extras = (
		op.get("push_extra_params", False)
		and op.get("extra_params")
		and kind in ("unary", "binary")
	)
	if push_extras:
		fields = "".join(
			f" {'oa::U32' if ep['type'] == 'oa::U8' else ep['type']} {ep['name'][0].lower()}{ep['name'][1:]};"
			for ep in op["extra_params"]
		)
		inits = "".join(
			f", static_cast<oa::U32>({input_param_name(ep['name'])})" if ep["type"] == "oa::U8"
			else f", {input_param_name(ep['name'])}"
			for ep in op["extra_params"]
		)
		push_struct = "struct { oa::U32 count;" + fields + " } push{n" + inits + "};"

	semantic_record = ""
	semantic_operation = None
	if "contract" in op:
		if kind == "binary":
			semantic_inputs = "{&inA, &inB}"
		elif kind in ("unary", "unary_scalar", "reduce_full"):
			semantic_inputs = "{&inA}"
		elif kind == "nullary_scalar":
			semantic_inputs = "{}"
		else:
			fail(f"{name}: unsupported generated semantic operation kind {kind!r}")
		attribute_values = _semantic_attribute_cpp_values(op)
		semantic_attributes = "{" + ", ".join(attribute_values) + "}"
		semantic_record = (
			f"\tconst auto semantic =\n"
			f"\t\tsession.recordOp({operation_registry_reference(namespace, name)}, "
			f"{semantic_inputs}, {{&out}},\n"
			f"\t\t{semantic_attributes});\n"
			"\tif (not semantic.isOk()) return {};\n"
		)
		semantic_operation = "semantic.getValue()"

	# Autograd attach: appended inside the function body, right before `return out;`
	autograd_block = emit_autograd_attach(op, semantic_operation)

	# Mark extra params as unused if we don't consume them
	ignore_extra = "" if push_extras else "".join(
		f"\t(void){input_param_name(ep['name'])};\n" for ep in op.get("extra_params", [])
	)
	out_alloc = _output_alloc_stmt(op, namespace)
	copy_prefix = ""
	if body == "bias_add_broadcast":
		copy_dispatch = (
			",\n\t\t1, 1, "
			f"{operation_registry_reference(namespace, name)}.name, 0,\n\t\t"
			f"{operation_registry_reference(namespace, name)}.hash, "
			f"0, 0, semantic.getValue()"
			if semantic_operation is not None else ""
		)
		copy_prefix = (
			"\tstruct { oa::U32 count; } copyPush{n};\n"
			"\toa::BufferAccess copyAccess[] = {oa::BufferAccess::Read, oa::BufferAccess::Write};\n"
			"\tsession.add(\"Copy\", {&inA, &out}, copyAccess, &copyPush, "
			f"sizeof(copyPush), divCeil(n, 256){copy_dispatch});\n\n"
		)
	workgroups_expr = _dispatch_workgroups_expr(op)
	if body == "bias_add_broadcast":
		workgroups_expr = "divCeil(rows * cols, 256)"
	
	# Kernels dispatched over a shape-changing output must receive that same
	# output element count in their bounds push. Passing the input count here
	# made half-width gated activations (SiluMul/Geglu) write one complete output
	# tensor past their allocation even though their dispatch group count was
	# correctly derived from the output.
	n_expr = (
		"static_cast<oa::U32>(out.numElements())"
		if kind == "nullary_scalar" or op.get("dispatch_workgroups") == "output_elemwise"
		else "static_cast<oa::U32>(inA.numElements())"
	)
	dispatch_identity = (
		",\n\t\t1, 1, "
		f"{operation_registry_reference(namespace, name)}.name, 0,\n\t\t"
		f"{operation_registry_reference(namespace, name)}.hash, "
		f"0, 0, semantic.getValue()"
		if semantic_operation is not None else ""
	)
	
	return (
		f"oa::Matrix {namespace}::{name}({cpp_param_list(op, with_defaults=False)}) {{\n"
		f"\tauto& session = oa::ExecutionSession::getActive();\n"
		f"{ignore_extra}"
		f"\t{out_alloc}\n"
		f"{semantic_record}"
		f"\toa::U32 n = {n_expr};\n"
		f"\n"
		f"{copy_prefix}"
		f"\t{push_struct}\n"
		f"\toa::BufferAccess access[] = {access};\n"
		f'\tsession.add("{op["kernel_forward"]}", {mats_init}, access, &push, sizeof(push), '
		f"{workgroups_expr}{dispatch_identity});\n"
		f"{autograd_block}"
		f"\treturn out;\n"
		f"}}\n"
	)


def selected_autograd_node_header(op: dict, domain: str) -> str:
	node_header = op.get("autograd", {}).get("node_header")
	if node_header:
		return node_header
	fail(
		f"{op.get('name', '<unnamed>')}: {domain} autograd policy must select "
		"an exact autograd.node_header or schema autograd_node_header"
	)


def emit_cpp_file(ops: list[dict], schema_name: str, category: str,
                  domain: str = "Core", namespace: str | None = None) -> str:
	if namespace is None:
		namespace = DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix")
	out: list[str] = []
	out.append(GEN_HEADER.format(schema_name=schema_name))
	out.append(f"// {namespace} — {category} GPU operations.\n")
	out.append("// Unified API: records operations to oa::ExecutionSession.\n\n")
	any_autograd = any(
		op.get("autograd", {}).get("grad_class")
		and op.get("body", "auto") not in ("manual_session", "cpu_util")
		for op in ops
	)
	any_contract = any(
		"contract" in op
		and (
			op.get("body", "auto") not in ("manual_session", "cpu_util")
			or op.get("generate_forwarder", False)
		)
		for op in ops
	)
	if any_autograd:
		node_headers = sorted({
			selected_autograd_node_header(op, domain)
			for op in ops
			if op.get("autograd", {}).get("grad_class")
			and op.get("body", "auto") not in ("manual_session", "cpu_util")
		})
		for node_header in node_headers:
			out.append(f"#include <{node_header}>\n")
	out.append("#include <oa/core/matrix.h>\n")
	out.append("#include <oa/core/fnMatrix.h>\n")
	if any_contract:
		out.append("#include <oa/core/op.h>\n")
	# Public header for the target namespace in this domain, when one exists.
	# Keyed by (domain, namespace) — core/ml/ui all extend FnMatrix but live in
	# different headers.
	ns_header = NAMESPACE_HEADER.get((domain, namespace))
	if ns_header:
		out.append(f"#include <{ns_header}>\n")
	out.append("#include <oa/core/status.h>\n")
	out.append("#include <oa/core/types.h>\n")
	out.append("#include <oa/core/bufferAccess.h>\n")
	out.append("#include <oa/runtime/executionSession.h>\n")
	out.append("#include <oa/core/validation.h>\n\n")
	needs_assert = any(
		op.get("output", {}).get("shape") == "last_dim_half"
		and op.get("body", "auto") not in ("manual_session", "cpu_util")
		for op in ops
	)
	if needs_assert:
		out.append("#include <cassert>\n\n")
	needs_div_ceil = any(
		op.get("body", "auto") not in ("manual_session", "cpu_util", "cpp_expr")
		for op in ops
	)
	if needs_div_ceil:
		out.append("static oa::U32 divCeil(oa::U32 inA, oa::U32 inB) { return (inA + inB - 1) / inB; }\n\n")
	for op in ops:
		# Manual implementations can still generate their mechanical active-context
		# forwarding overload. Validation/dispatch/composition remains hand-written.
		body = emit_manual_forwarder(op, namespace)
		if not body:
			body = emit_session_body(op, namespace)
		if body:
			hdr = f"// ─── {op['name']} ({op.get('notes', '').rstrip('.')}) " + "─" * 4
			out.append(hdr[:78].rstrip() + "\n\n")
			out.append(body + "\n")
	# Generated translation units have exactly one final newline. In particular,
	# all-manual schemas must not accumulate a second blank line at EOF.
	return "".join(out).rstrip() + "\n"


