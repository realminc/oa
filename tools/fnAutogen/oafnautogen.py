def _emit_autograd_backward_body(op: dict) -> str | None:
	"""Generate the backward() body for an op based on its formula field.
	Returns None for 'manual' or unsupported formulas."""
	ag = op.get("autograd", {})
	formula = ag.get("formula", "manual")
	if formula == "manual":
		return None

	# Determine scalar member name from ctor_args.
	ctor_args = ag.get("ctor_args", [])
	scalar_member = ""
	if ctor_args:
		# inScalar -> scalar_, inExponent -> exponent_, etc.
		arg = ctor_args[0]
		if arg.startswith("in") and len(arg) > 2 and arg[2].isupper():
			scalar_member = arg[2].lower() + arg[3:] + "_"
		else:
			scalar_member = arg + "_"

	B = "\t\t"  # two tabs: inside class, inside backward()
	body = ""
	if formula == "auto_binary_add":
		body = (
			f"{B}if (outDIn.size() > 0) outDIn[0] = inDOut;\n"
			f"{B}if (outDIn.size() > 1) outDIn[1] = inDOut;\n"
		)
	elif formula == "auto_binary_sub":
		body = (
			f"{B}if (outDIn.size() > 0) outDIn[0] = inDOut;\n"
			f"{B}if (outDIn.size() > 1) outDIn[1] = oa::FnMatrix::scale(inDOut, -1.0f);\n"
		)
	elif formula == "auto_binary_mul":
		body = (
			f"{B}const oa::Matrix& a = saved(0);\n"
			f"{B}const oa::Matrix& b = saved(1);\n"
			f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::mul(inDOut, b);\n"
			f"{B}if (outDIn.size() > 1) outDIn[1] = oa::FnMatrix::mul(inDOut, a);\n"
		)
	elif formula == "auto_unary_identity":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = inDOut;\n"
	elif formula == "auto_unary_neg":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::scale(inDOut, -1.0f);\n"
	elif formula == "auto_unary_log":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::div(inDOut, saved(0));\n"
	elif formula == "auto_unary_sqrt":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::div(inDOut, oa::FnMatrix::scale(saved(0), 2.0f));\n"
	elif formula == "auto_unary_exp":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::mul(inDOut, saved(0));\n"
	elif formula == "auto_unary_sin":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::mul(inDOut, oa::FnMatrix::cos(saved(0)));\n"
	elif formula == "auto_unary_cos":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::scale(oa::FnMatrix::mul(inDOut, oa::FnMatrix::sin(saved(0))), -1.0f);\n"
	elif formula == "auto_unary_reciprocal":
		body = (
			f"{B}if (outDIn.size() > 0) {{\n"
			f"{B}\tconst oa::Matrix& out = saved(0);\n"
			f"{B}\toutDIn[0] = oa::FnMatrix::scale(oa::FnMatrix::mul(inDOut, oa::FnMatrix::mul(out, out)), -1.0f);\n"
			f"{B}}}\n"
		)
	elif formula == "auto_unary_scalar_identity":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = inDOut;\n"
	elif formula == "auto_unary_scalar_scale":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::scale(inDOut, {scalar_member});\n"
	elif formula == "auto_unary_scalar_div_scalar":
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::scale(inDOut, 1.0f / {scalar_member});\n"
	elif formula == "auto_unary_scalar_pow":
		body = (
			f"{B}if (outDIn.size() > 0) {{\n"
			f"{B}\tconst oa::Matrix& x = saved(0);\n"
			f"{B}\tauto dPow = oa::FnMatrix::pow(x, {scalar_member} - 1.0f);\n"
			f"{B}\toutDIn[0] = oa::FnMatrix::scale(oa::FnMatrix::mul(inDOut, dPow), {scalar_member});\n"
			f"{B}}}\n"
		)
	elif formula == "auto_bwd_kernel":
		bwd_name = op["name"] + "Bwd"
		# Thread the saved scalar hyperparam (e.g. LeakyRelu/Elu alpha) into the
		# backward kernel. Without this the *Bwd call falls back to its defaulted
		# alpha, so a non-default alpha silently produces wrong input gradients.
		# scalar_member is non-empty only when the autograd block declares ctor_args.
		extra = f", {scalar_member}" if scalar_member else ""
		body = f"{B}if (outDIn.size() > 0) outDIn[0] = oa::FnMatrix::{bwd_name}(saved(0), inDOut{extra});\n"
	else:
		return None
	return body


def emit_autograd_class(op: dict) -> str:
	"""Emit a concrete GradNode subclass for one operation.
	Generates a full backward() body when formula is auto-*. Manual gradient
	classes live in hand-written Autograd*.h files and deliberately emit
	nothing here; a generated file containing only "hand-written elsewhere"
	comments is not an API surface and must not exist."""
	ag = op.get("autograd", {})
	if not ag or not ag.get("grad_class"):
		return ""
	name = op["name"]
	qualified_grad_class = ag["grad_class"]
	grad_class = qualified_grad_class.removeprefix("oa::")

	# Scalar member lines
	scalar_decls = ""
	scalar_ctor = ""
	if ag.get("ctor_args"):
		# Emit ctor with typed args + member initialization
		# Derive the member name from a constructor argument (inScalar -> scalar_).
		ctor_args = ag["ctor_args"]
		params = []
		inits = []
		members = []
		for arg in ctor_args:
			# Heuristic: arg like "inScalar" -> member "scalar_"
			if arg.startswith("in") and len(arg) > 2 and arg[2].isupper():
				member = arg[2].lower() + arg[3:] + "_"
			else:
				member = arg + "_"
			params.append(f"oa::F32 {arg}")
			inits.append(f"{member}({arg})")
			members.append(f"\toa::F32 {member};")
		scalar_ctor = (
			f"\texplicit {grad_class}({', '.join(params)}) noexcept "
			f": {', '.join(inits)} {{}}\n"
		)
		scalar_decls = "\n".join(members) + "\n"

	body = _emit_autograd_backward_body(op)
	if body is None:
		return ""

	# Auto-generated full class with Backward body
	return (
		f"class {grad_class} final : public oa::GradNode {{\n"
		f"public:\n"
		f"{scalar_ctor}"
		f"\tvoid backward(const oa::Matrix& inDOut, oa::Vec<oa::Matrix>& outDIn) override {{\n"
		f"{body}"
		f"\t}}\n"
		f"{scalar_decls}"
		f"}};\n"
	)


