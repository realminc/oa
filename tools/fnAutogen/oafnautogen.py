def validate_schema_set(schema_paths: list[Path]) -> None:
	"""Reject duplicate semantic identities across separate schema files."""
	seen: dict[tuple[str, str], Path] = {}
	for schema_path in schema_paths:
		with schema_path.open("rb") as file:
			data = tomllib.load(file)
		domain = infer_domain(schema_path)
		namespace = data.get("namespace", DOMAIN_NAMESPACE.get(domain, "oa::FnMatrix"))
		for op in data.get("ops", []):
			name = op.get("name", "")
			key = (namespace, name)
			if key in seen:
				fail(
					f"duplicate operation identity {namespace}::{name}: "
					f"{seen[key]} and {schema_path}"
				)
			seen[key] = schema_path


# ─── Manual-lowering autograd attachment emission ──────────────────────────

def _manual_autograd_attach_contract(
	op: dict,
) -> tuple[str, str, str]:
	ag = op["autograd"]
	inputs = ag["inputs"]
	saved = ag.get("saved", [])
	# Saved tensors are not necessarily differentiable graph inputs. Losses, for
	# example, differentiate logits while retaining integer targets for backward.
	# Pass every saved-only tensor to the generated helper, but keep requires-grad
	# checks and graph edges restricted to the schema's `inputs` list. `Out`/`out`
	# already names the helper's output parameter and needs no second declaration.
	saved_parameters = []
	for name in saved:
		if name in inputs or name in ("Out", "out") or name in saved_parameters:
			continue
		saved_parameters.append(name)
	state = ag.get("state", [])
	param_declarations = (
		["oa::Matrix& out"]
		+ [f"const oa::Matrix& {name}" for name in inputs]
		+ [f"const oa::Matrix& {name}" for name in saved_parameters]
		+ [f"{item['type']} {item['source']}" for item in state]
		+ ["oa::U32 inSemanticOp"]
	)
	param_names = (
		["out"]
		+ inputs
		+ saved_parameters
		+ [item["source"] for item in state]
		+ ["inSemanticOp"]
	)
	requires_grad = " or ".join(f"{name}.requiresGrad()" for name in inputs)
	conditions = ["oa::FnAutograd::isEnabled()", f"({requires_grad})"]
	for name, rank in zip(inputs, ag.get("input_ranks", [])):
		conditions.append(f"{name}.rank() == {rank}")
	return (
		", ".join(param_declarations),
		", ".join(param_names),
		" and ".join(conditions),
	)


def _emit_manual_autograd_attach_declaration(op: dict) -> list[str]:
	params, _, _ = _manual_autograd_attach_contract(op)
	return [f"oa::Status {op['name']}Enabled({params});"]


def _emit_manual_autograd_attach_wrapper(
	op: dict, namespace: str
) -> list[str]:
	params, args, condition = _manual_autograd_attach_contract(op)
	return [
		f"inline oa::Status {op['name']}({params}) {{",
		f"\tif (not ({condition})) return oa::Status::ok();",
		f"\treturn detail::{namespace}::{op['name']}Enabled({args});",
		"}",
		"",
	]


def _emit_manual_autograd_attach_definition(op: dict) -> list[str]:
	ag = op["autograd"]
	inputs = ag["inputs"]
	optional_indices = op.get("contract", {}).get("optional_inputs", [])
	optional_inputs = [
		inputs[index]
		for index in optional_indices
		if index < len(inputs)
	]
	saved = ag.get("saved", [])
	saved_expressions = ["out" if name in ("Out", "out") else name for name in saved]
	state = ag.get("state", [])
	grad_class = ag["grad_class"]
	params, _, _ = _manual_autograd_attach_contract(op)
	inputs_init = "{" + ", ".join(inputs) + "}"
	saved_init = "{" + ", ".join(saved_expressions) + "}"
	lines = [
		f"oa::Status {op['name']}Enabled({params}) {{",
	]
	if ag["attach"] == "broadcast_binary":
		lines += [
			f"\tif ({inputs[0]}.getShape() != {inputs[1]}.getShape()) {{",
			"\t\tauto gradFn = oa::makeShared<oa::GradBcastBinary>();",
			f"\t\tgradFn->op_ = oa::BcastBinOp::{ag['broadcast_op']};",
			f"\t\tgradFn->saveForBackward({inputs_init});",
			f"\t\tgradFn->setGraphInputs(oa::Vec<oa::Matrix>{inputs_init});",
			"\t\tgradFn->sequenceNr_ = oa::FnAutograd::nextSeq();",
			"\t\tgradFn->outputShape_ = out.getShape();",
			"\t\tOA_RETURN_IF_ERROR(oa::FnAutograd::attachSemantic(gradFn, inSemanticOp));",
			"\t\tout.mutAutograd().gradFn = gradFn;",
			"\t\treturn oa::Status::ok();",
			"\t}",
		]
	lines += [
		f"\tauto gradFn = oa::makeShared<{grad_class}>();",
		f"\tgradFn->saveForBackward({saved_init});",
	]
	if optional_inputs:
		optional_set = set(optional_inputs)
		# An absent optional semantic input is not an autograd edge. This keeps
		# the tape arity honest (Linear without bias is the first contract) and
		# prevents backward from manufacturing a gradient for an absent value.
		lines.append("\toa::Vec<oa::Matrix> graphInputs;")
		for name in inputs:
			if name in optional_set:
				lines.append(
					f"\tif (not {name}.isEmpty()) graphInputs.pushBack({name});"
				)
			else:
				lines.append(f"\tgraphInputs.pushBack({name});")
		lines.append("\tgradFn->setGraphInputs(std::move(graphInputs));")
	else:
		lines.append(
			f"\tgradFn->setGraphInputs(oa::Vec<oa::Matrix>{inputs_init});"
		)
	lines.append("\tgradFn->sequenceNr_ = oa::FnAutograd::nextSeq();")
	lines += [
		f"\tgradFn->{item['member']} = {item['source']};" for item in state
	]
	if ag.get("output_shape", False):
		lines.append("\tgradFn->outputShape_ = out.getShape();")
	lines += [
		"\tOA_RETURN_IF_ERROR(oa::FnAutograd::attachSemantic(gradFn, inSemanticOp));",
		"\tout.mutAutograd().gradFn = gradFn;",
		"\treturn oa::Status::ok();",
		"}",
		"",
	]
	return lines


